// Birthday props bench (task T1, engine/page/props-birthday.js): never-has-money/gunslinger (castLook "sheet") holds the
// FREE HUG coupon and wears the striped party hat on his cowboy hat's crown; never-has-money/viking wears the dotted hat
// on his hair and the rosette on his chest. Not a clip: stills only (no reviews).
//   node storyboards/lookdev/make-birthday-bench.mjs
//   node engine/render.mjs storyboards/lookdev/birthday-bench.json --stills 0.25,0.75,1.25,1.75,2.25,2.75 --draft --safe --out out/birthday-bench
import { clip, write, r3, frame } from "../lib/clip.mjs";
import * as grips from "../lib/grips.mjs";

const c = clip(), { A } = c;
const GSL = [-0.62, 0], VIK = [0.62, 0];
// the wear points (body frame: x to the wearer's left, y up, z out of the front), settled in this bench
const WEAR = {
  stripes: { x: 0.12, y: 1.265, z: -0.08, tilt: 12, pitch: 0 },
  dots: { x: -0.11, y: 1.27, z: 0.03, tilt: -10, pitch: 0 },
  rosette: { x: 0.24, y: 0.52, z: 0.34 },
};
// the coupon as the clip holds it (scale 1.75), at chest height in front of him, facing the camera
const CP_K = 1.75, SHOW = [r3(GSL[0] + 0.02), 0.55, r3(GSL[1] + 0.5)];
const CP = { id: "coupon", kind: "coupon", seed: 5, ink: +(process.env.INK ?? 1), scale: CP_K, ...grips.placeFor("coupon", SHOW, 0) };

const cast = [
  { id: "gsl", character: "never-has-money/gunslinger", at: GSL, face: 0, expr: "happy", follow: 0, seed: 1.3 },
  { id: "vik", character: "never-has-money/viking", at: VIK, face: 0, expr: "delighted", follow: 0, seed: 4.1 },
];
const props = [
  { id: "floor", kind: "plankfloor", x: 0, z: 0.4, w: 7, d: 6 },
  CP,
  { id: "hatG", kind: "partyhat", wear: "gsl", pattern: "stripes", ...WEAR.stripes },
  { id: "hatV", kind: "partyhat", wear: "vik", pattern: "dots", ...WEAR.dots },
  { id: "rosette", kind: "rosette", wear: "vik", ...WEAR.rosette },
];

// the hold: the right mitten on the coupon's edge from frame 0 (grips.phone, side R)
const h = grips.phone(c, "gsl", CP, { side: "R" });
c.arm(0, "gsl", "R", { prop: "coupon", grip: h.hands.R.grip, palm: true }, 0);
A(0, "gsl", "grip", { side: "R", shape: "hold", dur: 0 });
A(0, "gsl", "grab", { prop: "coupon", hand: "R", grip: h.hands.R.grip, dur: 0, pose: null });
A(0, "gsl", "look", { to: [0, 0.05], dur: 0, blink: false });
A(0, "vik", "look", { to: [0, 0.05], dur: 0, blink: false });

// one shot per 0.5 s; the stills are taken 0.25 s into each
const cw = 0.36 * CP_K / 0.45, cpt = [CP.x, CP.y, CP.z];   // the frame's width when the coupon fills 45 %
const SH = [
  ["coupon close", frame(cpt, { az: 0, h: cw * 16 / 9, fov: 20 })],
  ["gunslinger front", frame([GSL[0], 0.7, 0], { az: 0, h: 2.4, fov: 20 })],
  ["gunslinger 3/4", frame([GSL[0], 0.7, 0], { az: 40, h: 2.4, fov: 20 })],
  ["viking front", frame([VIK[0], 0.7, 0], { az: 0, h: 2.4, fov: 20 })],
  ["viking 3/4", frame([VIK[0], 0.7, 0], { az: -40, h: 2.4, fov: 20 })],
  ["both", frame([0, 0.8, 0], { az: 0, h: 3.2, fov: 20 })],
  ["gunslinger hat close", frame([GSL[0] + 0.05, 1.3, 0], { az: 0, h: 0.9, fov: 20 })],
  ["gunslinger hat 3/4", frame([GSL[0] + 0.05, 1.3, 0], { az: 35, h: 0.9, fov: 20 })],
  ["viking hat close", frame([VIK[0], 1.25, 0], { az: 0, h: 0.9, fov: 20 })],
  ["viking hat 3/4", frame([VIK[0], 1.25, 0], { az: -35, h: 0.9, fov: 20 })],
  ["rosette close", frame([VIK[0] + 0.25, 0.52, 0.3], { az: 0, h: 0.7, fov: 20 })],
  ["rosette 3/4", frame([VIK[0] + 0.25, 0.52, 0.3], { az: -35, h: 0.7, fov: 20 })],
];
const end = SH.length * 0.5;
c.cap(0, end, "birthday props bench", 1500, false, { kinetic: false });
write(import.meta.url, {
  id: `birthday-bench${process.env.INK ? "-ink" + process.env.INK : ""}`, title: "Birthday props bench", idea: "Birthday props bench (T1), not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false,
  set: { type: "plain", color: "#e9d2a8", floor: "#c9955a", light: "golden", para: 0, bloom: "emissive", aperture: 0, lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 } },
  music: false, sound: { auto: false },
  hook: { show: ["gsl", "vik"], hint: 0, what: "engine test" },
  cast, props, captions: c.captions, beats: c.beats(SH.map(([n, s], i) => [n, i * 0.5, s]), end),
  notes: "Generated by storyboards/lookdev/make-birthday-bench.mjs (props bench, no reviews).",
});

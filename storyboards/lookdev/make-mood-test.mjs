// Mood test: the full-strength reactions and the emotion word (acting.mjs mood + emote), Jonny's notes of 29 Oct
// ("the wizard should look a bit more angry and annoyed", an "annoyed" caption over Reaper). 0-1.2 resting face,
// 1.2 the old medium stern face (as clips wrote it before), 2.6 annoyed at full strength with the word, 4.2 angry.
//   node storyboards/lookdev/make-mood-test.mjs && node engine/render.mjs storyboards/lookdev/mood-test.json
import { clip, write } from "../lib/clip.mjs";
import * as act from "../lib/acting.mjs";

const c = clip(), { A } = c;
const END = 6.0, AT_CAM = [0, 0];
const cast = [{ id: "wiz", character: "halloween/wizard-host", at: [0, 0.3], face: "camera", expr: "kind", follow: 0.3, seed: 2.6 }];

act.blinksAt(c, "wiz", [0.6]);
A(0, "wiz", "look", { to: AT_CAM, dur: 0.01, blink: false });
A(1.2, "wiz", "expr", { expr: "stern", dur: 0.25 });                       // before: the medium face clips used
A(1.2, "wiz", "still", { dur: 1.2, idle: 0.06 });
c.textPop(1.25, "wiz", "before", { dur: 1.1, size: 70, dx: 0, dy: -0.8, angle: 0, color: "#ffffff" });
act.mood(c, 2.6, "wiz", "annoyed", { word: "annoyed", hold: 1.3 });
act.mood(c, 4.2, "wiz", "angry", { word: "angry", hold: 1.4 });

const MED = { pos: [0, 1.0, 4.2], look: [0, 0.82, 0], fov: 32 };
const beats = c.beats([["rest", 0, MED], ["before", 1.2, "keep"], ["annoyed", 2.6, "keep"], ["angry", 4.2, "keep"]], END);

write(import.meta.url, {
  id: "mood-test", title: "Mood test", idea: "Full-strength annoyed and angry faces with an emotion word",
  fps: 30, look: "anime-pro", profile: "short", loop: false, captionStyle: "kinetic",
  set: { type: "apartment", seed: 5 }, music: false, sound: { auto: false },
  hook: { show: ["wiz"], hint: 0, what: "engine test" },
  cast, props: [], captions: c.captions, beats,
  notes: "Generated by storyboards/lookdev/make-mood-test.mjs (engine test, no reviews).",
});

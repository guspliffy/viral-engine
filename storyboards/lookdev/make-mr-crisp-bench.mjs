// Mr. Crisp bench (task T3, 11 Nov 2026): the evil clown potato host (characters/hot-potato/mr-crisp.json, costume type
// "clown", engine/page/costumes-clown.js) on a plain set. Not a clip: a lookdev check judged from draft stills.
//   0.5 front, 1.5 three-quarter, 2.5 side, 3.5 rear (full body)
//   4.5 evil grin (his resting face), 5.5 delighted (TV smile), 6.5 furious (angry + teeth), 7.5 laugh: waist up from slightly below
//   8.0 - 9.0 both arms from rest to the gloves in front of the chest, 1 s (the every-frame strip), 9.8 rubbing pose held
//   10.5 next to potatobrawl/spud, for size
//   node storyboards/lookdev/make-mr-crisp-bench.mjs
//   node engine/render.mjs storyboards/lookdev/mr-crisp-bench.json --stills 0.5,1.5,2.5,3.5,4.5,5.5,6.5,7.5,9.8,10.5 --draft --safe
//   node engine/render.mjs storyboards/lookdev/mr-crisp-bench.json --stills 8.0,8.033,...(30 fps to 9.0) --draft --safe   (the strip)
//   node engine/render.mjs storyboards/lookdev/mr-crisp-bench-ink.json --stills 4.5,0.5 --draft --safe   (the clip template's ink lines on)
//   node qa/contact.mjs out/mr-crisp-bench-*-t*.png --out out/mr-crisp-bench.png
import { clip, write, frame } from "../lib/clip.mjs";

const END = 11.2, X = { front: -4.5, q3: -3, side: -1.5, rear: 0, evil: 1.5, delighted: 3, furious: 4.5, laugh: 6, rub: 7.5, size: 9.4 };
const FULL = (x) => frame([x, 0.7, 0], { az: 0, el: 2, h: 2.3, fov: 30 });
const BUST = (x) => frame([x, 0.8, 0.2], { az: 0, el: -8, h: 1.6, fov: 30 });

function build(id, ink) {
  const c = clip(), { A } = c;
  const who = (n, x, o = {}) => ({ id: n, character: "hot-potato/mr-crisp", at: [x, 0], face: 0, follow: 0.3, seed: 3.1, ...o });
  const cast = [
    who("cF", X.front), who("c3", X.q3, { face: -35 }), who("cS", X.side, { face: -90 }), who("cR", X.rear, { face: 180 }),
    who("cE", X.evil), who("cD", X.delighted, { expr: "delighted" }), who("cG", X.furious, { expr: "angry" }), who("cL", X.laugh, { expr: "delighted" }),
    who("cA", X.rub), who("cB", X.size, { face: -10 }),
    { id: "spud", character: "potatobrawl/spud", at: [X.size + 1.0, 0], face: 10, expr: "kind", follow: 0.3, seed: 2.9 },
  ];
  // the four faces (the clip uses the stock names on top of the resting evil grin; the lids are a control of their own)
  A(0, "cD", "face", { lid: 0.05, dur: 0.01 });
  A(0, "cG", "expr", { expr: "angry", set: { open: 0.55, curve: -0.2 }, dur: 0.01 }); A(0, "cG", "face", { lid: 0.3, dur: 0.01 });
  A(0, "cL", "expr", { expr: "delighted", set: { open: 1.0, curve: 1.0, wide: 0.35 }, dur: 0.01 }); A(0, "cL", "face", { lid: 1, dur: 0.01 });
  // both arms from rest to the gloves in front of the chest, 1 s; held
  const meet = (s) => ({ x: [s === "R" ? -0.07 : 0.07, 0.3, 0.62] });
  c.arm(8.0, "cA", "R", meet("R"), 1.0, "inOut"); c.arm(8.0, "cA", "L", meet("L"), 1.0, "inOut");
  const beats = c.beats([
    ["front", 0, FULL(X.front)], ["three-quarter", 1, FULL(X.q3)], ["side", 2, FULL(X.side)], ["rear", 3, FULL(X.rear)],
    ["evil grin", 4, BUST(X.evil)], ["delighted", 5, BUST(X.delighted)], ["furious", 6, BUST(X.furious)], ["laugh", 7, BUST(X.laugh)],
    ["arm move", 8, BUST(X.rub)], ["gloves in front", 9.5, BUST(X.rub)],
    ["next to Spud", 10.2, frame([X.size + 0.5, 0.75, 0], { az: 0, el: 2, h: 3.4, fov: 30 })],
  ], END);
  write(import.meta.url, {
    id, title: "Mr. Crisp bench", idea: "Lookdev bench (task T3), not a clip: the evil clown potato host, his costume and four faces",
    fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", cleanStart: true,
    motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: true,
    set: { type: "plain", color: "#8fc4ee", floor: "#4a4350", para: 0, bloom: "emissive", key: [0.6, 6.5, 4.0], aperture: 0, lighting: 2, hatch: { boil: 0.25 }, ...(ink && { cel: { at: 0.25 }, ink: true, satsuei: true }) },
    music: false, sound: { auto: false }, hook: { show: ["cF"], hint: 0, what: "lookdev bench" },
    cast, props: [], captions: c.captions, beats,
    notes: "Generated by storyboards/lookdev/make-mr-crisp-bench.mjs (lookdev bench, no reviews).",
  });
}
build("mr-crisp-bench", false);
build("mr-crisp-bench-ink", true);

// Engine test for follow-through (timeline.js st.ft): the Wizard's hat and sprout and Phoenix's crest trailing a walk,
// a stop, hops and turns. Render it twice (as is, and with followThrough: false via
// --no-ft) for a before/after. Pure engine test: no creative review.
//   node storyboards/lookdev/make-follow-through-test.mjs [--no-ft]
import { clip, write } from "../lib/clip.mjs";

const OFF = process.argv.includes("--no-ft");
const c = clip(), { A } = c;
const END = 7.0;

const WIZ = [-0.7, 0.3], PHX = [0.95, 0.3];
const cast = [
  { id: "wiz", character: "potatobrawl/wizard", at: WIZ, face: "camera", seed: 1.3 },
  { id: "phx", character: "potatobrawl/phoenix", at: PHX, face: "camera", seed: 2.1 },
];
for (const m of cast) { A(0, m.id, "noblink"); A(0, m.id, "look", { to: [0, 0], dur: 0.01, blink: false }); }

// a walk across and a sharp stop
A(0.4, "wiz", "move", { to: [0.0, 0.3], dur: 0.5, ease: "inOut", steps: 2 });
A(0.4, "phx", "move", { to: [1.25, 0.3], dur: 0.5, ease: "inOut", steps: 2 });
// quick turns away and back
A(2.0, "wiz", "turn", { to: "3q-left", dur: 0.25 });
A(2.8, "wiz", "turn", { to: "camera", dur: 0.25 });
// hops
A(3.7, "phx", "hop", { count: 2, height: 0.25, dur: 0.9 });
A(3.9, "wiz", "hop", { count: 1, height: 0.22, dur: 0.5 });
// back to the start
A(5.2, "wiz", "move", { to: WIZ, dur: 0.6, ease: "inOut", steps: 2 });
A(5.2, "phx", "move", { to: PHX, dur: 0.6, ease: "inOut", steps: 2 });

const SHOT = { pos: [0.2, 1.2, 6.2], look: [0.2, 0.7, -0.6], fov: 40 };
write(import.meta.url, {
  id: OFF ? "follow-through-test-off" : "follow-through-test",
  title: "Follow-through test",
  idea: "Engine test: soft parts trail the body",
  fps: 30, look: "anime-pro", profile: "short",
  set: { type: "apartment", seed: 5 },
  music: false, sound: { sfx: 0.5, ambience: 0.3 },
  ...(OFF && { followThrough: false }),
  cast, props: [], captions: [], beats: c.beats([["test", 0, SHOT]], END),
  notes: "Generated by storyboards/lookdev/make-follow-through-test.mjs (engine test).",
});

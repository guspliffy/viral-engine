// The friends rig's diagnostic fixtures (rigs/friends.js; reference pack in references/friends-v1/). Not clips:
// short look-dev storyboards for the reference boards and movement/grip previews.
//
//   node storyboards/lookdev/friends/make-friends-tests.mjs        -> storyboards/lookdev/friends/*.json
//   node engine/render.mjs storyboards/lookdev/friends/friends-turn-rusty.json --stills 0.5,1.5,2.5,3.5,4.5,5.5
import { writeFileSync } from "node:fs";

const OUT = new URL("./", import.meta.url);
const WHO = { rusty: { h: 1.2 }, pip: { h: 1.344 }, moss: { h: 1.104 } };
// the template's look (storyboards/templates/clip-template.mjs): sheet cast look, light 2, whole frame sharp
const LOOK = { look: "anime-pro", castLook: "sheet", rig: { hand: 2, eyes: 2 }, motion: { feet: 2 } };
const SETS = {
  neutral: { type: "plain", color: "#ece6dc", floor: "#d9cfc0", aperture: 0 },
  room: { type: "plain", color: "#efe2c8", floor: "#c9a27a", light: "golden", para: 0, bloom: "emissive", plate: { src: "assets/plates/livingroom-golden.png", z: -2.3, center: [0.3, 1.7], height: 6.4 }, aperture: 0, lighting: 2 },
};
const base = (id, title, set, extra = {}) => ({ id, title, idea: "Friends rig look-dev fixture, not a clip", fps: 30, ...LOOK, profile: "short", loop: false, set: SETS[set], music: false, sound: { auto: false }, hook: { show: [], hint: 0, what: "engine test" }, props: [], captions: [], notes: "Generated by make-friends-tests.mjs", ...extra });
const write = (sb) => { writeFileSync(new URL(`${sb.id}.json`, OUT), JSON.stringify(sb, null, 1)); console.log("wrote", sb.id); };

// a turnaround: the character stands still, the camera orbits it (front, its left three-quarter, its left profile,
// back, its right three-quarter, its right profile), one second each
const ORBIT = [["front", 0], ["3q-left", 45], ["profile-left", 90], ["back", 180], ["3q-right", -45], ["profile-right", -90]];
function turn(name, set = "neutral") {
  const H = WHO[name].h, D = 3.1, look = [0, H * 0.52, 0];
  const beats = ORBIT.map(([n, a], i) => { const r = (a * Math.PI) / 180; return { name: n, at: i, len: 1, shot: { pos: [+(Math.sin(r) * D).toFixed(3), +(H * 0.62).toFixed(3), +(Math.cos(r) * D).toFixed(3)], look, fov: 30 }, do: i ? [] : [{ who: name, do: "noblink", at: 0 }] }; });
  return base(`friends-turn-${name}${set === "neutral" ? "" : `-${set}`}`, `${name} turnaround`, set, { cast: [{ id: name, character: `friends/${name}`, at: [0, 0], face: 0, expr: "kind", follow: 0 }], beats, duration: ORBIT.length });
}
for (const n of Object.keys(WHO)) { write(turn(n)); write(turn(n, "room")); }

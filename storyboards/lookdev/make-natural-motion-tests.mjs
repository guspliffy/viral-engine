// Engine test for natural motion (movement study, 31 Oct 2026; util.js naturalOf, storyboard "motion"): three short
// benches, each written twice, today's motion and "motion": "natural", with nothing else different, for a side by side
// with a close-up crop. Pure engine test: no creative review.
//   node storyboards/lookdev/make-natural-motion-tests.mjs
//   node engine/render.mjs storyboards/lookdev/motion/walk-today.json   (and walk-natural, reach-*, everyday-*)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip } from "../lib/clip.mjs";
import * as grips from "../lib/grips.mjs";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "motion");
const base = (id, title, cast, props, beats) => ({
  id, title, idea: "Engine test: natural motion, not a clip",
  fps: 30, look: "anime-pro", castLook: "golden", profile: "short", loop: false,
  set: { type: "livingroom", seed: 5, focus: false },
  music: false, sound: { sfx: 0.6, ambience: 0.3 },
  hook: { show: cast.map((m) => m.id), hint: 0, what: "engine test" },
  cast, props, captions: [], beats,
  notes: "Generated by storyboards/lookdev/make-natural-motion-tests.mjs (engine test).",
});
function write(sb) {
  for (const v of ["today", "natural"]) {
    const out = { ...sb, id: `${sb.id}-${v}`, ...(v === "natural" && { motion: "natural" }) };
    out.captions = [{ from: 0, to: sb.duration ?? 99, text: v === "natural" ? "NATURAL MOTION" : "TODAY", pos: 1500, pop: false, kinetic: false }];
    fs.writeFileSync(path.join(OUT, `${sb.id}-${v}.json`), JSON.stringify(out, null, 1) + "\n");
  }
}

// 1. WALK: Phoenix turns, walks across and stops, turns back (the feet, bob, weight shift, lean and arm swing)
{
  const c = clip(), { A } = c, END = 4.6;
  A(0, "phx", "noblink");
  A(0.25, "phx", "turn", { to: "right", dur: 0.35 });
  A(0.7, "phx", "move", { to: [0.6, 0.1], dur: 1.9, steps: 2.2 });
  A(2.95, "phx", "turn", { to: "camera", dur: 0.35 });
  A(3.5, "phx", "look", { to: [0, 0], dur: 0.2, blink: false });
  const SHOT = { pos: [0, 0.75, 6.6], look: [0, 0.5, 0], fov: 40 };
  const cast = [{ id: "phx", character: "duo/phoenix", at: [-0.6, 0.1], face: "camera", expr: "kind", follow: 0.3, seed: 1.7, span: 0 }];
  write({ ...base("walk", "Natural motion: walk", cast, [], c.beats([["walk", 0, SHOT]], END)), duration: END });
}

// 2. REACH, PICK UP, LIFT TO DRINK: the Wizard takes a mug off the table, lifts it, tips it for a sip, puts it back
//    (arcs, the body leading the reach, the grip landing exactly where the grip library puts it)
{
  const c = clip(), { A } = c, END = 5.4;
  const MUG = { id: "it", kind: "campmug", scale: 1.9, x: -0.13, y: 0.36, z: 0.42, rot: 55 };
  const h = grips.mug(c, "wiz", MUG, { side: "R" });
  A(0, "wiz", "noblink");
  A(0, "wiz", "look", { to: [0, 0], dur: 0.01, blink: false });
  A(0.3, "wiz", "look", { to: [0.1, -0.8], dur: 0.2, blink: false });   // eyes go to the mug first
  let t = h.take(0.45);
  t = h.carry(t + 0.05, [-0.12, 0.42, 0.38], 0.45);
  A(t - 0.15, "wiz", "look", { to: [0, 0], dur: 0.25, blink: false });
  t = h.carry(t + 0.05, [-0.1, 0.45, 0.38], 0.4, "inOut", { tip: 18 });   // the sip (mouth height: potato faces sit low)
  A(t - 0.2, "wiz", "lean", { to: 4, dur: 0.3 });
  A(t - 0.2, "wiz", "face", { set: { lidL: 0.55, lidR: 0.55 }, dur: 0.2 });
  A(t + 0.35, "wiz", "face", { set: { lidL: 0, lidR: 0 }, dur: 0.2 });
  A(t + 0.35, "wiz", "lean", { to: 0, dur: 0.3 });
  t = h.carry(t + 0.4, [-0.12, 0.42, 0.38], 0.35, "inOut", { tip: 0 });
  A(t, "wiz", "look", { to: [0.1, -0.8], dur: 0.2, blink: false });
  t = h.put(t + 0.1, [MUG.x, MUG.y, MUG.z]);
  A(t, "wiz", "look", { to: [0, 0], dur: 0.25, blink: false });
  const SHOT = { pos: [-0.75, 1.05, 2.3], look: [-0.05, 0.55, 0.3], fov: 32 };
  const cast = [{ id: "wiz", character: "lookdev/wizard-crisp", at: [0, -0.25], face: 0, expr: "kind", follow: 0.2, seed: 2.6 }];
  const props = [{ id: "table", kind: "coffeetable", x: 0, z: 0.5, h: 0.36, w: 1.3, d: 0.5 }, MUG];
  write({ ...base("reach", "Natural motion: reach, pick up, drink", cast, props, c.beats([["reach", 0, SHOT]], END)), duration: END });
}

// 3. EVERYDAY: Phoenix looks round, waves, stretches up, walks to a stool, sits down and gets up again (turn with the
//    eyes leading, arcs on big arm moves, the forward lean before standing up, the bounce on the seat)
{
  const c = clip(), { A } = c, END = 6.4;
  A(0, "phx", "noblink");
  A(0.3, "phx", "turn", { to: "3q-left", dur: 0.4 });
  A(0.85, "phx", "arm", { side: "R", pose: "wave", dur: 0.35 });   // a wave hello
  A(1.55, "phx", "arm", { side: "R", pose: "rest", dur: 0.35 });
  A(1.55, "phx", "turn", { to: "camera", dur: 0.35 });
  A(2.0, "phx", "arm", { side: "both", pose: "up", dur: 0.45 });   // a big stretch
  A(2.75, "phx", "arm", { side: "both", pose: "rest", dur: 0.45 });
  A(3.1, "phx", "turn", { to: "left", dur: 0.3 });
  A(3.35, "phx", "move", { to: [-0.55, 0.35], dur: 0.8, steps: 2.4 });
  A(4.15, "phx", "turn", { to: "camera", dur: 0.3 });
  A(4.3, "phx", "sit", { seat: "chair", dur: 0.5, hands: "lap", feet: [0.38, 0.1] });
  A(5.4, "phx", "stand", { dur: 0.6 });
  const SHOT = { pos: [-0.2, 1.0, 5.6], look: [-0.2, 0.55, 0], fov: 34 };
  const cast = [{ id: "phx", character: "duo/phoenix", at: [0.35, 0.0], face: "camera", expr: "kind", follow: 0.3, seed: 3.1, span: 0 }];
  const props = [{ id: "chair", kind: "stool", x: -0.55, z: 0.0 }];
  const allowClip = [{ who: "phx", with: "chair", from: 3.55, to: END, reason: "sits down on the stool and gets up again" }];
  write({ ...base("everyday", "Natural motion: look, point, stretch, sit, stand", cast, props, c.beats([["everyday", 0, SHOT]], END)), duration: END, allowClip });
}

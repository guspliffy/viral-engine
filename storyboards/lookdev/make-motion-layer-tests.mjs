// Engine test for the motion layer (quality plan items 8 and 12; util.js layerOf, engine/page/solve.js): two benches,
// each written twice, the clip template's motion today ("motion": { "feet": 2 }, "rig": { "hand": 2 }) and the same
// with "overlap" and "timing" on, nothing else different, for a side by side with a close-up at normal and half speed.
// Pure engine test: no creative review.
//   node storyboards/lookdev/make-motion-layer-tests.mjs
//   node engine/render.mjs storyboards/lookdev/motion-layer/gestures-today.json   (and gestures-layer, reach-*)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip } from "../lib/clip.mjs";
import * as grips from "../lib/grips.mjs";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "motion-layer");
fs.mkdirSync(OUT, { recursive: true });
const base = (id, title, cast, props, beats, END) => ({
  id, title, idea: "Engine test: motion layer, not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false,
  set: { type: "livingroom", seed: 5, focus: false },
  music: false, sound: { sfx: 0.6, ambience: 0.3 }, cleanStart: true,
  hook: { show: cast.map((m) => m.id), hint: 0, what: "engine test" },
  cast, props, captions: [], beats, duration: END, rig: { hand: 2 },
  notes: "Generated by storyboards/lookdev/make-motion-layer-tests.mjs (engine test).",
});
function write(sb, labels) {
  for (const [v, motion, tag] of [["today", { feet: 2 }, "TODAY"], ["layer", { feet: 2, overlap: true, timing: true }, "OVERLAP + TIMING"]]) {
    const out = { ...sb, id: `${sb.id}-${v}`, motion };
    out.captions = [{ from: 0, to: sb.duration, text: tag, pos: 260, pop: false, kinetic: false }, ...labels.map(([from, to, text]) => ({ from, to, text, pos: 1450, pop: false, kinetic: false }))];
    fs.writeFileSync(path.join(OUT, `${out.id}.json`), JSON.stringify(out, null, 1) + "\n");
  }
}

// 1. GESTURES: Phoenix and Reaper turn to each other together, wave and shrug, both point at the camera on the same
//    beat, turn back, hold (weight shifts), Phoenix stretches, then walks a three-key path while Reaper leans
{
  const c = clip(), { A } = c, END = 10;
  for (const w of ["phx", "rea"]) A(0, w, "noblink");
  A(0.4, "phx", "turn", { to: "3q-right", dur: 0.4 });
  A(0.4, "rea", "turn", { to: "3q-left", dur: 0.4 });
  A(1.0, "phx", "arm", { side: "R", pose: "wave", dur: 0.35 });
  A(1.75, "phx", "arm", { side: "R", pose: "rest", dur: 0.35 });
  A(1.2, "rea", "arm", { side: "both", pose: "shrug", dur: 0.3 });
  A(1.95, "rea", "arm", { side: "both", pose: "rest", dur: 0.35 });
  A(2.5, "phx", "turn", { to: "camera", dur: 0.3 });
  A(2.5, "rea", "turn", { to: "camera", dur: 0.3 });
  A(2.6, "phx", "arm", { side: "R", pose: "point", dur: 0.3 });
  A(2.6, "rea", "arm", { side: "L", pose: "point", dur: 0.3 });
  A(3.3, "phx", "arm", { side: "R", pose: "rest", dur: 0.35 });
  A(3.3, "rea", "arm", { side: "L", pose: "rest", dur: 0.35 });
  // 3.7 .. 6.0: a hold (moving holds: the weight shifts)
  A(6.0, "phx", "arm", { side: "both", pose: "up", dur: 0.45 });
  A(6.7, "phx", "arm", { side: "both", pose: "rest", dur: 0.45 });
  A(7.3, "phx", "move", { to: [-0.95, 0.3], dur: 0.6 });
  A(7.9, "phx", "move", { to: [-0.7, 0.65], dur: 0.6 });
  A(8.5, "phx", "move", { to: [-0.4, 0.4], dur: 0.6 });
  A(7.4, "rea", "lean", { to: 8, dur: 0.3 });
  A(8.1, "rea", "lean", { to: 0, dur: 0.3 });
  const SHOT = { pos: [0.1, 0.85, 7.4], look: [0.1, 0.5, 0.3], fov: 34 };
  const cast = [
    { id: "phx", character: "duo/phoenix", at: [-0.55, 0.1], face: "camera", expr: "kind", follow: 0.3, seed: 1.7, span: 0 },
    { id: "rea", character: "notyet/reaper-noscythe", at: [0.75, 0.1], face: "camera", expr: "kind", follow: 0.3, seed: 2.9 },
  ];
  write(base("gestures", "Motion layer: gestures, turns, hold, chained walk", cast, [], c.beats([["gestures", 0, SHOT]], END), END),
    [[0, 0.95, "TURN TOGETHER"], [0.95, 2.45, "WAVE + SHRUG"], [2.45, 3.7, "POINT TOGETHER"], [3.7, 5.95, "HOLD"], [5.95, 7.25, "STRETCH"], [7.25, END, "3-KEY WALK + LEAN"]]);
}

// 2. REACH, PICK UP, DRINK: the Wizard takes a mug off the table, lifts it, sips, puts it back (the holding hand has
//    no lag, so the grip stays exact; the body and the free hand overlap)
{
  const c = clip(), { A } = c, END = 5.4;
  const MUG = { id: "it", kind: "campmug", scale: 1.9, x: -0.13, y: 0.36, z: 0.42, rot: 55 };
  const h = grips.mug(c, "wiz", MUG, { side: "R" });
  A(0, "wiz", "noblink");
  A(0.3, "wiz", "look", { to: [0.1, -0.8], dur: 0.2, blink: false });
  let t = h.take(0.45);
  t = h.carry(t + 0.05, [-0.12, 0.42, 0.38], 0.45);
  A(t - 0.15, "wiz", "look", { to: [0, 0], dur: 0.25, blink: false });
  t = h.carry(t + 0.05, [-0.1, 0.45, 0.38], 0.4, "inOut", { tip: 18 });
  A(t - 0.2, "wiz", "lean", { to: 4, dur: 0.3 });
  A(t - 0.2, "wiz", "face", { set: { lidL: 0.55, lidR: 0.55 }, dur: 0.2 });
  A(t + 0.35, "wiz", "face", { set: { lidL: 0, lidR: 0 }, dur: 0.2 });
  A(t + 0.35, "wiz", "lean", { to: 0, dur: 0.3 });
  A(t + 0.4, "wiz", "arm", { side: "L", pose: "hips", dur: 0.35 });
  t = h.carry(t + 0.4, [-0.12, 0.42, 0.38], 0.35, "inOut", { tip: 0 });
  A(t, "wiz", "look", { to: [0.1, -0.8], dur: 0.2, blink: false });
  t = h.put(t + 0.1, [MUG.x, MUG.y, MUG.z]);
  A(t, "wiz", "look", { to: [0, 0], dur: 0.25, blink: false });
  A(t + 0.1, "wiz", "arm", { side: "L", pose: "rest", dur: 0.35 });
  const SHOT = { pos: [-0.75, 1.05, 2.3], look: [-0.05, 0.55, 0.3], fov: 32 };
  const cast = [{ id: "wiz", character: "notyet/wizard-nostaff", at: [0, -0.25], face: 0, expr: "kind", follow: 0.2, seed: 2.6 }];
  const props = [{ id: "table", kind: "coffeetable", x: 0, z: 0.5, h: 0.36, w: 1.3, d: 0.5 }, MUG];
  write(base("reach", "Motion layer: reach, pick up, drink", cast, props, c.beats([["reach", 0, SHOT]], END), END), [[0, END, "REACH, SIP, PUT BACK"]]);
}

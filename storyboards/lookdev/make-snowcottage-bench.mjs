// Snowcottage bench (Survive it EP1 "Snowed in", task T1): the set "snowcottage" (engine/page/set-snowcottage.js) with
// the EP1 four at the staging proof's DAY 1 places, in the clip's look (castLook "sheet", look "anime-pro" with the
// clip template's cel, ink, satsuei and light 2). One state a second, a still in the middle of each:
//   (a) 0.5  day, fire 1, snowWindow 0.8 (frame 0)
//   (b) 1.5  fire 2, the flare (panel 03)
//   (c) 2.5  dark 1, fire 0.25 (embers), candles 1, snowWindow 1.0 (panels 04-05)
//   (d) 3.5  the door open 1, from the door camera (day)
//   node storyboards/lookdev/make-snowcottage-bench.mjs   -> snowcottage-bench.json, and the still times (printed)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
// steps at equal times: each state holds for its second
const step = (...v) => v.flatMap((x, i) => (i ? [[i, v[i - 1]], [i, x]] : [[0, x]]));
const SET = {
  type: "snowcottage", light: "golden", windows: false, aperture: 0, focus: false, bloom: "emissive", lighting: 2,
  hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true,
  fire: step(1, 2, 0.25, 1), candles: 1, snowWindow: step(0.8, 0.8, 1.0, 0.8), dark: step(0, 0, 1, 0), door: step(0, 0, 0, 1),
};
const FOUR = [["vik", "duo/viking", [0.71, -0.23]], ["sam", "duo/samurai", [-1.27, -1.84]], ["rea", "never-has-money/reaper", [-0.1, 0.27]], ["god", "potatobrawl/allfather", [0.32, -1.81]]];
const cast = FOUR.map(([id, character, at], i) => ({ id, character, at, face: "camera", follow: 0, sway: 0.4, seed: 1.1 + i * 0.7 }));
const actions = FOUR.map(([id]) => ({ who: id, at: 0, do: "noblink" }));
const ROOM = { pos: [0.76, 1.6, 2.96], look: [-0.02, 0.7, -1.91], fov: 58 }, DOOR = { pos: [1.63, 1.45, 3.03], look: [-2.08, 0.92, -1.63], fov: 60 };
export const STILLS = [0.5, 1.5, 2.5, 3.5];
const sb = {
  id: "snowcottage-bench", title: "Snowcottage bench: the snowed-in room, day, flare, night, door", fps: 30, look: "anime-pro", castLook: "sheet",
  profile: "short", loop: false, duration: 4, cleanStart: true, rig: { hand: 2, eyes: 2, hold: 2 }, animeTiming: true,
  set: SET, music: false, sound: { sfx: 0, ambience: 0 }, creative: { length: [1, 30], notes: false },
  shots: [{ at: 0, ...ROOM }, { at: 3, ...DOOR }], cast, actions,
  notes: "Generated by storyboards/lookdev/make-snowcottage-bench.mjs (set bench, Survive it EP1 task T1).",
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const f = path.join(here, `${sb.id}.json`);
  fs.writeFileSync(f, JSON.stringify(sb, null, 1) + "\n");
  console.log(path.relative(process.cwd(), f));
  console.log(`stills: ${STILLS.join(",")}`);
}

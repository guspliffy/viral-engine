// Engine test for arm rig 2 (plan item 11, "rig": { "arm": 2 }: the rubber-hose arm drawn through a two-bone elbow):
// one bench of every arm pose the clips use, written twice (hand rig 2 alone, and with arm rig 2), nothing else
// different, for a side by side with a close-up. Pure engine test: no creative review.
//   node storyboards/lookdev/make-arm-tests.mjs
//   node engine/render.mjs storyboards/lookdev/arms/arms-today.json   (and arms-arm2)
//
// What real arms do (the elbow is a hinge; upper arm and forearm about the same length; Ghibli keeps a slight bend in
// every arm, a straight lock only on a hard push):
//   hanging: elbow points back, a little out; the forearm hangs almost straight down
//   reaching forward or out: elbow down, a little out and back; the arm straightens only at the end of the reach
//   raised overhead: elbow out to the side, the forearm up
//   hand to the face: elbow down and forward, tucked in front of the chest
//   across the body: elbow down and out, the upper arm across the chest
//   hands on hips: elbows straight out to the sides
//   shrug: elbows bent and tucked, forearms out and up, palms up
// The elbow leads a raise and trails a drop (that timing is the motion layer's, item 12); the rig keeps the forearm's
// length and the bend's direction steady through every pose and blend.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip } from "../lib/clip.mjs";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "arms");
fs.mkdirSync(OUT, { recursive: true });
const base = (id, title, cast, beats) => ({
  id, title, idea: "Engine test: arm rig 2, not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false,
  set: { type: "livingroom", seed: 5, focus: false },
  music: false, sound: { sfx: 0.6, ambience: 0.3 }, motion: "natural",
  hook: { show: cast.map((m) => m.id), hint: 0, what: "engine test" },
  cast, props: [], captions: [], beats,
  notes: "Generated by storyboards/lookdev/make-arm-tests.mjs (engine test).",
});
function write(sb) {
  for (const v of ["today", "arm2"]) {
    const out = { ...sb, id: `${sb.id}-${v}`, rig: { hand: 2, ...(v === "arm2" && { arm: 2 }) } };
    out.captions = [{ from: 0, to: sb.duration, text: v === "arm2" ? "ARM RIG 2" : "TODAY (hand rig 2)", pos: 1500, pop: false, kinetic: false }];
    fs.writeFileSync(path.join(OUT, `${sb.id}-${v}.json`), JSON.stringify(out, null, 1) + "\n");
  }
}

// ARMS: rest, both up, out to the sides, reach across, point, shrug, hands on hips, both hands to the face, a wave,
// and back to rest; each held long enough to read, each move 0.4 s (the clips' usual)
{
  const c = clip(), { A } = c, D = 0.4, HOLD = 0.45;
  A(0, "phx", "noblink");
  A(0, "phx", "look", { to: [0, 0], dur: 0.01, blink: false });
  const seq = [
    ["both", "up"], ["both", "rest"],
    ["both", { o: [0.3, 0.6, 0.05] }], ["both", "rest"],                // out to the sides at shoulder height
    ["R", { x: [0.06, 0.26, 0.5] }], ["R", "rest"],                     // the right hand across the body
    ["R", "point"], ["R", "rest"],
    ["both", "shrug"], ["both", "rest"],
    ["both", "hips"], ["both", "rest"],
    ["both", "cheeks"], ["both", "rest"],
    ["R", "wave"], ["R", "rest"],
    ["both", "cast"], ["both", "rest"],
  ];
  let t = 0.3;
  for (const [side, pose] of seq) { A(t, "phx", "arm", { side, pose, dur: D }); t += D + HOLD; }
  const END = Math.round((t + 0.2) * 100) / 100;
  const SHOT = { pos: [0.5, 0.8, 4.6], look: [0, 0.62, 0], fov: 36 };
  const cast = [{ id: "phx", character: "duo/phoenix", at: [0, 0], face: "camera", expr: "kind", follow: 0.3, seed: 1.3, span: 0 }];
  write({ ...base("arms", "Arm rig 2: every arm pose", cast, c.beats([["arms", 0, SHOT]], END)), duration: END });
}
console.log(`wrote 2 storyboards to ${OUT}`);

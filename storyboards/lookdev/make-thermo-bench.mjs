// Potato Desk 11 "Thermostat war" props bench (task T1, 20 Nov 2026): thermostat, thermobox and stepstool of engine/page/props-thermo.js at the DESIGN's sizes
// (storyboards/series/potato-desk/11-thermostat/DESIGN.md sections 2, 3). Not a clip. One thermostat per state along a wall (1.5 m apart, each at y 1.36, z -1.30),
// the DESIGN's three cameras per state (frontal S01, close S03, three-quarter S27), both step heights in front of the wall. Spud stands at (0, -0.36) under the first one.
//   node storyboards/lookdev/make-thermo-bench.mjs                      (prints the still times)
//   node engine/render.mjs storyboards/lookdev/thermo-bench.json --stills <times> --draft --safe --out storyboards/lookdev/out
//   node qa/contact.mjs storyboards/lookdev/out/thermo-bench-*.png --out storyboards/lookdev/out/thermo-bench-sheet.png
import { clip, write } from "../lib/clip.mjs";

const c = clip();
const DX = 1.5, Y = 1.36, Z = -1.3;
// [id, extra spec, tweened state at 0 (0.01 s), label]
const T = [
  ["t19", { temp: 19 }],
  ["t21", { temp: 21 }],
  ["t30", { temp: 30 }],
  ["t12", { temp: 12 }],
  ["blank", { temp: "blank" }],
  ["down", { temp: 19 }, { down: 1 }],
  ["tape", { temp: 26, tape: 1 }],
  ["pop", { temp: 21, pop: 1 }],
  ["boxOn", { temp: 21, key: 0 }, { on: 1 }, "box"],
  ["boxKey", { temp: 21, key: 0.5 }, { on: 1 }, "box"],
  ["boxTug", { temp: 21, key: 1 }, { on: 1, tug: 1 }, "box"],
  ["boxRip", { temp: 21, key: 1, rip: 1, dropAt: 0 }, { on: 1 }, "box"],
  ["boxFull", { temp: 21, key: 1, window: 0 }, { on: 1 }, "box"],
  ["shake", { temp: 23 }, { shake: 1 }],
  ["up", { temp: 12 }, { up: 1 }],
];
const props = [
  { id: "wall", kind: "officewall", x: 10, y: 0, z: -1.3, w: 30, h: 2.6, dado: "#B7C4B8", wall: "#B7C4B8", top: "#B7C4B8", rail: "#AEBBAF" },
  { id: "floor", kind: "carpettiles", x: 10, y: 0, z: 4.6, w: 30, d: 12 },
  { id: "stoolHigh", kind: "stepstool", h: 0.74, x: -2.5, y: 0, z: -0.98 },
  { id: "stoolLow", kind: "stepstool", h: 0.26, x: -4.0, y: 0, z: -0.98 },
];
T.forEach(([id, spec, st, kind], i) => {
  const x = i * DX;
  props.push({ id, kind: kind === "box" ? "thermostat" : "thermostat", x, y: Y, z: Z, ...spec, ...(kind === "box" && { temp: spec.temp }) });
  if (kind === "box") props.push({ id: id + "B", kind: "thermobox", x, y: Y, z: Z, key: spec.key, rip: spec.rip, dropAt: spec.dropAt, window: spec.window });
  const tw = { ...(st || {}) }, boxTw = kind === "box" ? { on: tw.on, tug: tw.tug } : null;
  if (kind === "box") { delete tw.on; delete tw.tug; }
  if (Object.keys(tw).length) c.prop(0, id, tw, 0.01);
  if (boxTw) c.prop(0, id + "B", Object.fromEntries(Object.entries(boxTw).filter(([, v]) => v != null)), 0.01);
});
const cast = [{ id: "spud", character: "potatobrawl/spud", at: [0, -0.36], face: "camera", expr: "kind", follow: 0.2, seed: 1.9 }];
c.A(0, "spud", "noblink");

const sh = (pos, look, fov) => ({ pos, look, fov });
const front = (x) => sh([x, 1.45, 3.85], [x - 0.25, 1.1, -1.3], 30);
const close = (x) => sh([x, 1.38, 0.55], [x, 1.36, -1.3], 30);
const quarter = (x) => sh([x + 0.85, 2.0, 3.4], [x + 0.25, 1.05, -1.0], 46);
const X = (id) => T.findIndex((t) => t[0] === id) * DX;
const shots = [];
for (const id of ["t19", "t21", "t30", "t12", "blank", "down", "tape", "pop", "boxOn", "boxKey", "boxTug", "boxRip", "boxFull", "shake", "up"]) shots.push([id + "-front", front(X(id))]);
for (const id of ["t19", "t12", "down", "tape", "pop", "boxOn", "boxKey", "boxTug", "boxRip", "boxFull"]) shots.push([id + "-close", close(X(id))]);
for (const id of ["t19", "down", "tape", "pop", "boxOn", "boxKey", "boxRip"]) shots.push([id + "-quarter", quarter(X(id))]);
shots.push(["stools-quarter", sh([-2.0, 1.7, 3.0], [-3.2, 0.35, -0.98], 40)], ["stoolHigh-side", sh([-0.6, 0.9, 2.6], [-2.5, 0.4, -0.98], 36)], ["stoolLow-side", sh([-2.6, 0.7, 2.4], [-4.0, 0.15, -0.98], 36)]);
const list = shots.map(([n, s2], k) => [n, k * 1.1, s2]);
console.log("stills at", list.map(([, t]) => (t + 0.6).toFixed(1)).join(","));
console.log("names", list.map(([n, t]) => `${n}@${(t + 0.6).toFixed(1)}`).join(" "));
write(import.meta.url, {
  id: "thermo-bench", title: "Thermostat props bench", idea: "Props bench for Potato Desk 11 (T1), not a clip", fps: 30, look: "anime-pro", profile: "short", loop: false,
  castLook: "sheet", physics: false,
  set: { type: "plain", color: "#aab6bc", floor: "#6E7680", light: "soft", para: 0, aperture: 0, lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true },
  music: false, sound: { auto: false }, hook: { show: ["spud"], hint: 0, what: "engine bench" },
  cast, props, captions: c.captions, beats: c.beats(list, 1.1 * list.length),
  notes: "Generated by storyboards/lookdev/make-thermo-bench.mjs (engine bench, no reviews).",
});

// Engine test for the planted gait (quality plan item 10, timeline.js gaitPlan; storyboard "motion": { "feet": 2 }):
// one bench written twice, today's natural motion and the planted gait, with nothing else different, for a side by
// side with a close-up at normal and half speed. Phoenix walks across and stops, turns on the spot and back, shuffles
// sideways, runs and stops, gets shoved back (a stumble) and walks off with an eased start. Pure engine test.
//   node storyboards/lookdev/make-feet-tests.mjs
//   node engine/render.mjs storyboards/lookdev/feet/feet-bench-today.json   (and feet-bench-planted)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip } from "../lib/clip.mjs";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "feet");
fs.mkdirSync(OUT, { recursive: true });
const c = clip(), { A } = c, END = 12.4;
A(0, "phx", "noblink");
A(0, "phx", "turn", { to: "right", dur: 0 });
// 1. WALK AND STOP (default ease: the natural gait today)
A(0.3, "phx", "move", { to: [0.55, 0], dur: 1.7, steps: 2.2 });
// 2. TURN ON THE SPOT, half round and back (today the feet swivel with the body)
A(2.35, "phx", "turn", { to: "left", dur: 0.45 });
A(3.2, "phx", "turn", { to: "camera", dur: 0.35 });
// 3. SHUFFLE sideways and back (a short eased move: today's walk cycle, feet gliding)
A(3.85, "phx", "move", { to: [0.4, 0], dur: 0.45, ease: "out", steps: 2.6 });
A(4.55, "phx", "move", { to: [0.55, 0.05], dur: 0.4, ease: "in", steps: 2.6 });
// 4. RUN AND STOP (a "run": today the old cycle, feet sliding with the body)
A(5.2, "phx", "turn", { to: "left", dur: 0.25 });
A(5.35, "phx", "run", { pts: [[0, 0.55, 0.05], [0.15, 0.47, 0.05], [0.3, 0.28, 0.05], [0.75, -0.38, 0.05], [0.9, -0.52, 0.05], [1.05, -0.57, 0.05]], stride: 2, rate: [[0, 3.2]] });
// 5. SHOVED BACK: a jolt that starts fast and slows (ease out), the feet scramble to catch it
A(7.2, "phx", "turn", { to: "right", dur: 0.3 });
A(7.9, "phx", "expr", { to: "shocked", dur: 0.15 });
A(7.9, "phx", "move", { to: [-1.0, 0.05], dur: 0.4, ease: "out" });
A(8.6, "phx", "expr", { to: "annoyed", dur: 0.25 });
// 6. WALK OFF with an eased start and a sudden stop (ease "in": today's old cycle)
A(9.3, "phx", "move", { to: [0.45, 0.0], dur: 1.4, ease: "in" });
A(11.2, "phx", "turn", { to: "camera", dur: 0.35 });
const SHOT = { pos: [-0.25, 0.7, 7.4], look: [-0.25, 0.4, 0], fov: 30 };
const cast = [{ id: "phx", character: "duo/phoenix", at: [-0.9, 0], face: "camera", expr: "kind", follow: 0.3, seed: 1.7, span: 0 }];
const base = {
  id: "feet-bench", title: "Planted gait bench", idea: "Engine test: planted feet, not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false,
  set: { type: "livingroom", seed: 5, focus: false },
  music: false, sound: { sfx: 0.6, ambience: 0.3 },
  hook: { show: ["phx"], hint: 0, what: "engine test" },
  cast, props: [], captions: [], beats: c.beats([["bench", 0, SHOT]], END), duration: END,
  notes: "Generated by storyboards/lookdev/make-feet-tests.mjs (engine test).",
};
const LABELS = [[0, 2.3, "WALK + STOP"], [2.3, 3.8, "TURN ON THE SPOT"], [3.8, 5.15, "SHUFFLE"], [5.15, 7.1, "RUN + STOP"], [7.1, 9.2, "SHOVED BACK"], [9.2, END, "EASED START, SUDDEN STOP"]];
for (const [v, motion, tag] of [["today", "natural", "TODAY"], ["planted", { feet: 2 }, "PLANTED FEET"]]) {
  const sb = { ...base, id: `feet-bench-${v}`, motion };
  sb.captions = [{ from: 0, to: END, text: tag, pos: 260, pop: false, kinetic: false }, ...LABELS.map(([from, to, text]) => ({ from, to, text, pos: 1450, pop: false, kinetic: false }))];
  fs.writeFileSync(path.join(OUT, `${sb.id}.json`), JSON.stringify(sb, null, 1) + "\n");
}
console.log(`wrote 2 storyboards to ${OUT}`);

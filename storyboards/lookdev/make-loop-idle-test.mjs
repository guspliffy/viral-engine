// Engine test for loop-safe idle (util.js loopLen, "loopIdle": true): three fighters standing in a 4.2 s loop with
// nothing to do but breathe, sway, blink and move their idle parts (Dragon's wings and tail, Odin's raven, Phoenix's
// crest and wing beat) in front of a plate whose leaves and sun patches move. Played on repeat, the "off" version
// jumps at the seam and the "on" version doesn't. Pure engine test: no creative review.
//   node storyboards/lookdev/make-loop-idle-test.mjs   -> loop-idle-test-off.json and loop-idle-test-on.json
import { clip, write } from "../lib/clip.mjs";

const END = 4.2;
const cast = [
  { id: "dra", character: "lookdev/dragon-crisp", at: [-0.95, 0.0], face: "3q-right", seed: 1.3 },
  { id: "phx", character: "potatobrawl/phoenix", at: [0.0, 0.3], face: "camera", seed: 2.1 },
  { id: "odn", character: "lookdev/allfather-crisp", at: [0.95, 0.0], face: "3q-left", seed: 3.7 },
];
const SHOT = { pos: [0, 1.2, 7.4], look: [0, 0.8, -0.4], fov: 38 };
for (const on of [false, true]) {
  const c = clip();
  for (const m of cast) c.A(0, m.id, "look", { to: [0, 0], dur: 0.01, blink: false });
  write(import.meta.url, {
    id: `loop-idle-test-${on ? "on" : "off"}`,
    title: `Loop-safe idle test (${on ? "on" : "off"})`,
    idea: "Engine test: idle rhythms close exactly at the loop seam",
    fps: 30, look: "anime-pro", profile: "short", loop: true, ...(on && { loopIdle: true }),
    creative: { loop: true },
    set: { type: "plain", color: "#d9c9a8", floor: "#a88a68", light: "golden", plate: { src: "assets/plates/autumn-sidewalk.png", z: -2.4, center: [0, 1.6], height: 6.4 } },
    music: false, sound: { sfx: 0.5, ambience: 0.3 },
    cast, props: [], captions: [], beats: c.beats([["idle", 0, SHOT]], END),
    notes: "Generated by storyboards/lookdev/make-loop-idle-test.mjs (engine test).",
  });
}

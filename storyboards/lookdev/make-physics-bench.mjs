// Prop physics bench (quality plan item 17 trial, engine/page/physics.js): loose props that hit each other, the set
// and a character, baked with Rapier's deterministic build. Not a clip: an engine test Jonny judges from the video.
//   0.5 s  the Wizard slams the table and the pile jumps off it: the props tumble, hit each other and the floor
//   2.3 s  zero-g ("float", g 0): everything lifts off the floor with a small kick each, turning slowly
//   4.0 s  gravity back, hard: it all crashes down again into a new pile, one bag bouncing off the Wizard
//   node storyboards/lookdev/make-physics-bench.mjs && node engine/render.mjs storyboards/lookdev/physics-bench.json --draft
import { clip, write, r3 } from "../lib/clip.mjs";
import * as grips from "../lib/grips.mjs";

const c = clip(), { A, at } = c;
const TABLE_H = 0.36;
const props = [
  { id: "table", kind: "coffeetable", x: 0, z: 0.35, h: TABLE_H, w: 1.3, d: 0.5 },
  // spread along the table with gaps (each at least a few cm clear of the next), the pillow on the case: a small pile
  { id: "shoe", kind: "sneaker", x: -0.57, y: TABLE_H, z: 0.38, rot: 0, scale: 1.2, body: { settle: true } },
  { id: "case", kind: "suitcase", x: -0.29, y: TABLE_H, z: 0.35, tip: 90, scale: 0.7, color: "#d2433a", body: { settle: true } },
  { id: "pil", kind: "pillow", x: -0.29, y: 0.56, z: 0.35, rot: -10, scale: 0.6, body: { settle: true } },
  { id: "box", kind: "parcel", x: -0.04, y: TABLE_H, z: 0.38, rot: 0, scale: 0.6, body: { settle: true } },
  { id: "duf", kind: "duffel", x: 0.25, y: TABLE_H, z: 0.35, rot: 0, scale: 0.7, color: "#3a8f6a", body: { settle: true } },
];
const P = (t, prop, mode, o = {}) => at(t, { do: "physics", prop, mode, ...o });
A(0, "wiz", "noblink");
A(0, "wiz", "look", { to: [-0.3, -0.4], dur: 0, blink: false });
// the slam: his right palm comes down hard on the free end of the table at 0.5 s and everything on it jumps
grips.rest(c, "wiz", "R", props[0], [0.58, -0.06], 0.2, { dur: 0.3, ease: "in" });
c.arm(0.85, "wiz", "R", "rest", 0.5, "inOut");
// thrown off the table by the slam, away from it (to the left) and toward the camera, each a little differently (spin in rad/s about world axes)
P(0.52, "pil", "knock", { v: [-1.0, 1.7, 0.7], spin: [1.5, 0.5, 3] });
P(0.5, "duf", "knock", { v: [-1.2, 1.5, 0.9], spin: [-2, 1, 4] });
P(0.51, "box", "knock", { v: [-1.0, 1.8, 1.0], spin: [3, -2, 2] });
P(0.52, "case", "knock", { v: [-0.9, 1.4, 0.8], spin: [0.5, 0, 3.5] });
P(0.53, "shoe", "knock", { v: [-0.4, 2.0, 0.9], spin: [6, 3, -4] });
// zero-g: a small kick up for each, then gravity back hard
P(2.3, null, "float", { g: 0, dur: 0.2 });
for (const [i, id] of ["pil", "duf", "box", "case", "shoe"].entries()) P(r3(2.32 + i * 0.05), id, "knock", { v: [0.15 * (i - 2), 0.55 + 0.08 * i, 0.1 * ((i % 2) * 2 - 1)], spin: [0.6 * (i - 2), 0.4, -0.5 + 0.3 * i] });
A(2.4, "wiz", "look", { to: [-0.3, 0.2], dur: 0.4 });
P(4.0, null, "float", { g: -14, dur: 0.15 });
P(4.6, null, "float", { g: -9.81, dur: 0.3 });
A(4.2, "wiz", "look", { to: [-0.4, -0.6], dur: 0.25 });

const end = 6.5;
c.cap(0, end, "physics bench: knock, zero-g, fall", 1280, false, { kinetic: false });
// the bake's hash (engine/page/physics.js): the same storyboard bakes the same on every machine. The regression copy
// checks it on GitHub's runners (qa/regress.mjs "physics"); a change to the physics that moves anything changes it,
// like a golden still: look at the bench video, then update it here
const HASH = "15473468";

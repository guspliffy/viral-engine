// Engine test for Phase 3 acting (31 Oct 2026; storyboards/lib/acting.mjs "small gestures" and ma): two benches, each
// written twice, the way a clip does it today and with the new gestures or the pause before the payoff, both with
// "motion": "natural", for a side by side with a close-up crop. Pure engine test: no creative review.
//   node storyboards/lookdev/make-natural-acting-tests.mjs
//   node engine/render.mjs storyboards/lookdev/acting/gestures-today.json   (and gestures-new, ma-today, ma-new)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip } from "../lib/clip.mjs";
import * as act from "../lib/acting.mjs";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "acting");
fs.mkdirSync(OUT, { recursive: true });
const base = (id, title, cast, beats, END, extra = {}) => ({
  id, title, idea: "Engine test: small gestures and the pause before the payoff, not a clip",
  fps: 30, look: "anime-pro", castLook: "golden", profile: "short", loop: false, motion: "natural",
  set: { type: "livingroom", seed: 5, focus: false },
  music: false, sound: { sfx: 0.6, ambience: 0.3 },
  hook: { show: cast.map((m) => m.id), hint: 0, what: "engine test" },
  cast, props: [], beats, duration: END, ...extra,
  notes: "Generated by storyboards/lookdev/make-natural-acting-tests.mjs (engine test).",
});
const save = (sb) => fs.writeFileSync(path.join(OUT, `${sb.id}.json`), JSON.stringify(sb, null, 1) + "\n");
// one caption per segment: which version and what the gesture is for
const labels = (v, segs) => segs.map(([from, to, what]) => ({ from, to, text: `${v === "new" ? "NEW" : "TODAY"}: ${what}`, pos: 1500, pop: false, kinetic: false }));

// 1. GESTURES: Phoenix waits impatiently, schemes, composes himself after a scare, thinks it over. Today each beat is a
//    face change and an arm pose; the new version adds the gesture a person would make for themselves.
for (const v of ["today", "new"]) {
  const c = clip(), { A } = c, END = 12, N = v === "new";
  const ASIDE = [0.5, 0.12], HOME = [0, 0];
  A(0, "phx", "noblink");
  // waiting (0 - 2.9): annoyed, hands on the hips, eyes aside
  act.mood(c, 0.2, "phx", "annoyed", { hold: 1.6 });
  if (N) { act.hipsSettle(c, 0.25, "phx", { hold: 1.55 }); act.tapFoot(c, 0.6, "phx", { eyes: ASIDE, count: 4 }); }
  else { c.arm(0.3, "phx", "both", "hips", 0.3); A(0.5, "phx", "look", { to: ASIDE, dur: 0.25, blink: false }); c.arm(2.3, "phx", "both", "rest", 0.35); }
  A(2.25, "phx", "look", { to: HOME, dur: 0.25, blink: false });
  A(2.35, "phx", "expr", { expr: "kind", dur: 0.3 }); A(2.35, "phx", "face", { brow: 0, lid: 0, dur: 0.3 });
  // scheming (2.9 - 5.7): an idea lands, then (new) he rubs his hands
  act.idea(c, 2.95, "phx", { at: [-0.4, -0.3] });
  if (N) act.rubHands(c, 3.65, "phx", { rubs: 4, sly: false });
  A(5.15, "phx", "look", { to: HOME, dur: 0.25, blink: false });
  A(5.2, "phx", "expr", { expr: "kind", dur: 0.3 }); A(5.2, "phx", "face", { brow: 0, dur: 0.3 });
  // a scare and composing himself (5.7 - 9.3): a shock, then (new) a breath and brushing himself off
  act.shock(c, 5.8, "phx", { hold: 0.7 });
  A(6.6, "phx", "expr", { expr: "kind", dur: 0.35 }); A(6.6, "phx", "face", { brow: 0, dur: 0.3 });
  if (N) { const t = act.breath(c, 6.65, "phx"); act.brushOff(c, t + 0.05, "phx"); }
  // thinking (9.3 - 12): eyes up and aside, a held beat; (new) a hand to the chin and a head tilt
  if (N) act.thinkChin(c, 9.4, "phx", { hold: 1.2 });
  else { A(9.4, "phx", "look", { to: [0.45, 0.4], dur: 0.25, blink: false }); A(9.9, "phx", "still", { dur: 1.2, idle: 0.15 }); A(11.1, "phx", "look", { to: HOME, dur: 0.25, blink: false }); }
  const SHOT = { pos: [0, 0.72, 3.4], look: [0, 0.55, 0], fov: 32 };
  const cast = [{ id: "phx", character: "duo/phoenix", at: [0, 0], face: "camera", expr: "kind", follow: 0.3, seed: 3.1, span: 0 }];
  const sb = base(`gestures-${v}`, `Small gestures (${v})`, cast, c.beats([["gestures", 0, SHOT]], END), END);
  sb.captions = labels(v, [[0, 2.9, "waiting"], [2.9, 5.7, "scheming"], [5.7, 9.3, "after a scare"], [9.3, 12, "thinking"]]);
  save(sb);
}

// 2. MA: Phoenix boasts to Reaper, Reaper's flat "mm." is the payoff and Phoenix deflates. Today the boast's arm comes
//    down right into the payoff and the idle runs on; the new version finishes the gesture earlier and holds everyone
//    still for half a second before the payoff (act.ma), with the music's dip under it.
for (const v of ["today", "new"]) {
  const c = clip(), { A } = c, END = 5.4, PAY = 3.3, N = v === "new";
  A(0, "phx", "noblink"); A(0, "rea", "noblink");
  A(0, "phx", "look", { to: [0.6, 0.05], dur: 0.01, blink: false }); A(0, "rea", "look", { to: [-0.6, 0.05], dur: 0.01, blink: false });
  A(0.05, "phx", "expr", { expr: "happy", set: { curve: 0.6 }, dur: 0.25 });
  A(0.1, "phx", "talk", { line: "ba-da-bing ba-ba-boom!", tone: "excited", dur: 1.9 });
  c.arm(0.3, "phx", "L", "up", 0.4); c.arm(1.0, "phx", "L", "shrug", 0.35); c.arm(1.6, "phx", "L", "up", 0.35);
  act.blinksAt(c, "rea", [1.2]);
  if (N) { c.arm(2.2, "phx", "L", "rest", 0.4); act.ma(c, PAY, ["phx", "rea"]); }
  else { c.arm(2.95, "phx", "L", "rest", 0.4); A(2.9, "rea", "blink", { dur: 0.22 }); }
  // the payoff: Reaper's flat line and slow blink, Phoenix deflates
  A(PAY, "rea", "talk", { line: "mm.", tone: "calm", dur: 0.45 });
  A(PAY, "rea", "face", { lid: 0.45, dur: 0.25 });
  A(PAY + 0.1, "rea", "expr", { expr: "deadpan", dur: 0.25 });
  A(PAY + 0.55, "phx", "expr", { expr: "sad", set: { curve: -0.3 }, dur: 0.3 });
  A(PAY + 0.55, "phx", "droop", { to: 0.6, dur: 0.4 });
  A(PAY + 0.6, "phx", "squash", { amount: 0.08, dur: 0.45 });
  A(PAY + 0.7, "phx", "still", { dur: 1.1, idle: 0.1 });
  const SHOT = { pos: [0, 0.75, 4.4], look: [0, 0.55, 0], fov: 34 };
  const cast = [
    { id: "phx", character: "duo/phoenix", at: [-0.5, 0], face: "3q-right", expr: "kind", follow: 0.3, seed: 3.1, span: 0 },
    { id: "rea", character: "lookdev/reaper-crisp", at: [0.5, 0], face: "3q-left", expr: "deadpan", follow: 0.3, seed: 4.4 },
  ];
  const sb = base(`ma-${v}`, `The pause before the payoff (${v})`, cast, c.beats([["setup", 0, SHOT, "hook"], ["payoff", PAY, "keep", "payoff"]], END), END, { music: { seed: 11 } });
  sb.captions = labels(v, [[0, END, N ? "a still half second before the payoff" : "straight into the payoff"]]);
  save(sb);
}
console.log("wrote", fs.readdirSync(OUT).join(" "));

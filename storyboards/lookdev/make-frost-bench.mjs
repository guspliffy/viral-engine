// Frost bench (Survive it EP1 "Snowed in", task T3): the `frost` / `melt` face controls (engine/page/frost.js) on the
// cast, in the clip's look (castLook "sheet", look "anime-pro" with the clip template's cel, ink, satsuei and light 2)
// in the warm living room (set "xmasroom").
//   frost-bench.json      the EP1 four in a row (Viking, Samurai, Reaper, Norse god), one step a second: frost 0, 0.3
//                         (DAY 2), 0.8 (DAY 10), 1.0 (DAY 100), then the thaw (frost 0.5 with melt 1 over 0.6 s)
//   frost-bench-six.json  the other six (Dragon, Sorcerer, Phoenix, Wizard, Gunslinger, Astronaut) at frost 0.8
//   node storyboards/lookdev/make-frost-bench.mjs   -> both JSONs, and the still times (printed)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
// the clip template's look (storyboards/templates/clip-template.mjs)
const SET = { type: "xmasroom", light: "golden", windows: false, aperture: 0, focus: false, bloom: "emissive", lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true };
const base = (id, title, D, camera, cast, actions) => ({
  id, title, fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, duration: D, cleanStart: true,
  rig: { hand: 2, eyes: 2, hold: 2 }, animeTiming: true,
  set: SET, music: false, sound: { sfx: 0, ambience: 0 }, creative: { length: [1, 30], notes: false },
  camera, cast, actions, notes: "Generated by storyboards/lookdev/make-frost-bench.mjs (frost bench, Survive it EP1 task T3).",
});

// the four: one step a second, a still in the middle of each; the thaw's still mid-way (melt 0.5, steam up)
export const STEPS = [
  { at: 0, frost: 0, still: 0.5, name: "frost 0" },
  { at: 1, frost: 0.3, still: 1.5, name: "frost 0.3 (DAY 2)" },
  { at: 2, frost: 0.8, still: 2.5, name: "frost 0.8 (DAY 10)" },
  { at: 3, frost: 1, still: 3.5, name: "frost 1.0 (DAY 100)" },
  // the thaw keys frost 1 -> 0.5 with melt 0 -> 1 over 0.6 s; anime timing snaps a face blend, so the bench holds the
  // half-way state itself (frost 0.75, melt 0.5)
  { at: 4, frost: 0.75, melt: 0.5, still: 4.3, name: "melt 0.5 (the thaw)" },
];
const FOUR = [["vik", "duo/viking"], ["sam", "duo/samurai"], ["rea", "never-has-money/reaper"], ["god", "potatobrawl/allfather"]];
const four = (() => {
  const cast = FOUR.map(([id, character], i) => ({ id, character, at: [-1.8 + 1.2 * i, 0.4], face: "camera", follow: 0, sway: 0.4, seed: 1.1 + i * 0.7 }));
  const actions = [];
  for (const [id] of FOUR) {
    actions.push({ who: id, at: 0, do: "noblink" });
    for (const s of STEPS) actions.push({ who: id, at: s.at, do: "face", frost: s.frost, ...(s.melt != null && { melt: s.melt }), dur: s.dur ?? 0.01 });
  }
  const shot = { pos: [0, 1.0, 9.0], look: [0, 0.7, 0.4], fov: 56 };
  return base("frost-bench", "Frost bench: the EP1 four", 5, [{ at: 0, ...shot }, { at: 5, ...shot }], cast, actions);
})();

// the six at frost 0.8: three in front, three behind and between them
// (the Astronaut stands in the back row: in this room the wall behind him draws as flat grey, frost or not, and hid
// anyone standing behind him)
const SIX = [["drg", "potatobrawl/dragon"], ["sor", "duo/sorcerer"], ["ast", "duo/astronaut"], ["wiz", "never-has-money/wizard"], ["gun", "never-has-money/gunslinger"], ["phx", "duo/phoenix"]];
const six = (() => {
  const at = [[-2.1, -0.7], [-0.7, -0.7], [0.7, -0.7], [-1.4, 0.5], [0, 0.5], [1.4, 0.5]];   // the back row between the front row's
  const cast = SIX.map(([id, character], i) => ({ id, character, at: at[i], face: "camera", follow: 0, sway: 0.4, seed: 2.1 + i * 0.6 }));
  const actions = SIX.flatMap(([id]) => [{ who: id, at: 0, do: "noblink" }, { who: id, at: 0, do: "face", frost: 0.8, dur: 0.01 }]);
  const shot = { pos: [-0.35, 1.35, 9.0], look: [-0.35, 0.7, 0], fov: 54 };
  return base("frost-bench-six", "Frost bench: the other six at frost 0.8", 2, [{ at: 0, ...shot }, { at: 2, ...shot }], cast, actions);
})();

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const sb of [four, six]) {
    const f = path.join(here, `${sb.id}.json`);
    fs.writeFileSync(f, JSON.stringify(sb, null, 1) + "\n");
    console.log(path.relative(process.cwd(), f));
  }
  console.log(`stills (four): ${STEPS.map((s) => s.still).join(",")}; stills (six): 0.5`);
}

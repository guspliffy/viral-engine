// Share or Steal prop bench (task T1, 9 Nov 2026): the game pieces of engine/page/props-sos.js on a dark plain set, no
// cast. Not a clip: a lookdev check of the table, the gold pile, the SHARE/STEAL cards, the two chairs and the two
// trapdoors at the BOARD places. The camera is wider than the brief's [0, 1.7, 4.2] fov 45: the traps (0.75 m behind
// each chair, x +-1.27) fall outside that frame. (storyboards/series/share-or-steal/01-gunslinger-viking/BOARD.md §3).
//   0.5 s  everything at rest
//   1.5 s  one card at flip 0.5 with its glow on, another face up (flip 1)
//   2.5 s  the right chair at tip 60, its trap open 1 and warn 1
//   3.5 s  the right chair back at tip 0, the trap open, steam 1 rise 1
//   node storyboards/lookdev/make-sos-bench.mjs && node engine/render.mjs storyboards/lookdev/sos-bench.json --stills beats --draft --safe
import { clip, write } from "../lib/clip.mjs";

const c = clip();
const TABLE_H = 0.62;
// the chairs and the traps (0.75 m behind each chair along its back, same rot) at the BOARD places
const place = (x, z, rot, back) => { const a = (rot * Math.PI) / 180; return [Math.round((x - back * Math.sin(a)) * 1000) / 1000, Math.round((z - back * Math.cos(a)) * 1000) / 1000]; };
const [gx, gz] = place(-0.68, -0.52, 52, 0.75), [vx, vz] = place(0.68, -0.52, -52, 0.75);
const props = [
  { id: "trapG", kind: "sstrap", x: gx, z: gz, rot: 52 },
  { id: "trapV", kind: "sstrap", x: vx, z: vz, rot: -52 },
  { id: "table", kind: "sostable", x: 0, z: 0, r: 0.46, h: TABLE_H },
  { id: "pile", kind: "goldpile", x: 0, y: TABLE_H, z: -0.15 },
  // two cards per side, one share and one steal, flat on the table top (0.012 thick: the origin is the table top)
  { id: "cL1", kind: "sscard", face: "share", x: -0.31, y: TABLE_H, z: 0.05 },
  { id: "cL2", kind: "sscard", face: "steal", x: -0.115, y: TABLE_H, z: 0.25 },
  { id: "cR1", kind: "sscard", face: "steal", x: 0.31, y: TABLE_H, z: 0.05 },
  { id: "cR2", kind: "sscard", face: "share", x: 0.115, y: TABLE_H, z: 0.25 },
  { id: "chG", kind: "sschair", x: -0.68, z: -0.52, rot: 52 },
  { id: "chV", kind: "sschair", x: 0.68, z: -0.52, rot: -52 },
];
// `warn` is not one of propState's numbers, so the first tween would step: start it at 0 so the rest glide
c.prop(0, "trapG", { warn: 0 }, 0); c.prop(0, "trapV", { warn: 0 }, 0);
// 1.5 s: cR2 (share) is half way over with its glow lit, cL2 (steal) is face up
c.prop(1.0, "cR2", { flip: 0.5, glow: 1 }, 0.5);
c.prop(1.0, "cL2", { flip: 1 }, 0.4);
// 2.5 s: the right chair leans back 60 degrees, the trap opens and warns
c.prop(2.0, "chV", { tip: 60 }, 0.5);
c.prop(2.0, "trapV", { open: 1, warn: 1 }, 0.4);
// 3.5 s: the chair is back upright (empty), the trap stays open and steam pours out
c.prop(3.0, "chV", { tip: 0 }, 0.4);
c.prop(3.0, "trapV", { warn: 0, steam: 1, rise: 1 }, 0.4);

const end = 4;
// the brief's front camera for the table beats (cards ~100 px wide); the traps (x +-1.27) fall outside it, so the
// chair and trap beats use a wider one
const SPEC = { pos: [0, 1.7, 4.2], look: [0, 0.7, -0.4], fov: 45 }, WIDE = { pos: [0, 1.8, 6.0], look: [0, 0.7, -0.4], fov: 52 };
const beats = c.beats([["rest", 0, SPEC], ["cards", 1], ["tip", 2, WIDE], ["steam", 3]], end);
write(import.meta.url, {
  id: "sos-bench", title: "Share or Steal props bench", idea: "Prop bench (task T1), not a clip: table, gold pile, cards, chairs and trapdoors",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false,
  set: { type: "plain", color: "#0c0b11", floor: "#141219", night: true, para: 0, bloom: "emissive", lighting: 2, cel: { at: 0.25 }, ink: true, satsuei: true },
  music: false, sound: { auto: false }, hook: { show: [], hint: 0, what: "prop bench" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/lookdev/make-sos-bench.mjs (prop bench, no reviews).",
});

import { clip, write } from "../lib/clip.mjs";

const OX = 400;
const c = clip();
const props = [
  { id: "st", kind: "zstairs", x: OX, y: 0, z: 0 },
  { id: "dr", kind: "zdoor", x: OX + 0.5, y: 0, z: 3.4, rot: 180 },
  { id: "z1", kind: "zshot", x: OX + 0.7, y: 1.5, z: -2.6, n: 1, seed: 3 },
  { id: "z2", kind: "zshot", x: OX - 0.65, y: 1.5, z: -3.2, rot: 35, n: 1, seed: 5 },
];
const cracks = [0, 0.5, 1, 1, 0, 0.5, 1, 0];
cracks.forEach((k, i) => {
  const t = Math.max(0, i - 0.05);   // the state is set just before the beat's still
  c.prop(t, "st", { crack: k, flash: i === 3 ? 1 : 0 }, 0.01);
  c.prop(t, "z1", { y: i >= 4 && i <= 6 ? 100 : 1.5 }, 0.01);   // camera B stands over zombie 1: it steps out of the way
});
const A = { pos: [OX + 0.7, 0.35, 2.6], look: [OX + 0.7, 2.2, -2.6], fov: 55 };
const B = { pos: [OX + 0.75, 2.6, -2.9], look: [OX + 0.5, 0.7, 3.3], fov: 55 };


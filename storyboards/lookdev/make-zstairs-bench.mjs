  props, captions: c.captions,
  beats: c.beats([
    ["A-crack0", 0, A], ["A-crack-half", 1, A], ["A-crack1", 2, A], ["A-flash", 3, A],
    ["B-crack0", 4, B], ["B-crack-half", 5, B], ["B-crack1", 6, B], ["A-dark-tick", 7, A],
  ], 8),
  notes: "Generated by storyboards/lookdev/make-zstairs-bench.mjs (engine bench, no reviews).",

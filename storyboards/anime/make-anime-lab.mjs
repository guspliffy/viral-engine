// Anime look 01 (7 Nov 2026, research/anime-look-2026-11-07): the 31 Oct living-room lab scene (Phoenix's flare singes
// Reaper) with today's template look, then the report's first test, one change at a time:
//   anime-lab-a: today (castLook "sheet", lighting 2, hatching, the template's motion and rig)
//   anime-lab-b: + "cel" (one hard shadow edge, flat tones, the clean-egg shadow shape)
//   anime-lab-c: + anime timing (snap into each key, hold it; camera and world on every frame)
// Engine test, not for posting.   node storyboards/anime/make-anime-lab.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const base = JSON.parse(fs.readFileSync(path.join(here, "../drawn/lab-today.json"), "utf8"));
const CHAR = { "duo/phoenix": "potatobrawl/phoenix", "lookdev/reaper-crisp": "potatobrawl/reaper" };
const today = {
  ...base,
  castLook: "sheet",
  cast: base.cast.map((c) => ({ ...c, character: CHAR[c.character] || c.character })),
  set: { ...base.set, lighting: 2, hatch: { boil: 0.25 } },
  motion: { feet: 2, overlap: true, timing: true, solve: true },
  rig: { hand: 2, eyes: 2, hold: 2 },
  notes: "Generated by storyboards/anime/make-anime-lab.mjs (anime look 01, engine test, not for posting).",
};
const V = {
  a: { ...today, id: "anime-lab-a", title: "Anime look: today" },
  b: { ...today, id: "anime-lab-b", title: "Anime look: cel", set: { ...today.set, cel: { at: 0.25 } } },
  c: { ...today, id: "anime-lab-c", title: "Anime look: cel + anime timing", set: { ...today.set, cel: { at: 0.25 } }, animeTiming: true },
};
for (const [k, sb] of Object.entries(V)) {
  const f = path.join(here, `anime-lab-${k}.json`);
  fs.writeFileSync(f, JSON.stringify(sb, null, 1) + "\n");
  console.log("wrote", path.relative(process.cwd(), f));
}

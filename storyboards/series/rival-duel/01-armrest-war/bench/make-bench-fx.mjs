// Rival duel 01 armrest war: BENCH for engine/page/props-armrest-fx.js (builder B). Not a clip: a look bench judged from draft stills.
// One beat per key state, one second each, a still at beat start + 0.2 (STILLS below). Kinds stand far apart (x -30 hatch, -20 rocket,
// 0 Wedge on a seat, 10 bag and hat, 20 cockpit) on a plain floor.
//   node storyboards/series/rival-duel/01-armrest-war/bench/make-bench-fx.mjs
//   node engine/render.mjs storyboards/series/rival-duel/01-armrest-war/bench/armrest-fx-bench.json --stills <STILLS> --draft --silent
//   node qa/contact.mjs out/armrest-fx-bench-*-t*.png --out storyboards/series/rival-duel/01-armrest-war/bench/armrest-fx-sheet.png
import { clip, write } from "../../../../lib/clip.mjs";

const c = clip(), { A } = c;
const SEAT = 0.3;   // a seated potato rides 0.30 up (DESIGN.md rules)
const props = [
  { id: "hatch", kind: "ejecthatch", x: -30, y: 2.35, z: 0.05, staged: "bench: hung on a bin that is not drawn" },
  { id: "rocket", kind: "seatrocket", x: -20, y: 1.2, z: 0, staged: "bench: raised so the nozzle shows above the floor" },
  { id: "seat", kind: "planeseat", w: 0.96, arms: "none", color: "#2f4d8c", cover: 0.34, x: 0, y: 0, z: 0 },
  { id: "seatC", kind: "carrier", x: 0, y: 0, z: 0 },
  { id: "mask", kind: "sleepmask", wear: "wedge", x: 0, y: 0, z: 0, scale: 1 },
  { id: "pin", kind: "wingspin", wear: "wedge", x: 0, y: 0, z: 0 },
  { id: "bag", kind: "duffel", color: "#a8352b", trim: "#c9a25a", x: 10, y: 0.13, z: 0.62 },
  { id: "hat", kind: "pilothat", x: 10, y: 0.255, z: 0.62, staged: "in the bag" },
  { id: "card", kind: "cockpitcard", x: 20, y: 0, z: 0, rot: 0 },
];
const cast = [{ id: "wedge", character: "potatobrawl/wedge", at: [0, 0], face: 0, expr: "kind" }];
A(0, "wedge", "ride", { prop: "seatC", off: [0, SEAT, 0], yaw: 0, sit: true, dur: 0 });
A(0, "wedge", "noblink");
for (const side of ["R", "L"]) c.arm(0, "wedge", side, "lap", 0.01);

// the beats: [name, camera]. States are set at the beat's start (dur 0.01).
const T = (i) => i;
c.prop(T(0), "pin", { show: 1 }, 0.01);
const S = {};   // name -> beat index
const shots = [];
const beat = (name, cam, fn) => { const i = shots.length; S[name] = i; shots.push([name, T(i), cam]); if (fn) fn(T(i)); };
// hatch
const HC = { pos: [-29.2, 1.0, 3.0], look: [-30.0, 1.7, 0.05], fov: 62 };
beat("hatch-0", HC, (t) => c.prop(t, "hatch", { hatch: 0 }, 0.01));
beat("hatch-05", HC, (t) => c.prop(t, "hatch", { hatch: 0.5 }, 0.01));
beat("hatch-1", HC, (t) => c.prop(t, "hatch", { hatch: 1 }, 0.01));
beat("hatch-1-floor", { pos: [-28.6, 0.9, 3.4], look: [-30.2, 0.4, 0.0], fov: 56 });
beat("hatch-1-below", { pos: [-30.2, 0.2, 1.2], look: [-30.0, 2.3, 0.05], fov: 70 });
// rocket
const RC = { pos: [-18.7, 0.95, 1.5], look: [-20, 0.85, 0], fov: 40 };
beat("rocket-0", RC, (t) => c.prop(t, "rocket", { flame: 0 }, 0.01));
beat("rocket-1", RC, (t) => c.prop(t, "rocket", { flame: 1 }, 0.01));
beat("rocket-half", RC, (t) => c.prop(t, "rocket", { flame: 0.5 }, 0.01));
// Wedge: mask and pin
c.prop(T(shots.length), "mask", { scale: 1 }, 0.01);
beat("mask-front", { pos: [0, 1.0, 2.6], look: [0, 0.95, 0], fov: 34 }, (t) => A(t, "wedge", "expr", { expr: "serene", set: { open: 0.35 }, dur: 0 }));
beat("mask-34", { pos: [1.7, 1.1, 2.1], look: [0, 0.95, 0], fov: 34 });
beat("mask-lean15", { pos: [0.6, 1.05, 2.6], look: [0, 0.95, 0], fov: 34 }, (t) => A(t - 0.5, "wedge", "lean", { to: 15, dur: 0.3 }));
beat("mask-lean15-34", { pos: [1.7, 1.1, 2.1], look: [0.1, 0.95, 0], fov: 34 });
beat("pin-front", { pos: [0.3, 0.8, 2.0], look: [0.17, 0.72, 0], fov: 18 }, (t) => A(t - 0.5, "wedge", "lean", { to: 0, dur: 0.3 }));
beat("pin-34", { pos: [1.3, 0.85, 1.8], look: [0.17, 0.72, 0], fov: 18 });
beat("wedge-c2", { pos: [0, 1.1, 3.3], look: [0, 0.92, 0], fov: 46 });
// the hat in the bag
beat("hat-c2", { pos: [9.59, 1.1, 3.3], look: [9.59, 0.92, 0], fov: 46 });
beat("hat-low", { pos: [10.0, 0.3, 1.7], look: [10.0, 0.25, 0.62], fov: 40 });
beat("hat-close", { pos: [10.0, 0.75, 1.5], look: [10.0, 0.22, 0.62], fov: 34 });
// the cockpit
beat("cockpit", { pos: [20, 1.0, 3.2], look: [20, 1.0, 0], fov: 56 });
const END = shots.length + 0.5;

write(import.meta.url, {
  id: "armrest-fx-bench", title: "Armrest war fx bench", idea: "Look bench for props-armrest-fx.js, not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false,
  set: { type: "plain", color: "#c3ccd0", floor: "#97a3a8" }, music: false, sound: { auto: false },
  hook: { show: ["wedge"], hint: 0, what: "engine bench" },
  cast, props, captions: c.captions, beats: c.beats(shots, END), visible: c.visible,
  notes: "Generated by make-bench-fx.mjs (engine bench, no reviews).",
});
console.log("beats:", shots.map(([n, t]) => `${t}:${n}`).join(" "));
console.log("stills:", shots.map(([, t]) => (t + 0.2).toFixed(1)).join(","));

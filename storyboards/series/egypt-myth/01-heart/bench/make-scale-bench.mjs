//   feather the feather pan from above, the feather in the dish   feather2 the feather closer, from the front and above
//   under   the heart pan seen from below (16 petals, 60 beads, chain lugs)   splat  the same with smear 1 (9 splats on the petals)   pool  from above, smear 1 (the dish pool, 6 seeds)
//   smear   JUICE on the heart pan (smear 1), close   smear2  the same low from the side at tilt -0.8 (panel 02), drip 1

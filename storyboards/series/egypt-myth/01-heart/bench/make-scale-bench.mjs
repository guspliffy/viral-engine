import { clip, write } from "../../../../lib/clip.mjs";

const c = clip();
const seat = (tilt) => { const a = Math.asin(0.633 * tilt); return [-1.5 * Math.cos(a), 1.03 + 0.95 * tilt]; };   // the heart seat S (header of props-heart-scale.js)
const r3 = (x) => Math.round(x * 1000) / 1000;
const props = [
  { id: "sc", kind: "heartscale", x: 0, y: 0, z: 0, seed: 1 },
  { id: "heart", kind: "apple", x: seat(0)[0], y: seat(0)[1] + 0.10, z: 0, scale: 1.43 },   // placeholder: a 0.20 m red sphere
];
c.prop(0, "sc", { smear: 0, drip: 0, jolt: 0 }, 0);

const FULL = { pos: [0, 1.9, 12.2], look: [0, 1.9, 0], fov: 34 };
const shots = [
  ["full0", 0, FULL, 0], ["fullA", 1.1, FULL, -0.4], ["fullB", 2.2, FULL, -0.8], ["fullC", 3.3, FULL, 0.3],
  ["pan04", 4.4, { pos: [-1.5, 1.1, 3.4], look: [-1.5, 1.15, 0], fov: 30 }, 0],
  ["pan04b", 5.5, { pos: [-1.5, 0.9, 3.4], look: [-1.4, 1.05, 0], fov: 30 }, -0.4],
  ["feather", 6.6, { pos: [1.3, 1.95, 1.5], look: [1.5, 1.08, 0.1], fov: 38 }, 0],
  ["feather2", 7.7, { pos: [1.5, 1.65, 0.95], look: [1.5, 1.0, 0.14], fov: 26 }, 0],
  ["smear", 8.8, { pos: [-1.9, 1.5, 1.9], look: [-1.45, 1.0, 0.1], fov: 34 }, 0, 1],
  ["smear2", 9.9, { pos: [-2.0, 0.55, 1.7], look: [-1.25, 0.28, 0.1], fov: 34 }, -0.8, 1],
  ["under", 11.0, { pos: [-1.5, 0.30, 1.7], look: [-1.5, 1.0, 0.0], fov: 32 }, 0],
  ["splat", 12.1, { pos: [-1.5, 0.30, 1.7], look: [-1.5, 1.0, 0.0], fov: 32 }, 0, 1],
  ["pool", 13.2, { pos: [-1.55, 2.35, 0.95], look: [-1.5, 1.04, 0.05], fov: 30 }, 0, 1],
  ["top", 14.3, { pos: [0, 3.1, 5.0], look: [0, 3.1, 0], fov: 30 }, 0],
  ["base", 15.4, { pos: [0, 0.8, 4.6], look: [0, 0.8, 0], fov: 30 }, 0],
  ["claw", 16.5, { pos: [-1.35, 2.95, 1.45], look: [-1.5, 2.9, 0], fov: 26 }, 0],
];
const times = [];
for (const [name, at, , tilt, smear] of shots) {
  const [sx, sy] = seat(tilt);
  c.prop(at, "sc", { tilt, smear: smear ?? 0, drip: smear ? 1 : 0 }, 0);
  c.prop(at, "heart", { x: r3(sx), y: r3(sy + 0.10) }, 0);
  times.push(r3(at + 0.4));
}
const end = 17.6;
const sb = {
  id: "scale-bench", title: "Egypt myth 01: the scale bench", idea: "Engine look bench for the heartscale kind (DESIGN B), not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, motion: "natural",
  set: { type: "plain", color: "#2a2230", floor: "#1c1b22", light: "soft", para: 0, aperture: 0, lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true },
  music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine bench" },
  cast: [],
  props, captions: c.captions,
  beats: c.beats(shots.map(([n, at, cam]) => [n, at, cam]), end),
  notes: "Generated by storyboards/series/egypt-myth/01-heart/bench/make-scale-bench.mjs (engine bench, no story).",
};
console.log("stills:", times.join(","));
write(import.meta.url, sb);

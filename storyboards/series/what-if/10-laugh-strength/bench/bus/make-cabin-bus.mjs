// Bench for the cabin bus (engine/page/props-cabinbus.js, kind "bus" with cabin: true) on the "street" set. Not a clip.
// The bus (scale 1.8, open 1) stands at its stopped mark; Chip and Wedge ride it at the DESIGN-STREET offsets; from 1.0 to 1.5 s it is
// lifted level by 1.21 m. Two storyboards, one per camera (HERO and SIDE), 2.5 s each; stills at 0.5 and 2.0 s.
//   node storyboards/series/what-if/10-laugh-strength/bench/bus/make-cabin-bus.mjs
//   for n in cabin-bus cabin-bus-side; do node engine/render.mjs <this dir>/$n.json --stills 0.5,2.0 --draft --safe; done
//   node qa/contact.mjs out/cabin-bus-*.png out/cabin-bus-side-*.png --out <this dir>/cabin-bus-sheet.png
import { clip, write } from "../../../../../lib/clip.mjs";

const CAMS = {
  "cabin-bus": { pos: [11.0, 0.35, -1.45], look: [-1.0, 1.93, -2.35], fov: 27 },        // HERO
  "cabin-bus-side": { pos: [0, 1.5, 7], look: [-1.5, 1.4, -1.45], fov: 40 },            // SIDE
};
const BUS = [-0.55, -0.12, -1.45], S = 1.8, CHIP = [0.38, 0.75, -0.27], WEDGE = [0.30, 0.62, -0.66];
for (const [id, cam] of Object.entries(CAMS)) {
  const c = clip();
  c.A(0, "chip", "ride", { prop: "bus", off: CHIP, yaw: 90, dur: 0 });
  c.A(0, "wedge", "ride", { prop: "bus", off: WEDGE, yaw: 90, dur: 0 });
  c.prop(1.0, "bus", { y: BUS[1] + 1.21 }, 0.5);
  const beats = c.beats([["cabin", 0, cam, "bench"]], 2.5);
  write(import.meta.url, {
    id, title: "EP10 cabin bus bench", idea: "Props bench for the cabin bus (bus, cabin: true), not a clip",
    fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet",
    motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false,
    set: { type: "street", parking: false }, hud: { sky: false }, music: false, sound: { auto: false },
    cast: [
      { id: "chip", character: "potatobrawl/chip", at: [BUS[0] + CHIP[0] * S, BUS[2] + CHIP[2] * S], face: 90, expr: "delighted", seed: 2.3 },
      { id: "wedge", character: "potatobrawl/wedge", at: [BUS[0] + WEDGE[0] * S, BUS[2] + WEDGE[2] * S], face: 90, expr: "delighted", seed: 3.1 },
    ],
    props: [{ id: "bus", kind: "bus", cabin: true, open: 1, x: BUS[0], y: BUS[1], z: BUS[2], scale: S }],
    captions: c.captions, beats,
    notes: "Generated by storyboards/series/what-if/10-laugh-strength/bench/bus/make-cabin-bus.mjs (props bench, no reviews).",
  });
}

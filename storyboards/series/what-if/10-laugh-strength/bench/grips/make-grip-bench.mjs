// Grip bench for the two new holds (storyboards/lib/grips.mjs bar and underpad), There's a catch 10, laugh strength: Spud alone in the gym
// takes the prop, lifts it, holds it. One storyboard per pose and per camera (wide = the clip's wide, close = a close camera on the hands):
//   node storyboards/series/what-if/10-laugh-strength/bench/grips/make-grip-bench.mjs
// poses: hip (two-hand overhand deadlift hold, bar centre (0.76, 0.52, -0.60)), over (two-hand press, bar to y 1.35), one (one hand, bar to y 1.35),
// bench (underpad, bench feet 0.80 -> 1.02, pad top 1.22 -> 1.44). Env: DY, DZ nudge the bar fists; LIFT the underpad gloves' depth.
import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import * as grips from "../../../../../lib/grips.mjs";

const num = (k, d) => (process.env[k] != null ? +process.env[k] : d);
const BAR = { id: "bar", kind: "barbell", plates: 0 }, BENCH = { id: "bench", kind: "weightbench" };
const SPUD = [0.76, -1.02], BSPUD = [-0.57, -1.0];
const WIDE = { pos: [0.06, 1.62, 7.85], look: [0.06, 1.62, -1], fov: 36 };
// the close camera: three-quarter from the front right, level with the prop's hold height
const closeCam = (P) => ({ pos: [P.to[0] + 0.9, (P.hy ?? P.to[1]) + 0.15, P.to[2] + 2.6], look: [P.to[0], (P.hy ?? P.to[1]) - 0.15, P.to[2]], fov: 34 });
// the side camera (from the holder's right, level with the hold, close on one fist)
const sideCam = (P) => ({ pos: [P.to[0] - 2.4, (P.hy ?? P.to[1]) + 0.05, P.to[2] + 0.4], look: [P.to[0] - (P.side ?? 0.3), (P.hy ?? P.to[1]), P.to[2]], fov: 18 });
const POSES = {
  hip: { at: [0.76, 0.52, -0.6], to: [0.76, 0.57, -0.6], who: SPUD, hold: (c, p) => grips.bar(c, "spud", p, { dy: num("DY", 0), dz: num("DZ", 0) }) },
  over: { at: [0.76, 0.52, -0.6], to: [0.76, 1.35, -0.6], who: SPUD, hold: (c, p) => grips.bar(c, "spud", p, { under: true, dy: num("DY", 0), dz: num("DZ", 0) }) },
  one: { at: [0.52, 0.52, -0.6], to: [0.52, 1.35, -0.6], who: SPUD, hold: (c, p) => grips.bar(c, "spud", p, { side: "R", under: true, dy: num("DY", 0), dz: num("DZ", 0) }) },
  bench: { at: [-0.57, 0.8, -1.0], to: [-0.57, 1.02, -1.0], hy: 1.33, who: BSPUD, crouch: 1.1, hold: (c, p) => grips.underpad(c, "spud", p, { lift: num("LIFT", 0.025), ...(process.env.DZ != null && { dz: +process.env.DZ }), ...(process.env.GX != null && { gx: +process.env.GX }) }) },
};

for (const [name, P] of Object.entries(POSES)) for (const view of ["", "-close", "-side"]) {
  const c = clip(), { A } = c, isBar = name !== "bench";
  const spec = { ...(isBar ? BAR : BENCH), staged: "grip bench: the prop waits in the air for the hand", ...grips.placeFor(isBar ? "barbell" : "weightbench", P.at, 0) };
  const h = P.hold(c, spec);
  A(0, "spud", "noblink");
  A(0, "spud", "look", { to: [0, 0.1], dur: 0.01, blink: false });
  if (P.crouch) A(0, "spud", "crouch", { to: P.crouch, dur: 0.01 });
  A(0.2, "spud", "look", { to: [0, -0.2], dur: 0.15, blink: false });
  let t = h.take(0.35, { reach: 0.5 });                                       // approach + secure
  if (name === "hip") { t = h.carry(t + 0.1, P.to, 0.3); t = h.carry(t + 0.1, P.at, 0.4); t += 0.6; }   // a heave and it sinks back
  else {
    t = h.carry(t + 0.1, P.to, 1.0);                          // lift
    if (P.crouch) A(t - 1.0, "spud", "crouch", { to: 0, dur: 1.0 });
    t += 0.8;                                                 // hold
  }
  const end = Math.ceil((t + 0.2) * 10) / 10;
  write(import.meta.url, {
    id: `bench-${name}${view}`, title: `Grip bench: ${name}`, idea: "Grip bench for catch 10, not a clip",
    fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", rig: { hand: 2, eyes: 2, hold: 2 }, physics: true,
    set: { type: "gym", seed: 6 }, music: false, sound: { auto: false },
    hook: { show: ["spud", spec.id], hint: 0, what: "grip test" },
    cast: [{ id: "spud", character: "potatobrawl/spud", at: P.who, face: 0, expr: "kind", follow: 0.2, seed: 1.3 }],
    props: [spec], captions: c.captions, beats: c.beats([[name, 0, view === "-close" ? closeCam(P) : view === "-side" ? sideCam(P) : WIDE]], end),
    notes: "Generated by bench/grips/make-grip-bench.mjs (engine test, no reviews).",
  });
}

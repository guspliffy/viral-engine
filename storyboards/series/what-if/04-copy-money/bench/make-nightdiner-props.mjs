// Bench for the night-ending props (engine/page/props-nightdiner.js, task T4 of storyboards/series/what-if/04-copy-money/BRIEF-T4.md):
// the dark diner front in the snow and the oil barrel fire, on a plain night set with Gunslinger and Reaper either side
// of the barrel. Eight stills, 1 s apart, each taken 0.6 s into its beat: camera A (wide, 9.7 m) and camera B (6.1 m)
// with fire 1 at two clock values, feed 0 and 1, flicker 0 and 1. Not a clip.
//   still 1  A  clock 0.35  feed 0  flicker 0      still 5  B  clock 0.35  feed 0  flicker 0
//   still 2  A  clock 0.95  feed 0  flicker 1      still 6  B  clock 0.95  feed 0  flicker 1
//   still 3  A  clock 0.35  feed 1  flicker 0      still 7  B  clock 0.35  feed 1  flicker 0
//   still 4  A  clock 0.95  feed 1  flicker 1      still 8  B  clock 0.95  feed 1  flicker 1
//   node storyboards/series/what-if/04-copy-money/bench/make-nightdiner-props.mjs
//   node engine/render.mjs storyboards/series/what-if/04-copy-money/bench/nightdiner-props.json --stills 0.6,1.6,2.6,3.6,4.6,5.6,6.6,7.6 --draft --out <dir>
//   node qa/contact.mjs <dir>/nightdiner-props-*.png --out storyboards/series/what-if/04-copy-money/bench/nightdiner-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const END = 8.0;
const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };

const CAM_A = { pos: [0.3, 1.5, 9.7], look: [0.3, 0.82, 2.0], fov: 48 };
const CAM_B = { pos: [-0.1, 1.2, 6.1], look: [-0.15, 0.82, 2.0], fov: 36 };
// [camera, clock, feed, flicker, label]
const SHOTS = [
  ["A", 0.35, 0, 0, "camera A, clock 0.35, feed 0, flicker 0"],
  ["A", 0.95, 0, 1, "camera A, clock 0.95, feed 0, flicker 1"],
  ["A", 0.35, 1, 0, "camera A, clock 0.35, feed 1, flicker 0"],
  ["A", 0.95, 1, 1, "camera A, clock 0.95, feed 1, flicker 1"],
  ["B", 0.35, 0, 0, "camera B, clock 0.35, feed 0, flicker 0"],
  ["B", 0.95, 0, 1, "camera B, clock 0.95, feed 0, flicker 1"],
  ["B", 0.35, 1, 0, "camera B, clock 0.35, feed 1, flicker 0"],
  ["B", 0.95, 1, 1, "camera B, clock 0.95, feed 1, flicker 1"],
];

const FRONT = { id: "front", kind: "dinerfront", x: 0, y: 0, z: 0, rot: 0, w: 9, d: 9 };
const BARREL = { id: "barrel", kind: "oilbarrel", x: 0.25, y: 0, z: 2.4, rot: 0, glow: 1, feed: 0 };
// seed the keys propState has no default for (and fire, whose default is 0), then one jump per beat
c.prop(0, "barrel", { fire: 1, clock: 0.35, feed: 0, glow: 1 }, 0, "linear");
c.prop(0, "front", { flicker: 0 }, 0, "linear");
SHOTS.forEach(([, clock, feed, flicker], i) => {
  c.prop(i + 0.01, "barrel", { clock, feed }, 0, "linear");
  c.prop(i + 0.01, "front", { flicker }, 0, "linear");
});

const cast = [
  { id: "gsl", character: "never-has-money/gunslinger", at: [-0.75, 2.0], face: 0, expr: "kind", follow: 0.2, seed: 2.6 },
  { id: "rea", character: "never-has-money/reaper", at: [1.35, 2.25], face: 0, expr: "kind", follow: 0.2, seed: 1.4 },
];
for (const w of ["gsl", "rea"]) c.A(0, w, "look", { to: [0, 0.1], dur: 0.01, blink: false });

const beats = c.beats(SHOTS.map(([cam, , , , label], i) => [`${cam.toLowerCase()}${i + 1}`, i, cam === "A" ? CAM_A : CAM_B, label]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "nightdiner-props", title: "Night diner props bench", idea: "Props bench for There's a catch EP04 (dinerfront, oilbarrel), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
  set: { type: "plain", color: "#0e1630", floor: "#161c2c" }, sky: [[0, 1]], music: false, sound: { auto: false },
  hook: { show: ["gsl", "barrel"], hint: 0, what: "engine test" },
  cast, props: [FRONT, BARREL], captions: c.captions, beats,
  notes: "Generated by storyboards/series/what-if/04-copy-money/bench/make-nightdiner-props.mjs (props bench, no reviews).",
});

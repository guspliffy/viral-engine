// Step 1 of T2 (DESIGN 3.5): does a prop param tween still run inside a "pause" window? A pocketwatch (hands) and a
// rainbox (time) are tweened over 0..2 s; a pause (no keeper, look none) covers 0.5..1.7 s. Stills at 0.6, 1.1, 1.6:
// if the params are frozen inside the pause, the three stills are identical.
//   node storyboards/series/what-if/07-fire-rewind/bench/make-pause-tween-test.mjs   -> pause-tween-test.json
//   node engine/render.mjs <that json> --stills 0.6,1.1,1.6 --draft --safe --silent
import { clip, write } from "../../../../lib/clip.mjs";

const c = clip(), { prop } = c;
const props = [
  { id: "w", kind: "pocketwatch", x: 0, y: 1.0, z: 0, scale: 6 },
  { id: "r", kind: "rainbox", x: 0, y: 0, z: -1, box: [4, 3, 3] },
];
prop(0, "w", { hands: 0 }, 0); prop(0, "r", { time: 0 }, 0);
prop(0, "w", { hands: 1.5 }, 2); prop(0, "r", { time: 6 }, 2);
write(import.meta.url, {
  id: "pause-tween-test", title: "pause tween test", idea: "T2 step 1: a prop tween inside a pause, not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, music: false, sound: { auto: false, sfx: 0, ambience: 0, speech: false }, cleanStart: true,
  set: { type: "snowslope", dark: 0, windows: false, aperture: 0, focus: false, lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 } },
  hook: { show: [], hint: 0, what: "engine test" }, cast: [], props,
  pause: [{ from: 0.5, to: 1.7, keep: [], look: "none" }],
  captions: c.captions, beats: c.beats([["watch", 0, { pos: [0, 1.0, 2.6], look: [0, 1.0, 0], fov: 40 }]], 2),
  notes: "Test only. Generated by make-pause-tween-test.mjs (T2 step 1).",
});

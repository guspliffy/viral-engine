const T = { s03: 0, s06: 1, s10: 2, close: 3, ring: 4, ringlow: 5.5, ringfade: 6 }, END = 7;

const props = [
  // the library: the clip's floor, Reaper's table and chair, two reading tables, the dais and the issue desk
  { id: "floor", kind: "libfloor", x: 0, z: -1, w: 18, d: 22, seed: 21 },
  { id: "table", kind: "table", x: -0.7, z: 0, w: 1.7, d: 0.8, color: "#7a4a2c", legs: "#4e2e1a" },
  { id: "chairR", kind: "chair", x: 0.05, z: -0.72, rot: 0, scale: 0.7 },
  { id: "t20", kind: "table", x: -3.4, z: -2.2, w: 1.5, d: 0.8, color: "#7a4a2c", legs: "#4e2e1a" },
  { id: "t21", kind: "table", x: 2.9, z: -1.2, w: 1.5, d: 0.8, color: "#7a4a2c", legs: "#4e2e1a" },
  { id: "dais", kind: "libdais", x: -0.4, z: -5.35, w: 2.4, d: 1.6, h: 0.5 },
  { id: "desk", kind: "libdesk", x: -0.4, y: 0.5, z: -5, w: 2, h: 0.45 },
  { id: "streak", kind: "flamestreak", path: PATH, len: 1.6, ghosts: 3, seed: 1 },
  { id: "ring", kind: "flamering", x: RING[0], z: RING[2], rx: 1.8, rz: 1.3, seed: 1, fade: 1 },
];

c.prop(T.s03, "streak", { t: 0.3 }, 0, "linear");
c.prop(T.s06, "streak", { t: 0.6 }, 0, "linear");
c.prop(T.s10, "streak", { t: 1.0 }, 0, "linear");
c.prop(T.close, "streak", { t: 0.6 }, 0, "linear");
c.prop(T.ring, "streak", { fade: 1 }, 0, "linear");

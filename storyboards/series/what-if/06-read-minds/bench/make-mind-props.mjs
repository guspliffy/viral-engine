// Bench for the mind props (engine/page/props-mind.js, task T2 of storyboards/series/what-if/06-read-minds/BRIEF-T2.md):
// thoughtbubble (23 objects, three pops), bubblefield (n 150 day and night, n 600 with a pull, n 0 for the timing) and eyeglow on
// Spud from the front and at yaw 30. Writes mind-props.json (dark red night set) and mind-day.json (daylight set). Not a clip.
//   node storyboards/series/what-if/06-read-minds/bench/make-mind-props.mjs
//   node engine/render.mjs storyboards/series/what-if/06-read-minds/bench/mind-props.json --stills 0.5,1.5,2.5,3.5,4.5,5.5,6.5,7.5 --draft --safe --out <dir>
//   node engine/render.mjs storyboards/series/what-if/06-read-minds/bench/mind-day.json --stills 0.5 --draft --safe --out <dir>
//   node qa/contact.mjs <dir>/mind-props-*.png --out storyboards/series/what-if/06-read-minds/bench/mind-sheet.png
// stills (night): 1 object grid, 2 pops 0.05 / 0.5 / 1, 3 field n150 glow 1, 4 field n600 pull 0.6, 5 field n0 (timing), 6 field n600
// fill 1 (timing), 7 Spud eyeglow front, 8 Spud eyeglow yaw 30. (day): the field n150 fill 1 glow 0.
import { clip, write } from "../../../../lib/clip.mjs";

const OBJS = ["cards27", "aces", "pizza", "phone", "shoe", "fish", "clock", "heart", "sandwich", "football", "coin", "crown", "gift", "book", "car", "guitar", "camera", "watch", "burger", "cat", "bag", "cake", "plane"];
const EYE = JSON.parse(process.env.EYE || "[0,0.61,0.36]"), EYE30 = JSON.parse(process.env.EYE30 || JSON.stringify(EYE));
const RIG = { hand: 2, eyes: 2, hold: 2 }, MOTION = { feet: 2, overlap: true, timing: true, solve: true };

function build(day) {
  const c = clip();
  const props = [];
  OBJS.forEach((o, i) => props.push({ id: `b-${o}`, kind: "thoughtbubble", obj: o, r: 0.2, x: -0.78 + (i % 4) * 0.52, y: 3.35 - Math.floor(i / 4) * 0.55, z: 0, pop: 1, seed: i }));
  for (const [i, p] of [0.05, 0.5, 1].entries()) props.push({ id: `pop${i}`, kind: "thoughtbubble", obj: "pizza", r: 0.2, x: 20 + (i - 1) * 0.5, y: 1.4, z: 0, pop: p, seed: 3 });
  props.push({ id: "f150", kind: "bubblefield", n: 150, w: 4, h: 3, d: 4, x: 40, y: 0, z: 0, fill: 1, glow: day ? 0 : 1, seed: 1 });
  props.push({ id: "f600", kind: "bubblefield", n: 600, w: 4, h: 3, d: 4, x: 60, y: 0, z: 0, fill: 1, glow: 1, pull: 0.6, to: [1.2, 1.6, -1.5], seed: 2 });
  props.push({ id: "f0", kind: "bubblefield", n: 0, w: 4, h: 3, d: 4, x: 80, y: 0, z: 0, fill: 1, glow: 1, seed: 3 });
  props.push({ id: "f600b", kind: "bubblefield", n: 600, w: 4, h: 3, d: 4, x: 80, y: 0, z: 0, fill: 1, glow: 1, seed: 2, scale: 0 });
  props.push({ id: "eg1", kind: "eyeglow", wear: "spud", x: EYE[0], y: EYE[1], z: EYE[2], on: 1, pulse: 0, gap: 0.2 });
  props.push({ id: "eg2", kind: "eyeglow", wear: "spud2", x: EYE30[0], y: EYE30[1], z: EYE30[2], on: 1, pulse: 0, gap: 0.2 });
  c.prop(0, "eg1", { on: 1 }, 0, "linear"); c.prop(0, "eg2", { on: 1 }, 0, "linear");
  // still 6 (t 5.5) swaps the empty field for the full one at the same spot
  c.prop(5.2, "f600b", { scale: 1 }, 0, "linear");
  const dist = (d, y, x, fov = 40) => ({ pos: [x, y, d], look: [x, y, 0], fov });
  const CAMS = [
    ["grid", 0, { pos: [0, 2.2, 6.6], look: [0, 2.2, 0], fov: 40 }, "all 23 objects"],
    ["pops", 1, { pos: [20, 1.4, 4.2], look: [20, 1.4, 0], fov: 40 }, "pop 0.05, 0.5, 1"],
    ["f150", 2, { pos: [40, 1.5, 10], look: [40, 1.5, 0], fov: 40 }, "n 150 fill 1"],
    ["f600p", 3, { pos: [60, 1.5, 10], look: [60, 1.5, 0], fov: 40 }, "n 600 pull 0.6"],
    ["f0", 4, { pos: [80, 1.5, 10], look: [80, 1.5, 0], fov: 40 }, "n 0"],
    ["f600", 5, { pos: [80, 1.5, 10], look: [80, 1.5, 0], fov: 40 }, "n 600"],
    ["eye0", 6, { pos: [100, 0.6, 2.6], look: [100, 0.58, 0], fov: 30 }, "eyeglow front"],
    ["eye30", 7, { pos: [102, 0.6, 2.6], look: [102, 0.58, 0], fov: 30 }, "eyeglow yaw 30"],
  ];
  void dist;
  const beats = c.beats(CAMS.map(([id, t, cam, l]) => [id, t, cam, l]), 8);
  const cast = [
    { id: "spud", character: "potatobrawl/spud", at: [100, 0], face: 0, expr: "kind", follow: 0.2, seed: 1 },
    { id: "spud2", character: "potatobrawl/spud", at: [102, 0], face: 30, expr: "kind", follow: 0.2, seed: 2 },
  ];
  for (const w of ["spud", "spud2"]) c.A(0, w, "look", { to: [0, 0.1], dur: 0.01, blink: false });
  write(import.meta.url, {
    id: day ? "mind-day" : "mind-props", title: "Mind props bench", idea: "Props bench for There's a catch EP06 (thoughtbubble, bubblefield, eyeglow), not a clip",
    fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
    set: day ? { type: "plain", color: "#bfe0f2", floor: "#b9a98a" } : { type: "plain", color: "#3a0c14", floor: "#2a0810" }, sky: [[0, 1]], music: false, sound: { auto: false },
    hook: { show: ["spud", "b-pizza"], hint: 0, what: "engine test" },
    cast, props, captions: c.captions, beats, notes: "Generated by make-mind-props.mjs (props bench, no reviews).",
  });
}
build(false);
build(true);

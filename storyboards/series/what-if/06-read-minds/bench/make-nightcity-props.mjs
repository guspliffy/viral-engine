// Bench for the night city props (engine/page/props-nightcity.js, task T3 of storyboards/series/what-if/06-read-minds/BRIEF-T3.md).
// Two storyboards (not clips): nightcity-props.json (the neoncity from 40 m above the casino looking out, then straight
// down on the dome) and nighthotel-props.json (the hotel room from the front, a nightskyline behind its window, Spud
// sitting up in the bed with the hotelpillow on his head). The in-hand proof of the pillow is made by
//   node storyboards/lookdev/make-grip-tests.mjs --prop hotelpillow --hold box
//   node storyboards/series/what-if/06-read-minds/bench/make-nightcity-props.mjs
//   node engine/render.mjs storyboards/series/what-if/06-read-minds/bench/nightcity-props.json --stills 0.6,1.6 --draft --safe
//   node engine/render.mjs storyboards/series/what-if/06-read-minds/bench/nighthotel-props.json --stills 2.4 --draft --safe
//   node qa/contact.mjs out/nightcity-props-*.png out/nighthotel-props-*.png --out storyboards/series/what-if/06-read-minds/bench/nightcity-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";
import * as grips from "../../../../lib/grips.mjs";

const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const common = { fps: 30, look: "anime-pro", profile: "short", loop: false, motion: MOTION, rig: RIG, physics: false, music: false, sound: { auto: false } };

// ---- the city: two beats
{
  const c = clip();
  const A = { pos: [0, 40, 25], look: [0, 10, -40], fov: 55 }, B = { pos: [0, 50, 0.01], look: [0, 14, 0], fov: 55 }, F = { pos: [0, 9, 44], look: [0, 9, 0], fov: 50 };
  const beats = c.beats([["above", 0, A, "from 40 m above the casino"], ["down", 1, B, "straight down on the dome"], ["front", 2, F, "casino front from the plaza"]], 3.4);
  write(import.meta.url, {
    id: "nightcity-props", title: "Night city props bench", idea: "Props bench for There's a catch EP06 (neoncity), not a clip", ...common,
    castLook: "sheet", set: { type: "plain", color: "#05081e", floor: "none" },
    hook: { show: ["city"], hint: 0, what: "engine test" },
    cast: [], props: [{ id: "city", kind: "neoncity", x: 0, y: 0, z: 0, rot: 0, w: 120, d: 120, casino: [0, 0] }], captions: c.captions, beats,
    notes: "Generated by storyboards/series/what-if/06-read-minds/bench/make-nightcity-props.mjs (props bench, no reviews).",
  });
}

// ---- the hotel room: Spud sits up in the bed and holds the pillow on his head
{
  const c = clip(), { A } = c;
  const CAM = { pos: [0, 1.4, 4.5], look: [0, 1, -1], fov: 50 };
  const BED = [-0.2, -1.25];
  const spec = { id: "pil", kind: "hotelpillow", ...grips.placeFor("hotelpillow", [0.55, 0.585, BED[1] + 0.9], 0) };
  A(0, "spud", "sit", { seat: "bed", dur: 0.01, hands: "lap", height: 0.5 });
  A(0, "spud", "look", { to: [0, 0], dur: 0.01, blink: false });
  const h = grips.box(c, "spud", spec, { height: 0.55 });
  let t = h.take(0.3);
  t = h.carry(t + 0.05, [BED[0], 1.28, BED[1] + 0.05], 0.7);
  c.cap(0, 3, "Hotel room: pillow on his head", 300, false, { kinetic: false });
  write(import.meta.url, {
    id: "nighthotel-props", title: "Night hotel props bench", idea: "Props bench for There's a catch EP06 (hotelroom, nightskyline, hotelbed, hotelpillow), not a clip", ...common,
    castLook: "sheet", set: { type: "plain", color: "#05081e", floor: "none" },
    hook: { show: ["spud", "room"], hint: 0, what: "engine test" },
    cast: [{ id: "spud", character: "potatobrawl/spud", at: BED, face: 0, expr: "terrified", follow: 0.2, seed: 1.3 }],
    props: [
      { id: "room", kind: "hotelroom", x: 0, y: 0, z: 0, rot: 0, bed: 0 },
      { id: "bed", kind: "hotelbed", x: BED[0], y: 0, z: BED[1], rot: 0 },
      { id: "sky", kind: "nightskyline", x: 0, y: -1, z: 13, rot: 0, w: 30, h: 14, r: 18 },
      spec,
    ],
    captions: c.captions, beats: c.beats([["hotel", 0, CAM, "hotel room"]], 3), notes: "Generated by make-nightcity-props.mjs (props bench, no reviews).",
  });
  console.log("hotel still at", r3(t + 0.2));
}

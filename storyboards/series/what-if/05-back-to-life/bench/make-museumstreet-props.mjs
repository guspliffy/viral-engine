// Bench for the museum's outside (engine/page/props-museumstreet.js, task T4 of BRIEF-T4.md): museumfront, townsquare,
// hillneck, streetcracks with the T. rex, the street lamp and one potato, on a plain bright set. Not a clip.
// Fifteen stills, 1 s apart, each taken 0.6 s into its beat (the params jump 0.01 s after the beat starts):
//   1 F breach 0                       2-5  F breach 1, burst 0.15 / 0.4 / 0.9 / 2
//   6-9 S breach 1, burst 0.15 / 0.4 / 0.9 / 2    10 L (panel 11)    11-14 N (panel 12) grow 1, rise 0 / 0.35 / 0.7 / 1    15 W overview of the square (mine)
//   node storyboards/series/what-if/05-back-to-life/bench/make-museumstreet-props.mjs [--only front|square|hill|cracks]
//   node engine/render.mjs storyboards/series/what-if/05-back-to-life/bench/btl-street-props.json --stills 0.6,1.6,...,14.6 --draft --safe
//   node qa/contact.mjs out/btl-street-props-*.png --out storyboards/series/what-if/05-back-to-life/bench/museumstreet-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const END = 15.0;
const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const only = process.argv.includes("--only") ? process.argv[process.argv.indexOf("--only") + 1] : null;

const CAM = {
  F: { pos: [0.15, 0.5, 11.5], look: [0.5, 2.4, 2.5], fov: 46 },
  S: { pos: [10.5, 1.4, 8], look: [0.8, 2.7, 2.6], fov: 46 },
  L: { pos: [0.6, 0.9, 14.2], look: [-2.2, 4.6, 8], fov: 46 },
  N: { pos: [0.4, 0.3, 17.4], look: [-0.9, 5.2, 6], fov: 58 },
  W: { pos: [0, 11, 42], look: [0, 8, -5], fov: 85 },   // overview of my own, not a panel: the whole square at once
};
// [camera, breach, burst, rise, label]
const SHOTS = [
  ["F", 0, 0, 0, "F (panel 01), breach 0"],
  ...[0.15, 0.4, 0.9, 2].map((b) => ["F", 1, b, 0, `F, breach 1, burst ${b}`]),
  ...[0.15, 0.4, 0.9, 2].map((b) => ["S", 1, b, 0, `S (panel 10), breach 1, burst ${b}`]),
  ["L", 1, 2, 0, "L (panel 11)"],
  ...[0, 0.35, 0.7, 1].map((r) => ["N", 1, 2, r, `N (panel 12), grow 1, rise ${r}`]),
  ["W", 1, 2, 1, "W overview, rise 1"],
];

const FRONT = { id: "front", kind: "museumfront", x: 0, y: 0, z: 0, rot: 0, w: 34, h: 10, breachX: 1.4, breachW: 9, breachH: 7.5, breach: 0, burst: 0 };
const SQUARE = { id: "square", kind: "townsquare", x: 0, y: 0, z: 10, rot: 0, w: 40, d: 34 };
// headH 23 / headZ 11 (contract: 36 / 14): with the contract head the N camera, whose top edge is 52 deg up, cannot hold it (59 deg)
const NECK = { id: "neck", kind: "hillneck", x: 2.5, y: 0, z: -18, rot: 0, rise: 0, headH: 23, headZ: 11 };
const CRACKS = { id: "cracks", kind: "streetcracks", x: -0.6, y: 0, z: 15, rot: 0, r: 2.6, grow: 1 };
const LAMP = { id: "lamp", kind: "streetlamp", x: -2.5, y: 0, z: 8, rot: 0, h: 6.5, lit: 0 };
const REX = { id: "rex", kind: "trex", x: 1.0, y: 0, z: 1.0, rot: 0, scale: 1.5, jaw: 0.9, lean: 14 };
const props = [FRONT, SQUARE, NECK, CRACKS, LAMP, REX].filter((p) => !only || ({ front: ["front", "lamp", "rex"], square: ["square", "lamp"], hill: ["neck", "front"], cracks: ["cracks", "square"] }[only] || []).includes(p.id));

// seed every tweened key at time 0, then one jump per beat
c.prop(0, "front", { breach: 0, burst: 0 }, 0, "linear");
c.prop(0, "neck", { rise: 0 }, 0, "linear");
SHOTS.forEach(([, breach, burst, rise], i) => {
  c.prop(i + 0.01, "front", { breach, burst }, 0, "linear");
  c.prop(i + 0.01, "neck", { rise }, 0, "linear");
});

const cast = [{ id: "spud", character: "potatobrawl/spud", at: [0.1, 6], face: 0, expr: "terrified", follow: 0.2, seed: 1.3 }];
c.A(0, "spud", "look", { to: [0, 1.5], dur: 0.01, blink: false });

const beats = c.beats(SHOTS.map(([cam, , , , label], i) => [`${cam.toLowerCase()}${i + 1}`, i, CAM[cam], label]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "btl-street-props", title: "Museum street props bench", idea: "Props bench for There's a catch EP05 (museumfront, townsquare, hillneck, streetcracks), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
  set: { type: "plain", color: "#9fcdf0", floor: "#a39f97", light: "golden" }, sky: [[0, 1]], music: false, sound: { auto: false },
  hook: { show: ["spud", "front"], hint: 0, what: "engine test" },
  cast, props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/what-if/05-back-to-life/bench/make-museumstreet-props.mjs (props bench, no reviews).",
});

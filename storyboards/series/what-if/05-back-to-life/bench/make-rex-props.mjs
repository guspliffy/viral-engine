// Bench for the T. rex additions (engine/page/props-dino.js `trex`, task T5 of storyboards/series/what-if/05-back-to-life/BRIEF-T5.md):
// spec.skin "brown", glow, gait and drool. A green trex at [-3, 0] and a brown one at [3, 0] (both scale 1.5) and Spud at [0, 2] on
// the plain golden set. Not a clip. One still per beat, 1 s apart, each taken 0.6 s into its beat; every beat sets every param (dur 0).
//   1 front, both at rest              2-5 side on the brown one, gait 0, 0.25, 0.5, 0.75 (green one and Spud out of the shot)
//   6-7 looking up at the brown face, drool 0 and 1 (lean 6, neckP 8, headP 32, squint 0.75, brow -1, jaw 0.25)
//   8-9 front, glow 0.5 and 1 on the brown one only      10 face, drool 1 and jaw 0.6    11-13 extras: green one running and drooling, both whole at 26 m (rest, glow), 3/4 on the brown one
//   node storyboards/series/what-if/05-back-to-life/bench/make-rex-props.mjs   (prints the still times and their labels)
//   node engine/render.mjs storyboards/series/what-if/05-back-to-life/bench/btl-rex-props.json --stills <times> --draft --safe
//   node qa/contact.mjs out/btl-rex-props-*.png --out storyboards/series/what-if/05-back-to-life/bench/rex-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };

const FRONT = { pos: [0, 1.6, 14], look: [0, 2.6, 0], fov: 46 };
const SIDE = { pos: [30, 2.4, -1.2], look: [3, 2.0, -1.2], fov: 46 };   // 27 m off: the whole 8 m trex and tail in the frame
const WIDE = { pos: [0, 2.4, 26], look: [0, 2.2, 0], fov: 46 };           // extra: both whole (the brief's 14 m front cuts them)
const THREEQ = { pos: [9.5, 1.5, 10], look: [3, 2.4, 1.5], fov: 46 };      // extra: the starving brown one in three-quarter view
const FACE = { pos: [3, 0.45, 5.5], look: [3, 3.4, 1], fov: 55 };
const POSE = { lean: 6, neckP: 8, headP: 32, squint: 0.75, brow: -1, jaw: 0.25 };

const HOME = { rexg: { x: -3, z: 0 }, rexb: { x: 3, z: 0 } };
const REST = { gait: 0, drool: 0, glow: 0, lean: 0, neckP: 0, headP: 0, squint: 0, brow: 0, jaw: 0 };
const FAR = 60;   // the green one stands this far back in the side shots
// [label, camera, { green params } | null (out of the shot), { brown params }]
const SHOTS = [
  ["front rest", FRONT, {}, {}],
  ["side gait 0", SIDE, null, { gait: 0 }],
  ["side gait 0.25", SIDE, null, { gait: 0.25 }],
  ["side gait 0.5", SIDE, null, { gait: 0.5 }],
  ["side gait 0.75", SIDE, null, { gait: 0.75 }],
  ["face drool 0", FACE, null, { ...POSE, drool: 0 }],
  ["face drool 1", FACE, null, { ...POSE, drool: 1 }],
  ["front glow 0.5 (brown)", FRONT, {}, { glow: 0.5 }],
  ["front glow 1 (brown)", FRONT, {}, { glow: 1 }],
  ["face drool 1, jaw 0.6", FACE, null, { ...POSE, jaw: 0.6, drool: 1 }],
  ["front gait 0.25 drool 1 (green)", FRONT, { gait: 0.25, drool: 1, jaw: 0.3, brow: -1, headP: 12 }, {}],
  ["extra wide rest", WIDE, {}, {}],
  ["extra wide glow 1 (brown)", WIDE, {}, { glow: 1 }],
  ["extra 3/4 brown starving, drool 1", THREEQ, null, { jaw: 0.3, brow: -1, squint: 0.7, headP: 12, drool: 1, gait: 0.25 }],
];
const END = SHOTS.length;

const props = [
  { id: "rexg", kind: "trex", x: HOME.rexg.x, y: 0, z: HOME.rexg.z, rot: 0, scale: 1.5 },
  { id: "rexb", kind: "trex", x: HOME.rexb.x, y: 0, z: HOME.rexb.z, rot: 0, scale: 1.5, skin: "brown" },
];
// seed the params propState has no default for (gait, drool) and glow at time 0 so no first tween jumps
for (const id of ["rexg", "rexb"]) c.prop(0, id, { gait: 0, drool: 0, glow: 0 }, 0, "linear");
SHOTS.forEach(([, , green, brown], i) => {
  const t = i + 0.01;
  c.prop(t, "rexg", { x: HOME.rexg.x, z: green ? HOME.rexg.z : HOME.rexg.z - FAR, ...REST, ...(green ?? {}) }, 0, "linear");
  c.prop(t, "rexb", { x: HOME.rexb.x, z: HOME.rexb.z, ...REST, ...brown }, 0, "linear");
});

const cast = [{ id: "spud", character: "potatobrawl/spud", at: [0, 2], face: 0, expr: "terrified", follow: 0.2, seed: 1.3 }];
c.A(0, "spud", "look", { to: [0, 2.4], dur: 0.01, blink: false });

const beats = c.beats(SHOTS.map(([label, cam], i) => [`s${i + 1}`, i, cam, label]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));
SHOTS.forEach(([label], i) => console.log(`  ${r3(i + 0.6).toFixed(2)}s  ${label}`));

write(import.meta.url, {
  id: "btl-rex-props", title: "T. rex additions bench", idea: "Props bench for There's a catch EP05 (trex skin, glow, gait, drool), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
  set: { type: "plain", color: "#9fcdf0", floor: "#d9cfc0", light: "golden" }, sky: [[0, 1]], music: false, sound: { auto: false },
  hook: { show: ["spud", "rexb"], hint: 0, what: "engine test" },
  cast, props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/what-if/05-back-to-life/bench/make-rex-props.mjs (props bench, no reviews).",
});

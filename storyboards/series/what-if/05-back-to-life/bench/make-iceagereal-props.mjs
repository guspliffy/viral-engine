// One still per beat, 1 s apart, each taken 0.6 s into its beat; every beat sets every param (dur 0).
//   per animal: 1 side at rest  2-4 side gait 0.25, 0.5, 0.75  5 3/4 front  6 front from below, the HUNGRY face (brow -1, squint 0.7, jaw 0.5,
//   drool 1, lookY -0.8, headP 22)  7 head close-up side, jaw 1  8 calm face close-up, brow 0.4  9-10 glow 0.5, 1
//   mammoth also: trunk -1, trunk 1.   sabre-tooth also: crouch 1, bound 0.5 (gait 0.25)
//   node storyboards/series/what-if/05-back-to-life/bench/make-iceagereal-props.mjs   (prints the still times and their labels)
//   node engine/render.mjs storyboards/series/what-if/05-back-to-life/bench/btl-iceagereal-props.json --stills <times> --draft --safe
//   node qa/contact.mjs out/btl-iceagereal-props-*.png --out storyboards/series/what-if/05-back-to-life/bench/iceagereal-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const FAR = 60;

const SC = { mam: 1.3, sab: 1.6 };
const CAMS = {
  mam: {
    side: { pos: [14.5, 2.0, 0.9], look: [0, 1.95, 0.9], fov: 40 }, tq: { pos: [8.5, 2.6, 9.5], look: [0, 1.9, 0.7], fov: 40 },
    below: { pos: [0.3, 0.45, 5], look: [0, 2.7, 2.0], fov: 46 }, head: { pos: [6.0, 2.9, 1.8], look: [0, 2.7, 1.8], fov: 36 }, calm: { pos: [1.4, 2.8, 7.0], look: [0, 2.6, 2.2], fov: 30 },
  },
  sab: {
    side: { pos: [9.8, 0.95, 0.1], look: [0, 0.9, 0.1], fov: 40 }, tq: { pos: [5.2, 1.5, 5.8], look: [0, 0.9, 0.2], fov: 40 },
    below: { pos: [0.3, 0.45, 5], look: [0, 1.25, 1.7], fov: 36 }, head: { pos: [3.4, 1.35, 1.6], look: [0, 1.3, 1.6], fov: 30 }, calm: { pos: [0.8, 1.35, 4.6], look: [0, 1.3, 1.6], fov: 26 },
  },
};
const REST = {
  mam: { gait: 0, trunk: 0, trunkY: 0, ears: 0, glow: 0, jaw: 0, brow: 0, squint: 0, blink: 0, lookX: 0, lookY: 0, headY: 0, headP: 0, drool: 0, breath: 0 },
  sab: { gait: 0, bound: 0, crouch: 0, lick: 0, tail: 0, glow: 0, jaw: 0, brow: 0, squint: 0, blink: 0, lookX: 0, lookY: 0, headY: 0, headP: 0, drool: 0, breath: 0 },
};
const HUNGRY = { brow: -1, squint: 0.7, jaw: 0.5, drool: 1, lookY: -0.8, headP: 22 };
const common = (id) => [
  ["side at rest", "side", {}], ["side gait 0.25", "side", { gait: 0.25 }], ["side gait 0.5", "side", { gait: 0.5 }], ["side gait 0.75", "side", { gait: 0.75 }],
  ["3/4 front", "tq", {}], ["front from below, HUNGRY", "below", HUNGRY], ["head side, jaw 1", "head", { jaw: 1 }], ["calm face, brow 0.4", "calm", { brow: 0.4 }],
  ["glow 0.5", "tq", { glow: 0.5 }], ["glow 1", "tq", { glow: 1 }],
].map(([l, cam, p]) => [`${id} ${l}`, id, CAMS[id][cam], p]);
const SHOTS = [
  ...common("mam"), ["mam trunk -1", "mam", CAMS.mam.side, { trunk: -1 }], ["mam trunk 1", "mam", CAMS.mam.side, { trunk: 1 }],
  ...common("sab"), ["sab crouch 1", "sab", CAMS.sab.side, { crouch: 1 }], ["sab bound 0.5, gait 0.25", "sab", CAMS.sab.side, { bound: 0.5, gait: 0.25 }],
];
const END = SHOTS.length;

const props = [
  { id: "mam", kind: "mammoth", x: 0, y: 0, z: 0, rot: 0, scale: SC.mam, ...REST.mam },
  { id: "sab", kind: "sabretooth", x: 0, y: 0, z: 0, rot: 0, scale: SC.sab, ...REST.sab },
];
for (const id of ["mam", "sab"]) c.prop(0, id, { ...REST[id] }, 0, "linear");
SHOTS.forEach(([, who, , p], i) => {
  const t = i + 0.01;
  for (const id of ["mam", "sab"]) c.prop(t, id, { x: id === who ? 0 : FAR, z: 0, ...REST[id], ...(id === who ? p : {}) }, 0, "linear");
});

const cast = [{ id: "spud", character: "potatobrawl/spud", at: [1.6, 2.6], face: 0, expr: "terrified", follow: 0.2, seed: 1.3 }];
c.A(0, "spud", "look", { to: [0, 2.4], dur: 0.01, blink: false });

const beats = c.beats(SHOTS.map(([label, , cam], i) => [`s${i + 1}`, i, cam, label]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));
SHOTS.forEach(([label], i) => console.log(`  ${r3(i + 0.6).toFixed(2)}s  ${label}`));

write(import.meta.url, {
  id: "btl-iceagereal-props", title: "Real mammoth and sabre-tooth bench", idea: "Props bench for There's a catch EP05 (real-anatomy mammoth and sabre-tooth), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
  set: { type: "plain", color: "#9fcdf0", floor: "#d9cfc0", light: "golden" }, sky: [[0, 1]], music: false, sound: { auto: false },
  hook: { show: ["spud", "mam"], hint: 0, what: "engine test" },
  cast, props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/what-if/05-back-to-life/bench/make-iceagereal-props.mjs (props bench, no reviews).",
});

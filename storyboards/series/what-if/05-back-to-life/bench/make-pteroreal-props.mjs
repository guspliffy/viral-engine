// Bench for the real-anatomy Pteranodon (engine/page/props-ptero.js `pterosaur`, task R3 of storyboards/series/what-if/05-back-to-life/BRIEF-R3.md).
// One animal at scale 1 on the plain golden set, Spud beside it for scale. Not a clip. One still per beat, 1 s apart, each taken 0.6 s into
// its beat; every beat sets every param (dur 0). The animal hangs at y 1.7 (y 4.8 for the shots from below: the camera stays above the floor).
//   1 from above, wings spread   2 from below at 40 deg (how the clip sees it)   3-6 front, flap at four phases a quarter cycle apart
//   7 side, gliding   8 head close-up from the side, jaw 1   9 the HUNGRY face from the front below   10 fold 1   11 bank 30   12-13 glow 0.5, 1
//   node storyboards/series/what-if/05-back-to-life/bench/make-pteroreal-props.mjs   (prints the still times and their labels)
//   node engine/render.mjs storyboards/series/what-if/05-back-to-life/bench/btl-pteroreal-props.json --stills <times> --draft --safe --out <dir>
//   node qa/contact.mjs <dir>/btl-pteroreal-props-*.png --out storyboards/series/what-if/05-back-to-life/bench/pteroreal-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };

const Y1 = 1.7, Y2 = 4.8;
const REST = { flap: 0, bank: 0, fold: 0, glow: 0, jaw: 0, brow: 0, squint: 0, blink: 0, lookX: 0, lookY: 0, headY: 0, headP: 0, drool: 0, breath: 0 };
const FRONT = { pos: [0, Y1, 6], look: [0, Y1, 0], fov: 50 };
const HUNGRY = { brow: -1, squint: 0.7, jaw: 0.3, drool: 1, lookY: -0.8, headP: 25 };
// [label, camera, height, params]
const SHOTS = [
  ["1 from above", { pos: [0, 8.7, 0.9], look: [0, Y1, 0.1], fov: 55 }, Y1, {}],
  ["2 from below 40 deg", { pos: [0, 1.26, 4.4], look: [0, Y2, 0.2], fov: 50 }, Y2, {}],
  ["3 front flap 0.125", FRONT, Y1, { flap: 0.125 }],
  ["4 front flap 0.375", FRONT, Y1, { flap: 0.375 }],
  ["5 front flap 0.625", FRONT, Y1, { flap: 0.625 }],
  ["6 front flap 0.875", FRONT, Y1, { flap: 0.875 }],
  ["7 side gliding", { pos: [6.5, Y1, 0.3], look: [0, Y1, 0.3], fov: 40 }, Y1, {}],
  ["8 head side jaw 1", { pos: [1.5, Y1 + 0.28, 0.85], look: [0, Y1 + 0.25, 0.7], fov: 40 }, Y1, { jaw: 1 }],
  ["9 hungry from front below", { pos: [0, 3.4, 3.6], look: [0, 4.95, 0.9], fov: 40 }, Y2, HUNGRY],
  ["10 fold 1", { pos: [4, Y1 + 0.1, 4], look: [0, Y1 - 0.1, 0], fov: 40 }, Y1, { fold: 1 }],
  ["11 bank 30", FRONT, Y1, { bank: 30 }],
  ["12 glow 0.5", FRONT, Y1, { glow: 0.5 }],
  ["13 glow 1", FRONT, Y1, { glow: 1 }],
];
const END = SHOTS.length;

const props = [{ id: "pte", kind: "pterosaur", x: 0, y: Y1, z: 0, rot: 0, ...REST }];
// seed the params propState has no default for (blink, fold, drool) at time 0 so no first tween jumps
c.prop(0, "pte", { blink: 0, fold: 0, drool: 0 }, 0, "linear");
SHOTS.forEach(([, , h, set], i) => c.prop(i + 0.01, "pte", { x: 0, y: h, z: 0, rot: 0, ...REST, ...set }, 0, "linear"));

const cast = [{ id: "spud", character: "potatobrawl/spud", at: [1.5, 1.2], face: 0, expr: "neutral", follow: 0.2, seed: 1.3 }];
c.A(0, "spud", "look", { to: [0, 1.7], dur: 0.01, blink: false });

const beats = c.beats(SHOTS.map(([label, cam], i) => [`s${i + 1}`, i, cam, label]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));
SHOTS.forEach(([label], i) => console.log(`  ${r3(i + 0.6).toFixed(2)}s  ${label}`));

write(import.meta.url, {
  id: "btl-pteroreal-props", title: "Real Pteranodon bench", idea: "Props bench for There's a catch EP05 (real-anatomy pterosaur), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
  set: { type: "plain", color: "#9fcdf0", floor: "#d9cfc0", light: "golden" }, sky: [[0, 1]], music: false, sound: { auto: false },
  hook: { show: ["spud", "pte"], hint: 0, what: "engine test" },
  cast, props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/what-if/05-back-to-life/bench/make-pteroreal-props.mjs (props bench, no reviews).",
});

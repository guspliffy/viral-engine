import { clip, write, r3 } from "../../../../lib/clip.mjs";

const BOX = { spud: [0.8, 1.0, 0.5], chip: [0.6, 0.65, 0.4], wedge: [1.0, 1.1, 0.5], mash: [0.7, 1.35, 0.5] };
const box = (id, who, x, y, z) => ({ id, kind: "stoneblock", x, y, z, w: BOX[who][0], h: BOX[who][1], d: BOX[who][2] });
const base = (id, title, idea, props, c, beats, len) => ({ id, title, idea, fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet",
  motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false,
  set: { type: "plain", color: "#bcd0e4", floor: "none" }, hud: { sky: false }, music: false, sound: { auto: false },
  hook: { show: ["gorge"], hint: 0, what: "engine test" }, cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/what-if/09b-teleport-forget/bench/make-gorge-bench.mjs (props bench, no reviews)." });

// ------------------------------------------------------------------------------------------------ the main bench
{
  const c = clip();
  const CAM = {
    wide: { pos: [0.5, 4.8, 5.2], look: [0, -2.4, -4.5], fov: 50 }, wide0: { pos: [0, 1.2, 4], look: [0, -1, -4.5], fov: 56 }, raised: { pos: [0, 3.4, 3.2], look: [0, -2.2, -4.5], fov: 56 },
    down: { pos: [0, 1, -4.5], look: [0, -30, -4.8], fov: 60 }, upA: { pos: [0.2, -30, -0.8], look: [0.2, 0, -1.2], fov: 60 }, upB: { pos: [0, -30, -4.5], look: [0, 0, -4.9], fov: 60 },
    brk: { pos: [1.6, 0.9, 1.6], look: [0.2, 0, 0.2], fov: 50 }, fray: { pos: [0.5, -0.72, -3.9], look: [0, -0.87, -4.25], fov: 36 },
    photo: { pos: [6.0, 1.0, 7.8], look: [6.0, 1.05, 1.5], fov: 50 }, hang: { pos: [0, 3.4, 3.2], look: [0, -3.0, -4.5], fov: 56 },
  };
  const CH = BRIDGE_Y(); function BRIDGE_Y() { return -0.9; }
  const props = [
    { id: "gorge", kind: "gorge", x: 0, y: 0, z: 0 }, { id: "rope", kind: "bridgerope", x: 0, y: 0, z: 0 }, { id: "planks", kind: "planks", x: 0, y: 0, z: 0 },
    box("chipbox", "chip", 0, CH - 0.65, -4.5), box("spudbox", "spud", 40, 0, 0), box("wedgebox", "wedge", 40, 0, 0), box("mashbox", "mash", 40, 0, 0),
    { id: "g1", kind: "stoneblock", x: 40, y: 0, z: 0, w: 0.12, h: 0.12, d: 0.12 }, { id: "g2", kind: "stoneblock", x: 40, y: 0, z: 0, w: 0.12, h: 0.12, d: 0.12 }, { id: "g3", kind: "stoneblock", x: 40, y: 0, z: 0, w: 0.12, h: 0.12, d: 0.12 },
  ];
  c.prop(0, "gorge", { lipbreak: 0, crumble: 0 }, 0);
  c.prop(0, "rope", { strands: 3, snap: 0, sway: 0, nearfall: 0, hangers: 1 }, 0);
  const shots = [], stills = [];
  const S = (t0, len, cam, label, still) => { shots.push([`s${shots.length + 1}`, t0, CAM[cam], label]); stills.push(...[].concat(still ?? t0 + len / 2)); };
  const GP = (z, sway) => [sway * (0.5 * 4 * ((0.5 - z) / 10) * (1 - (0.5 - z) / 10) + 0.5 * (1 - Math.abs(2 * ((0.5 - z) / 10) - 1))), 0, z];
  const rope = (s, sway) => { const g = 0.5 * 4 * s * (1 - s) + 0.5 * (1 - Math.abs(2 * s - 1)); return [sway * g, 0.30 + 0.40 * s - 1.40 * g]; };
  const glove = (z, sway) => { const s = (0.5 - z) / 10, [x, y] = rope(s, sway); return [x, y, z]; };
  void GP;
  // h: planks at clip 0.0, 0.5, 1.5 (default starts), then 11.2, 11.8, 12.6 (planks 5 and 6 from the hangers; the snap is on at 10.94 so only they draw)
  S(0, 2.2, "hang", "h: planks at 0.0 0.5 1.5", [0.0, 0.5, 1.5]);
  S(2.2, 1, "wide", "a: briefed wide, Chip box under the rope"); S(3.2, 1, "raised", "a: raised wide, sun line, planks");
  S(4.2, 1, "down", "b: straight down, foam t1"); S(5.2, 1, "down", "b: straight down, foam t2");
  S(6.2, 1, "upA", "c: straight up from (0.2,-30,-0.8)"); S(7.2, 1, "upB", "c: straight up from (0,-30,-4.5)");
  S(8.2, 1, "photo", "i: the photo, four boxes"); S(9.2, 1, "photo", "i: the photo, Spud hidden");
  c.prop(10.94, "rope", { snap: 1 }, 0);
  S(10.2, 2.8, "hang", "h: planks 11.2 11.8 12.6", [11.2, 11.8, 12.6]);
  // e: lipbreak 0, .08, .16, .3, .6, 1 (nearfall with it), crumble .3 .7
  const E = [[0, 0], [0.08, 0], [0.16, 0], [0.3, 0], [0.6, 0], [1, 0], [1, 0.3], [1, 0.7]];
  E.forEach(([p, q], i) => { const t0 = 13 + i; c.prop(t0, "gorge", { lipbreak: p, crumble: q }, 0); c.prop(t0, "rope", { nearfall: p, snap: 1 }, 0); S(t0, 1, "brk", `e: lipbreak ${p} crumble ${q}`); });
  // f: the fray from 0.6 m at strands 3, 2.5, 2, 1.4, 1, 0.5, 0
  [3, 2.5, 2, 1.4, 1, 0.5, 0].forEach((v, i) => { const t0 = 21 + i; c.prop(t0, "rope", { strands: v, snap: 0, nearfall: 0 }, 0); c.prop(t0, "gorge", { lipbreak: 0, crumble: 0 }, 0); S(t0, 1, "fray", `f: strands ${v}`); });
  // g: snap 0, .1, .3, .6, 1 from the raised wide; sway -0.15 and 0.15 with boxes at the three glove points
  [0, 0.1, 0.3, 0.6, 1].forEach((v, i) => { const t0 = 28 + i; c.prop(t0, "rope", { strands: 3, snap: v, sway: 0 }, 0); S(t0, 1, "raised", `g: snap ${v}`); });
  [-0.15, 0.15].forEach((sw, i) => { const t0 = 33 + i; c.prop(t0, "rope", { strands: 3, snap: 0, sway: sw }, 0); S(t0, 1, "wide", `g: sway ${sw}, boxes on the glove points`); });
  // box stand-ins per still (dur-0 sets at the start of each beat)
  const far = 40, hide = { x: far, y: 0, z: 0 };
  const at = (t, id, p) => c.prop(t, id, p, 0);
  const HIDE_ALL = (t) => ["spudbox", "wedgebox", "mashbox", "g1", "g2", "g3"].forEach((id) => at(t, id, hide));
  HIDE_ALL(0); at(0, "chipbox", { x: 0, y: CH - 0.65, z: -4.5 });
  at(8.2, "chipbox", { x: 6.48, y: 0, z: 1.5 }); at(8.2, "spudbox", { x: 5.85, y: 0, z: 1.5 }); at(8.2, "wedgebox", { x: 5.05, y: 0, z: 1.5 }); at(8.2, "mashbox", { x: 7.10, y: 0, z: 1.5 });
  at(9.2, "spudbox", hide);
  at(10.2, "chipbox", { x: 0, y: CH - 0.65, z: -4.5 }); at(10.2, "wedgebox", hide); at(10.2, "mashbox", hide);
  for (let i = 0; i < 8; i++) at(13 + i, "chipbox", { x: 0, y: 40, z: 0 });
  for (let i = 0; i < 7; i++) at(21 + i, "chipbox", { x: 0, y: 40, z: 0 });
  [-0.15, 0.15].forEach((sw, i) => { const t0 = 33 + i, g = [glove(-4.5, sw), glove(-4.75, sw), glove(-4.25, sw)];
    at(t0, "chipbox", { x: g[0][0], y: g[0][1] - 0.65, z: -4.5 });
    ["g1", "g2", "g3"].forEach((id, k) => at(t0, id, { x: g[k][0], y: g[k][1] - 0.06 + (k ? 0.18 : 0.0), z: g[k][2] }));
  });
  [0, 0.1, 0.3, 0.6, 1].forEach((v, i) => at(28 + i, "chipbox", { x: 0, y: CH - 0.65, z: -4.5 }));
  for (const t of [28, 29, 30, 31, 32]) HIDE_ALL(t);
  for (const t of [4.2, 5.2, 6.2, 7.2]) at(t, "chipbox", { x: 0, y: 40, z: 0 });
  const beats = c.beats(shots, 35);
  console.log("bench stills:", stills.map(r3).join(","));
  write(import.meta.url, base("gorge-bench", "Gorge pack bench", "Props bench for There's a catch EP09b (gorge, bridgerope, planks), not a clip", props, c, beats, 35));
}

// ------------------------------------------------------------------------------------------------ the fall strips (DONE WHEN d)
{
  const c = clip(), shots = [], stills = [];
  const props = [{ id: "gorge", kind: "gorge", x: 0, y: 0, z: 0 }, { id: "rope", kind: "bridgerope", x: 0, y: 0, z: 0 }];
  c.prop(0, "gorge", { lipbreak: 0, crumble: 0 }, 0); c.prop(0, "rope", { strands: 3, snap: 1, sway: 0, nearfall: 0, hangers: 0 }, 0);
  // 13 m/s at 30 fps: 0.4333 m a frame; the strip is 12 consecutive frames, so the stills are 1/30 s apart
  for (const [name, z, look] of [["near", -1.75, 1], ["far", -7.25, -1]]) for (let i = 0; i < 12; i++) {
    const y = -1 - (13 / 30) * i, t = r3((name === "near" ? 0 : 12) * (1 / 30) * 3 + i / 30 + 0.2);
    void t;
    const t0 = (name === "near" ? 0 : 12) + i;
    shots.push([`${name}${i}`, t0 * 0.2, { pos: [0, y, z], look: [0, y, z + look * 3], fov: 60 }, `${name} wall, frame ${i}, y ${y.toFixed(2)}`]); stills.push(t0 * 0.2 + 0.1);
  }
  const beats = c.beats(shots, 24 * 0.2);
  console.log("strip stills:", stills.map(r3).join(","));
  write(import.meta.url, base("gorge-strip", "Gorge fall strip", "Fall strip bench for the gorge walls (DESIGN 7 d), not a clip", props, c, beats, 5));
}

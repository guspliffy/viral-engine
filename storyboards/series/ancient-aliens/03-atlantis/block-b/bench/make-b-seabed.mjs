// Bench for the block B Sicily seabed (engine/page/props-at-b-seabed.js, kind atbseabed, brief block-b/briefs/B1.md): one storyboard per camera, each one still.
//   A panel 14 / plate 14: wide, eye 1.2 m, from (0.5, 1.2, 7) looking at (-1, 0.9, -6), fov 40, Spud at (1.5, 1.5)
//   B panel 13: low by the play area, from (0.4, 0.55, 2.6) looking (-0.5, 0.4, 0), fov 38, lamp on, the 39 bars (hero bar at (0.45, 0.35))
//   C panels 22-24: the other way (toward +z): from (0, 1.0, -3) looking (0, 0.9, 4), fov 40, Spud at (0, 0.5)
//   D1 / D2: A with the camera moved 1.5 m in x (the parallax proof)
//   node storyboards/series/ancient-aliens/03-atlantis/block-b/bench/make-b-seabed.mjs [A,B,C,D1,D2]
//   node engine/render.mjs <bench>/b-seabed-A.json --stills 1 --draft --out out/b-seabed      (one at a time)
//   then block-b/bench/b-seabed-<cam>-vs.png (still | plate 14) and b-seabed-sheet.png (qa/contact.mjs)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip } from "../../../../../lib/clip.mjs";
import { host, lampClip, P, AT_UNDER, FRAME } from "../../kit/at-kit.mjs";
const OUT = path.dirname(fileURLToPath(import.meta.url));
const [PX, PZ] = P.sicily;
const r3 = (x) => Math.round(x * 1000) / 1000;
const camAt = (pos, look, fov) => ({ pos: [r3(PX + pos[0]), pos[1], r3(PZ + pos[2])], look: [r3(PX + look[0]), look[1], r3(PZ + look[2])], fov });
const CAM_A = { pos: [0.5, 1.2, 7], look: [-1, 0.9, -6], fov: 40 };
const shift = (c, dx) => ({ pos: [c.pos[0] + dx, c.pos[1], c.pos[2]], look: [c.look[0] + dx, c.look[1], c.look[2]], fov: c.fov });
const fishA = [{ id: "school", kind: "fish", type: "silver", n: 12, x: PX, z: PZ, path: [[-3.2, 2.2, -6], [-1.2, 2.5, -7], [1.4, 2.1, -8], [3.4, 2.4, -6.5], [0.5, 2.7, -5.5]], phase: 0.3, speed: 0.4 },
  { id: "school2", kind: "fish", type: "silver", n: 9, x: PX, z: PZ, path: [[-6, 2.6, -2], [-4, 2.9, -3], [-2, 2.5, -2.4], [-4.5, 2.3, -1.2]], phase: 0.1, speed: 0.35 }];
const GROUPS = {
  A: { label: "A panel 14", spud: { at: [1.5, 1.5], face: "camera" }, lamp: 0, cam: CAM_A, props: fishA },
  B: { label: "B panel 13", spud: { at: [0.0, 0.2], face: 300 }, lamp: 1, cam: { pos: [0.4, 0.55, 2.6], look: [-0.5, 0.4, 0], fov: 38 },
    props: [{ id: "bars", kind: "ingots", x: PX + 0.45, z: PZ + 0.35, lamp: 1, lampFrom: [-0.95, 0.62, -0.1] }] },
  C: { label: "C panel 22-24", spud: { at: [0, 0.5], face: "camera" }, lamp: 0, cam: { pos: [0, 1.0, -3], look: [0, 0.9, 4], fov: 40 },
    props: [{ id: "big", kind: "fish", type: "big", x: PX, z: PZ, path: [[-3.4, 1.1, 2.4], [-0.6, 1.1, 2.4], [2.2, 1.1, 2.3], [4.4, 1.1, 2.2]], phase: 0.2 }] },
  W: { label: "W wreck close (debug)", lamp: 0, cam: { pos: [-1.5, 1.6, 0.5], look: [-5.5, 1.0, -8.5], fov: 50 }, props: [] },
  J: { label: "J jar + rocks close (debug)", lamp: 0, cam: { pos: [-2.2, 0.9, 2.5], look: [-5.4, 0.5, -1.8], fov: 42 }, props: [] },
  F: { label: "F foreground left (debug)", lamp: 0, cam: { pos: [3.2, 1.0, 7.5], look: [6, 0.4, 3.5], fov: 45 }, props: [] },
  D1: { label: "D1 A moved 1.5 m", spud: { at: [1.5, 1.5], face: "camera" }, lamp: 0, cam: shift(CAM_A, 0.75), props: fishA },
  D2: { label: "D2 A moved -1.5 m", spud: { at: [1.5, 1.5], face: "camera" }, lamp: 0, cam: shift(CAM_A, -0.75), props: fishA },
};
const want = (process.argv[2] || Object.keys(GROUPS).join(",")).split(",");
for (const name of want) {
  const G = GROUPS[name]; if (!G) continue;
  const c = clip(), END = 3.0;
  const sb = {
    id: `b-seabed-${name}`, title: `Block B seabed bench ${name}`, ...FRAME.wide.sb(1500), fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, motion: "natural",
    set: { ...AT_UNDER }, music: false, sound: { sfx: 0, ambience: 0 }, creative: { length: [0, 20], notes: false },
    cast: G.spud ? [{ id: "spud", character: "potatobrawl/spud", at: [PX + G.spud.at[0], PZ + G.spud.at[1]], face: G.spud.face, expr: "kind", seed: 1.3 }] : [],
    props: [{ id: "place", kind: "atbseabed", x: PX, z: PZ, seed: 1, sway: 1, shafts: 1, silt: 1, fog: 35 }, ...(G.spud ? [host("spud", G.lamp ?? 0)] : []), ...G.props],
    allowClip: G.spud ? lampClip(["spud"], END) : [],
    beats: c.beats([["hold", 0, camAt(G.cam.pos, G.cam.look, G.cam.fov)]], END), duration: END, notes: `Generated by make-b-seabed.mjs (bench ${name}): ${G.label}`,
  };
  fs.writeFileSync(path.join(OUT, `b-seabed-${name}.json`), JSON.stringify(sb, null, 1) + "\n");
  console.log("wrote", `b-seabed-${name}.json`, "|", G.label);
}

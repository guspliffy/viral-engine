// Bench for the shelf edge (engine/page/props-at-b-shelf.js, brief block-b/briefs/B2.md): kind atbshelf at PLACE(25), plain set + AT_UNDER, wide frame.
//   A panel 21 wide (Spud at (0.9, 0) facing +x, lamp on)   B a closer   C the drop (no Spud)   D sideways dolly (A moved 1.5 m in x)
//   node storyboards/series/ancient-aliens/03-atlantis/block-b/bench/make-b-shelf.mjs [A,B,...]
//   node engine/render.mjs <bench>/b-shelf-A.json --stills 0.5,2 --draft --out out/b-shelf   (then the vs sheets: see the ffmpeg lines in the report)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip, r3 } from "../../../../../lib/clip.mjs";
import { host, lampClip } from "../../../kit/aa-kit.mjs";
import { AT_UNDER, PLACE } from "../../kit/at-kit.mjs";
const OUT = path.dirname(fileURLToPath(import.meta.url));
const [PX, PZ] = PLACE(25);
const cam = (p, l, fov) => ({ pos: [r3(PX + p[0]), r3(p[1]), r3(PZ + p[2])], look: [r3(PX + l[0]), r3(l[1]), r3(PZ + l[2])], fov });
const GROUPS = {
  A: { label: "A panel 21: camera over the deep ~2 m beyond the lip, looking back along it", spud: true, cam: cam([6.5, 1.0, 13], [-2, -1, -3], 40) },
  B: { label: "B a closer of the same idea", spud: true, cam: cam([4.4, 0.9, 5.0], [-0.5, -0.4, -1.5], 38) },
  C: { label: "C the drop", spud: false, cam: cam([6, -3, 6], [1, -8, -2], 40) },
  E: { label: "E dev: grass and rocks left of Spud", spud: false, cam: cam([-6, 1.2, 8], [-11, 0.2, 3], 40) },
  F: { label: "F dev: Spud close, sand and the lip", spud: true, cam: cam([-0.6, 0.9, 2.6], [1.4, 0.3, 0], 36) },
  G: { label: "G dev: the lip from above-left", spud: true, cam: cam([-2, 4, 9], [3, -3, 0], 45) },
  H: { label: "H panel 21 from the deep side (dev): Spud at the edge, the face below", spud: true, cam: cam([5.5, 3.0, 9], [0.5, -2.5, -1], 42) },
};
const want = (process.argv[2] || Object.keys(GROUPS).join(",")).split(",");
for (const name of want) {
  const G = GROUPS[name]; if (!G) continue;
  const c = clip(), END = 4.0;
  const sb = {
    id: `b-shelf-${name}`, title: `Atlantis shelf edge bench ${name}`, frame: "wide", far: 1500, fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, motion: "natural",
    set: { ...AT_UNDER }, music: false, sound: { sfx: 0, ambience: 0 }, creative: { length: [0, 20], notes: false },
    cast: G.spud ? [{ id: "spud", character: "potatobrawl/spud", at: [PX + 0.9, PZ], face: 90, expr: "kind", seed: 1.3 }] : [],
    props: [{ id: "shelf", kind: "atbshelf", x: PX, z: PZ, seed: 1, sway: 1, fog: 22 }, ...(G.spud ? [host("spud", 1)] : [])], allowClip: G.spud ? lampClip(["spud"], END) : [],
    beats: c.beats([["hold", 0, G.cam]], END), duration: END, notes: `Generated by make-b-shelf.mjs (bench ${name}): ${G.label}`,
  };
  fs.writeFileSync(path.join(OUT, `b-shelf-${name}.json`), JSON.stringify(sb, null, 1) + "\n");
  console.log("wrote", `b-shelf-${name}.json`, "|", G.label);
}

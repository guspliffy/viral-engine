// Bench for the hatch deck (engine/page/props-at-d-hatch.js, brief D4, panel 45): the hatch hall with the foreman waving, five crew
// (four seated, one standing... see the table), the one empty seat and Spud in the lift beam. WIDE frame (1920 x 1080), far 9000, AT_NIGHT.
//   A  plate 45: from the water under the hatch, Spud in the beam at y -4        B  Spud higher (y -1.5), looking at the camera
//   C  side view of the whole piece, the sea to the hall, for scale             D  close on the empty seat and the foreman
//   E  the tall frame (1080 x 1920): written to at-hatch-tall.json
//   node make-at-hatch.mjs ; node engine/render.mjs <bench>/at-hatch.json --stills <times> --draft --out out/at-hatch
//   node qa/contact.mjs out/at-hatch/*.png --out <bench>/at-hatch-sheet.png
import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { AT_NIGHT } from "../../kit/at-kit.mjs";

const GX = 60000, DEG = Math.PI / 180;
const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const w = (x, z) => [r3(GX + x), r3(z)];
const polar = (r, d) => [r * Math.cos(d * DEG), r * Math.sin(d * DEG)];
const faceTo = (x, z) => ((Math.atan2(-x, -z) / DEG) % 360 + 360) % 360;   // facing the hatch axis (0 = +z, 90 = +x)
const SEATS = { A: [5.15, -32], B: [5.15, -16], C: [5.15, 16], D: [6.7, -34], E: [6.7, 30] };   // crew, same as the kind's seat table
const SEAT_TOP = 0.45;
const cam = (p, l, f = 40, near = 0.1) => ({ pos: [r3(GX + p[0]), r3(p[1]), r3(p[2])], look: [r3(GX + l[0]), r3(l[1]), r3(l[2])], fov: f, near });

function build(tall) {
  const c = clip(), cast = [], props = [], SHOTS = [];
  props.push({ id: "hatch", kind: "hatchhall", x: GX, z: 0, lit: 1, beam: 1 });
  props.push({ id: "sea", kind: "sea", x: GX, z: 0, y: -9, grade: "night", horizon: true, calm: [0, 0, 18], foam: [[-2.2, 0, 2.7, 0.7]], mist: [-2.2, 0, 5], mistA: 0.22, swell: 0.35, reach: 9000 });
  // the crew: seated, facing the hatch axis
  for (const [id, [r, d]] of Object.entries(SEATS)) {
    const [x, z] = polar(r, d), f = faceTo(x, z);
    cast.push({ id: "crew" + id, character: "ancient-aliens/alien-crew", at: w(x, z), face: r3(f), expr: "kind", follow: 0.2, seed: id.charCodeAt(0) });
    c.A(0, "crew" + id, "sit", { seat: "none", rot: r3(f), height: SEAT_TOP, dur: 0.01, hands: "lap" });
  }
  { const [x, z] = polar(5.7, 52), f = faceTo(x, z); cast.push({ id: "foreman", character: "ancient-aliens/alien-foreman", at: w(x, z), face: r3(f), expr: "kind", follow: 0.2, seed: 5 }); c.arm(0.05, "foreman", "R", "wave", 0.25); c.arm(0.4, "foreman", "R", { o: [0.25, 1.0, 0.1] }, 0.2); c.arm(0.65, "foreman", "R", "wave", 0.2); }
  cast.push({ id: "spud", character: "potatobrawl/spud", at: w(-2.2, 0), face: 90, expr: "kind", follow: 0.2, seed: 2.1 });
  const spud = (t, y, face) => { c.A(t, "spud", "fly", { to: { x: r3(GX - 2.2), y, z: 0 }, dur: 0.01 }); if (face != null) c.A(t, "spud", "turn", { face, dur: 0.01 }); };
  let T = 0;
  const shot = (name, label, camera, set) => { T = r3(SHOTS.length * 1.0); SHOTS.push([name, T, camera, label]); set?.(T); };
  if (!tall) {
    shot("A", "A plate 45: from the water, Spud in the beam at y -4", cam([-6.2, -7.8, 5.0], [3.0, 1.6, -0.6], 62), (t) => spud(t, -4, 321));
    shot("B", "B Spud higher (y -1.5), looking at the camera", cam([-3.4, -7.6, 6.4], [-0.4, 0.4, -0.2], 50), (t) => spud(t, -1.5, 349));
    shot("C", "C side view, the sea to the hall, for scale", cam([-17, -6.5, 20], [-1, -2.0, 0], 50), (t) => spud(t, -4, 323));
    shot("D", "D close: the empty seat and the foreman", cam([-0.2, 1.3, -0.9], [4.6, 0.8, 1.6], 50), (t) => spud(t, -1.5, 349));
  } else {
    shot("E", "E tall frame", cam([1.2, -8.2, 7.4], [-1.3, 0.2, -0.4], 56), (t) => spud(t, -4.2, 8));
  }
  const END = r3(SHOTS.length * 1.0 + 0.1);
  SHOTS.forEach(([, t, , label]) => c.cap(t, t + 0.95, label, tall ? 1700 : 1030, false, { kinetic: false, size: 28 }));
  const id = tall ? "at-hatch-tall" : "at-hatch";
  console.log(id, "stills:", SHOTS.map(([, t]) => r3(t + 0.55)).join(","), "names:", SHOTS.map(([n]) => n).join(","));
  write(import.meta.url, {
    id, title: "Atlantis hatch bench", idea: "Props bench for block D builder D4 (hatchhall), not a clip",
    fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
    ...(tall ? {} : { frame: "wide" }), far: 9000,
    set: AT_NIGHT, music: false, sound: { auto: false },
    hook: { show: ["spud"], hint: 0, what: "engine test" },
    cast, props, captions: c.captions, beats: c.beats(SHOTS.map(([n, t, cm, l]) => [n, t, cm, l]), END),
    notes: "Generated by storyboards/series/ancient-aliens/03-atlantis/block-d/bench/make-at-hatch.mjs (props bench, no reviews).",
  });
}
build(false); build(true);

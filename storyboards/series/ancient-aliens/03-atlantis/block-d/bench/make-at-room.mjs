import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { AT_NIGHT } from "../../kit/at-kit.mjs";

const MOTION = { feet: 2, overlap: true, timing: true, solve: true }, RIG = { hand: 2, eyes: 2, hold: 2 };
const WRITE = { o: [-0.2, 0.283, 0.68] }, REST_L = { o: [-0.12, 0.283, 0.5] };
const PLATO = { id: "plato", character: "ancient-aliens/plato", at: [0.66, -1.35], face: 0, expr: "kind", follow: 0.2, seed: 4.1 };
const SPUD = (id, x, y, z) => ({ id, character: "potatobrawl/spud", at: [x, z], y, face: 0, expr: "kind", follow: 0.2, seed: 2.1 });
const ROOM = { id: "room", kind: "platoroom", x: 0, y: 0, z: 0 }, CHAIR = { id: "klis", kind: "klismos", x: 0.66, y: 0, z: -1.35, rot: 0 };
const cam = (pos, look, fov) => ({ pos, look, fov });

function make(id, shots, cast, seated) {
  const c = clip(), SH = shots.map((s, i) => ({ ...s, T: r3(0.1 + i * 1.0) }));
  SH.forEach((s) => {
    if (seated) { c.A(s.T, "plato", "sit", { seat: "klis", dur: 0.01, hands: "keep" }); c.arm(s.T, "plato", "R", WRITE, 0.01); c.arm(s.T, "plato", "L", REST_L, 0.01); c.A(s.T, "plato", "look", { to: [0, -0.4], dur: 0.01 }); }
    c.cap(s.T, s.T + 0.9, s.label, 1860, false, { kinetic: false, size: 30 });
  });
  const END = r3(0.1 + SH.length + 0.1);
  console.log(id, "stills:", SH.map((s) => r3(s.T + 0.55)).join(","));
  write(import.meta.url, {
    id, title: "Plato room bench", idea: "Bench for platoroom + klismos (D2), not a clip", frame: "wide", far: 9000, fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet",
    motion: MOTION, rig: RIG, physics: false, set: AT_NIGHT, music: false, sound: { auto: false }, hook: { show: cast.map((q) => q.id), hint: 0, what: "engine test" },
    cast, props: [ROOM, ...(seated ? [CHAIR] : [])], captions: c.captions, beats: c.beats(SH.map((s) => [s.name, s.T, s.cam]), END),
    notes: "Generated by block-d/bench/make-at-room.mjs (bench, no reviews).",
  });
}
const C39 = cam([0.05, 1.3, 2.0], [0.0, 1.2, -1.6], 38), C47 = cam([0.62, 1.3, 1.15], [0.58, 1.22, -1.5], 26), C48 = cam([0.3, 1.2, 2.3], [0.4, 1.1, -1.5], 33);
const CD = cam([0.1, 1.25, 0.9], [0.0, 1.15, -1.6], 40), CE = cam([-0.7, 1.4, -0.5], [-0.7, 1.3, -5], 35);
make("at-room-1", [{ name: "A", cam: C39, label: "A cam 39: Spud at the window, Plato writing" }, { name: "B", cam: C47, label: "B cam 47: Plato close, window behind left" }], [PLATO, SPUD("spudL", -0.7, 0.4, -2.25)], true);
make("at-room-2", [{ name: "C", cam: C48, label: "C cam 48: Spud in front of the desk, Plato behind" }], [PLATO, SPUD("spudIn", 0.25, 0, -0.05)], true);
make("at-room-3", [{ name: "D", cam: CD, label: "D the room from the plate's view" }, { name: "E", cam: CE, label: "E the window view alone" }], [], false);

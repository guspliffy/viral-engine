import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { AT_NIGHT, P as PLACES } from "../../kit/at-kit.mjs";

const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const [PX, PZ] = PLACES.helike;
const cam = (p, l, f) => ({ pos: [r3(PX + p[0]), r3(p[1]), r3(PZ + p[2])], look: [r3(PX + l[0]), r3(l[1]), r3(PZ + l[2])], fov: f });
const CAMS = {
  A: cam([1.2, 2.4, 6.4], [8.5, -3.9, -80], 34),
  D: cam([-4, 2.6, -36], [30, -3.6, -80], 38),
  F: cam([0.9, 0.85, 3.1], [0, 0.18, 0], 30),
  E: cam([3, 4.2, 9], [8, -5.5, -60], 54),
};
const SHOTS = [["A", 0, "A panel 37: flood 0", CAMS.A], ["B", 1, "B flood 1", CAMS.A], ["C", 0.5, "C flood 0.5", CAMS.A], ["D", 1, "D low 3/4 along the shore, flood 1", CAMS.D], ["F", 0, "F Spud's feet", CAMS.F]];
const build = (id, shots, extra) => {
  const c = clip();
  const spec = (t, flood) => c.prop(t, "helike", { flood }, 0);
  const S = shots.map(([n, fl, label, cm], i) => { const t = r3(0.1 + i); spec(t, fl); c.cap(t, t + 0.9, label, extra.capY, false, { kinetic: false, size: 28 }); return [n, t, cm, label]; });
  const END = r3(0.1 + shots.length + 0.1);
  console.log(id, "stills:", S.map(([, t]) => r3(t + 0.55)).join(","));
  write(import.meta.url, {
    id, title: "Helike bench", idea: "Props bench for block D's Helike (kind helike), not a clip",
    fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false, far: 9000, ...extra.frame,
    set: { ...AT_NIGHT }, music: false, sound: { auto: false }, hook: { show: ["spud"], hint: 0, what: "engine test" },
    cast: [{ id: "spud", character: "potatobrawl/spud", at: [r3(PX), r3(PZ)], face: 180, expr: "kind", follow: 0.2, seed: 2.1 }],
    props: [{ id: "helike", kind: "helike", x: r3(PX), z: r3(PZ), flood: 0 }],
    captions: c.captions, beats: c.beats(S, END), notes: "Generated by storyboards/series/ancient-aliens/03-atlantis/block-d/bench/make-at-helike.mjs (props bench, no reviews).",
  });
};
build("at-helike", SHOTS, { capY: 1030, frame: { frame: "wide" } });
build("at-helike-tall", [["E", 0.6, "E tall frame, flood 0.6", CAMS.E]], { capY: 1800, frame: {} });

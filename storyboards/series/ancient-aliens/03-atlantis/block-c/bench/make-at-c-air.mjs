// Bench for block C2 (engine/page/props-at-c-air.js, brief block-c/briefs/C2.md): Bimini from above. One group = one camera, the place at x 60000.
//   A  panel 27: camera (6, 32, 40) look (0, -5, -400) fov 45; boat at (26, -70)
//   B  higher: (40, 120, 140) look (0, -5, -500) fov 40: the road's whole 800 m and the island
//   C  lower push: (-4, 14, 14) look (2, -5, -120) fov 42
//   S1 / S2 the sky alone, fov 40, looking toward az 0 and az 120 (seam check)
//   D  the boat close (12, 7, -50) look (26, 0, -70)
//   (the bed and the road are C1's biminibed / biminiroad; set o.c1 false for the stand-in biminiairfloor)
//   A2 panel 27 with the island at size 1.8 and the boat nearer (the painting's drone distance)
//   node storyboards/series/ancient-aliens/03-atlantis/block-c/bench/make-at-c-air.mjs [A,B,C]
//   node engine/render.mjs storyboards/series/ancient-aliens/03-atlantis/block-c/bench/at-c-air.json --stills <times> --draft --out out/at-c-air
import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { AT_DAY } from "../../kit/at-kit.mjs";

const c = clip();
const NAMES = ["A", "B", "C", "A2", "D", "S1", "S2"], want = (process.argv[2] || NAMES.join(",")).split(",");
const GX = Object.fromEntries(NAMES.map((n, i) => [n, 60000 + i * 6000]));
const props = [], SHOTS = [];
const on = (g) => want.includes(g);
const P = (g, id, kind, extra = {}) => props.push({ id: id + g, kind, x: GX[g], z: 0, ...extra });
const cam = (g, p, l, f) => ({ pos: [r3(GX[g] + p[0]), r3(p[1]), r3(p[2])], look: [r3(GX[g] + l[0]), r3(l[1]), r3(l[2])], fov: f });
const place = (g, o = {}) => {
  P(g, "clouds", "biminisky");
  if (o.c1 !== false) { P(g, "bed", "biminibed", { reef: true }); P(g, "road", "biminiroad"); } else P(g, "floor", "biminiairfloor");
  P(g, "sea", "biminisea", o.sea ?? { clarity: 2, scatter: 0.55, net: 0.9 });   // C1's bed is already graded from above
  P(g, "isle", "biminiisle", o.isle ?? {});
  props.push({ id: "boat" + g, kind: "biminiboat", x: GX[g] + (o.boat?.[0] ?? 26), z: o.boat?.[1] ?? -70, rot: o.boat?.[2] ?? 0 });
};
if (on("A")) { place("A"); SHOTS.push(["A", cam("A", [6, 32, 40], [0, -5, -400], 45), "A panel 27"]); }
if (on("B")) { place("B"); SHOTS.push(["B", cam("B", [40, 120, 140], [0, -5, -500], 40), "B higher"]); }
if (on("C")) { place("C", { boat: [10, -40, 0] }); SHOTS.push(["C", cam("C", [-4, 14, 14], [2, -5, -120], 42), "C lower push"]); }
if (on("A2")) { place("A2", { isle: { at: [0, -1100] }, boat: [24, -44, 0] }); SHOTS.push(["A2", cam("A2", [6, 32, 40], [0, -26, -260], 45), "A2 panel 27, island size 1.8 nearer"]); }

if (on("D")) { place("D"); SHOTS.push(["D", cam("D", [12, 7, -50], [26, 0, -70], 40), "D boat close"]); }

for (const [g, look] of [["S1", [0, 18, -100]], ["S2", [86.6, 18, 50]]]) if (on(g)) { P(g, "sky", "biminisky"); P(g, "sea", "biminisea", { clarity: 2, scatter: 0.55 }); SHOTS.push([g, cam(g, [0, 4, 0], look, 40), `${g} sky alone, fov 40, az ${g === "S1" ? 0 : 120}`]); }

let T = 0;
SHOTS.forEach(([name, cm, label], i) => { T = r3(0.1 + i * 1.0); SHOTS[i] = [name, T, cm, label]; c.cap(T, T + 0.9, label, 1860, false, { kinetic: false, size: 30 }); });
const END = r3(0.1 + SHOTS.length * 1.0 + 0.1);
console.log("stills:", SHOTS.map(([, t]) => r3(t + 0.55)).join(","));
console.log("names:", SHOTS.map(([n]) => n).join(","));
write(import.meta.url, {
  id: "at-c-air", title: "Atlantis block C2 bench", idea: "Props bench for Bimini from above (biminisea, biminiisle, biminiboat, biminiclouds), not a clip",
  frame: "wide", far: 1500, fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false,
  set: AT_DAY, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats: c.beats(SHOTS.map(([n, t, cm]) => [n, t, cm]), END),
  notes: "Generated by storyboards/series/ancient-aliens/03-atlantis/block-c/bench/make-at-c-air.mjs (props bench, no reviews).",
});

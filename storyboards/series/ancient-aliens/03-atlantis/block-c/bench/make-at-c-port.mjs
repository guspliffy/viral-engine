// Bench for Port Royal 1692 (engine/page/props-at-c-port.js, task C3 of ../briefs/C3.md): one group per camera, 4000 m apart on x from 80000
// (a sea draws only within its spec.reach of its own x, z). Wide frame, far 1500, light AT_DAY (sun 20 deg left of -z, 55 up).
//   A  panel 34: Spud on the deck, sink 0
//   B  panel 35: Spud running, sink 0.5
//   C  the same as B at sink 1 (two thirds gone)
//   D  wide without Spud: the whole bay, sink 0
//   node storyboards/series/ancient-aliens/03-atlantis/block-c/bench/make-at-c-port.mjs [A,B,C,D]
//   node engine/render.mjs storyboards/series/ancient-aliens/03-atlantis/block-c/bench/at-c-port.json --stills <times> --draft --out out/at-c-port
//   node qa/contact.mjs out/at-c-port/at-c-port-*.png --out storyboards/series/ancient-aliens/03-atlantis/block-c/bench/at-c-port-sheet.png
import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { AT_DAY } from "../../kit/at-kit.mjs";

const c = clip();
const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const NAMES = ["A", "B", "C", "D"], want = (process.argv[2] || NAMES.join(",")).split(",");
const GX = Object.fromEntries(NAMES.map((n, i) => [n, 80000 + i * 4000]));
const on = (g) => want.includes(g);
const cast = [], props = [], SHOTS = [];
const spud = (g, x, z, face, y = 1.2) => cast.push({ id: `spud${g}`, character: "potatobrawl/spud", at: [GX[g] + x, z], y, face, expr: "kind", follow: 0.2, seed: 2.1 });
const cam = (g, p, l, f) => ({ pos: [r3(GX[g] + p[0]), r3(p[1]), r3(p[2])], look: [r3(GX[g] + l[0]), r3(l[1]), r3(l[2])], fov: f });
const MIRRORS = [[82, -128, 30, 10, "#2a211a"], [56, -158, 24, 9, "#2a211a"]];
function place(g, sink) {
  props.push({ id: "sky" + g, kind: "aasky", x: GX[g], z: 0, time: "day" });
  props.push({ id: "sea" + g, kind: "sea", x: GX[g], z: 0, grade: "tropic", horizon: true, reach: 1700, mirrors: MIRRORS });
  props.push({ id: "port" + g, kind: "portroyal", x: GX[g], z: 0, sink, shake: sink > 0 && sink < 1 ? 0.5 : 0 });
}
if (on("A")) { place("A", 0); spud("A", -0.3, 0, 15); SHOTS.push(["A", cam("A", [1.5, 2.8, 8], [-2, 3.5, -50], 40), "A panel 34: Port Royal 1692, sink 0"]); }
if (on("B")) { place("B", 0.5); spud("B", -0.8, 2.0, 200); SHOTS.push(["B", cam("B", [2.0, 2.8, 8], [-4, 3.5, -45], 44), "B panel 35: the slide, sink 0.5"]); }
if (on("C")) { place("C", 1); spud("C", -0.8, 2.0, 200); SHOTS.push(["C", cam("C", [2.0, 2.8, 8], [-4, 3.5, -45], 44), "C panel 35: two thirds gone, sink 1"]); }
if (on("D")) { place("D", 0); SHOTS.push(["D", cam("D", [6, 9, 20], [-10, 3, -80], 45), "D the whole bay, sink 0"]); }

let T = 0;
SHOTS.forEach(([name, cm, label], i) => { T = r3(0.1 + i * 1.0); SHOTS[i] = [name, T, cm, label]; c.cap(T, T + 0.9, label, 1860, false, { kinetic: false, size: 30 }); });
const END = r3(0.1 + SHOTS.length * 1.0 + 0.1);
console.log("stills:", SHOTS.map(([, t]) => r3(t + 0.55)).join(","));
console.log("names:", SHOTS.map(([n]) => n).join(","));
write(import.meta.url, {
  id: "at-c-port", title: "Atlantis block C Port Royal bench", idea: "Props bench for portroyal (Port Royal 1692 and its slide), not a clip",
  frame: "wide", far: 1500, fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
  set: AT_DAY, music: false, sound: { auto: false },
  hook: { show: [cast[0]?.id], hint: 0, what: "engine test" },
  cast, props, captions: c.captions, beats: c.beats(SHOTS.map(([n, t, cm]) => [n, t, cm]), END),
  notes: "Generated by storyboards/series/ancient-aliens/03-atlantis/block-c/bench/make-at-c-port.mjs (props bench, no reviews).",
});

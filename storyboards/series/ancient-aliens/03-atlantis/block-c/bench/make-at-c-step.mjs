// Bench for block C5 (engine/page/props-at-c-step.js, brief block-c/briefs/C5.md): the marble step in the calm sea. One group = one camera, the place at x 120000 (+6000 per group).
//   A  panel 31: block 0; Spud on the upper tread (0, -0.3) y 0.30; camera (0.6, 0.9, 6.5) look (0, 0.6, -20) fov 38
//   B  panel 32: block 1; Spud on the lower tread (-0.6, 0.9) y -0.55 face 10; the ruler at (0.25, 0.42); camera (-0.2, 0.15, 2.6) look (0.1, 0.1, 0.4) fov 36
//   C  panel 33: block 1; Spud on the upper tread (-0.5, -0.7) y 0.30 (standing: no sit pose in the bench); ruler as B; camera (0.3, 0.55, 3.2) look (0.1, 0.45, -0.8) fov 34
//   D  panel 36 / wide: block 0; Spud (0, 0) y 0.30; camera (0.3, 0.75, 3.0) look (0, 0.7, -10) fov 34
//   node storyboards/series/ancient-aliens/03-atlantis/block-c/bench/make-at-c-step.mjs [A,B,C,D]
//   node engine/render.mjs storyboards/series/ancient-aliens/03-atlantis/block-c/bench/at-c-step.json --stills <times> --draft --out out/at-c-step
import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { AT_DAY } from "../../kit/at-kit.mjs";

const c = clip();
const NAMES = ["A", "B", "C", "D"], want = (process.argv[2] || NAMES.join(",")).split(",");
const GX = Object.fromEntries(NAMES.map((n, i) => [n, 120000 + i * 6000]));
const cast = [], props = [], SHOTS = [];
const on = (g) => want.includes(g);
const P = (g, id, kind, extra = {}) => props.push({ id: id + g, kind, x: GX[g], z: 0, ...extra });
const cam = (g, p, l, f) => ({ pos: [r3(GX[g] + p[0]), r3(p[1]), r3(p[2])], look: [r3(GX[g] + l[0]), r3(l[1]), r3(l[2])], fov: f });
const spud = (g, x, z, y, face = 0) => cast.push({ id: `spud${g}`, character: "potatobrawl/spud", at: [GX[g] + x, z], y, face, expr: "kind", follow: 0.2, seed: 2.1 });
const place = (g, block, ruler) => {
  P(g, "clouds", "biminisky", { sunAz: 20, cover: 0.7 });
  P(g, "sea", "stepsea");
  P(g, "step", "atstep", { block });
  P(g, "land", "horizonland", { coast: "island", az: -30, size: 2.4 });
  P(g, "gulls", "seagulls", { n: 2, centre: [-6, 9, -40], r: 10 });
  if (ruler) props.push({ id: "ruler" + g, kind: "ruler", x: GX[g] + 0.25, y: -0.55, z: 0.42, water: 0.55, tint: "#ffffff" });
};
if (on("A")) { place("A", false, false); spud("A", 0, -0.3, 0.30); SHOTS.push(["A", cam("A", [0.6, 0.9, 6.5], [0, 0.6, -20], 38), "A panel 31"]); }
if (on("B")) { place("B", true, true); spud("B", -0.6, 0.9, -0.55, 10); SHOTS.push(["B", cam("B", [-0.2, 0.15, 2.6], [0.1, 0.1, 0.4], 36), "B panel 32"]); }
if (on("C")) { place("C", true, true); spud("C", -0.5, -0.7, 0.30); SHOTS.push(["C", cam("C", [0.3, 0.55, 3.2], [0.1, 0.45, -0.8], 34), "C panel 33"]); }
if (on("D")) { place("D", false, false); spud("D", 0, 0, 0.30); SHOTS.push(["D", cam("D", [0.3, 0.75, 3.0], [0, 0.7, -10], 34), "D panel 36 / wide"]); }

let T = 0;
SHOTS.forEach(([name, cm, label], i) => { T = r3(0.1 + i * 1.0); SHOTS[i] = [name, T, cm, label]; });
const END = r3(0.1 + SHOTS.length * 1.0 + 0.1);
console.log("stills:", SHOTS.map(([, t]) => r3(t + 0.55)).join(","));
console.log("names:", SHOTS.map(([n]) => n).join(","));
write(import.meta.url, {
  id: "at-c-step", title: "Atlantis block C5 bench", idea: "Props bench for the marble step in the calm sea (atstep, stepsea), not a clip",
  frame: "wide", far: 1500, fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false,
  set: { ...AT_DAY, floor: "none" }, music: false, sound: { auto: false },
  hook: { show: [cast[0]?.id], hint: 0, what: "engine test" },
  cast, props, captions: [], beats: c.beats(SHOTS.map(([n, t, cm]) => [n, t, cm]), END),
  notes: "Generated by storyboards/series/ancient-aliens/03-atlantis/block-c/bench/make-at-c-step.mjs (props bench, no reviews).",
});

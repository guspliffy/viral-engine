// Bench for block C4 (engine/page/props-at-c-road.js, brief block-c/briefs/C4.md): the edge road at stormy evening, panel 29. One group = one camera, the place at x 100000.
//   A  panel 29: Spud (-0.6, 1.0) y 0.35 face 20, foreman at (0.5, -0.4) face -150, 4 crew in file down the road, camera (0.8, 1.4, 4.5) look (-1, 2.2, -40) fov 42, sea grade storm
//   B  no cast, low and wide: camera (-1.5, 1.7, 6) [y raised 0.8 with the road] look (2, 6, -110) fov 46 (the road to the gate, the city)
//   node storyboards/series/ancient-aliens/03-atlantis/block-c/bench/make-at-c-road.mjs [A,B]
//   node engine/render.mjs storyboards/series/ancient-aliens/03-atlantis/block-c/bench/at-c-road.json --stills <times> --draft --out out/at-c-road
import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { AT_EVE } from "../../kit/at-kit.mjs";

const c = clip();
const NAMES = ["A", "B"], want = (process.argv[2] || NAMES.join(",")).split(",");
const GX = Object.fromEntries(NAMES.map((n, i) => [n, 100000 + i * 6000]));
const props = [], cast = [], SHOTS = [];
const on = (g) => want.includes(g);
const P = (g, id, kind, extra = {}) => props.push({ id: id + g, kind, x: GX[g], z: 0, ...extra });
const cam = (g, p, l, f) => ({ pos: [r3(GX[g] + p[0]), r3(p[1]), r3(p[2])], look: [r3(GX[g] + l[0]), r3(l[1]), r3(l[2])], fov: f });
const who = (g, id, character, x, z, face, seed) => cast.push({ id: id + g, character, at: [GX[g] + x, z], y: 0.8, face, expr: "kind", follow: 0.2, seed });
const place = (g) => {
  P(g, "sea", "sea", { grade: "storm", horizon: true, reach: 1700, swell: 0.5, chop: 0.6, calm: [0, -45, 80], hi: "#f0d0b0", skyH: "#d88a4a", skyZ: "#4a4252", haze: "#7a5a58" });
  P(g, "surf", "stormsurf", {});
  P(g, "city", "stormcity", {});
  P(g, "road", "edgeroad2", { water: 0.6 });
};
if (on("A")) {
  place("A");
  who("A", "spud", "potatobrawl/spud", -0.6, 1.0, 20, 2.1);
  who("A", "foreman", "ancient-aliens/alien-foreman", 0.5, -0.4, -150, 3.1);
  [[0.9, -3], [1.1, -6], [1.0, -9], [1.2, -12]].forEach(([x, z], i) => who("A", "crew" + i, "ancient-aliens/alien-crew", x, z, 180, 3.3 + i));
  SHOTS.push(["A", cam("A", [0.8, 1.4, 4.5], [-1, 2.2, -40], 42), "A panel 29: the edge road, foreman, crew, Spud"]);
}
if (on("B")) { place("B"); SHOTS.push(["B", cam("B", [-1.5, 1.7, 6], [2, 6, -110], 46), "B low and wide: the road to the gate, the city"]); }

let T = 0;
SHOTS.forEach(([name, cm, label], i) => { T = r3(0.1 + i * 1.0); SHOTS[i] = [name, T, cm, label]; c.cap(T, T + 0.9, label, 1860, false, { kinetic: false, size: 30 }); });
const END = r3(0.1 + SHOTS.length * 1.0 + 0.1);
console.log("stills:", SHOTS.map(([, t]) => r3(t + 0.55)).join(","));
console.log("names:", SHOTS.map(([n]) => n).join(","));
write(import.meta.url, {
  id: "at-c-road", title: "Atlantis block C4 bench", idea: "Props bench for the edge road at stormy evening (edgeroad2, stormcity), not a clip",
  frame: "wide", far: 1500, fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false,
  set: AT_EVE, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast, props, captions: c.captions, beats: c.beats(SHOTS.map(([n, t, cm]) => [n, t, cm]), END),
  notes: "Generated by storyboards/series/ancient-aliens/03-atlantis/block-c/bench/make-at-c-road.mjs (props bench, no reviews).",
});

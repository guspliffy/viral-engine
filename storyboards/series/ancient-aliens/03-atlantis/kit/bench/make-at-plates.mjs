// Bench: Spud on the painted Atlantis environments (plates painted from the approved panels, made into layered envs
// with engine/plates/env.py). One storyboard per env, wide frame; stills at 0.5 s.
//   node storyboards/series/ancient-aliens/03-atlantis/kit/bench/make-at-plates.mjs [env ...]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip } from "../../../../../lib/clip.mjs";
import { host, lampClip } from "../../../kit/aa-kit.mjs";
const OUT = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(OUT, "../../../../../..");
// per env: Spud's spot and the camera, relative to the painting camera (env.json eye)
const SPOTS = {
  "at-harbour-dawn": { at: [-0.7, 1.0], face: "camera", cam: { dx: 0, dy: 0, dz: 0, fov: 40, lookY: 0 } },
  "at-sicily-seabed": { at: [0.3, 0.6], face: "camera", cam: { dx: 0, dy: 0, dz: 0, fov: 40, lookY: 0 } },
};
for (const ENV of process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(SPOTS)) {
  const E = JSON.parse(fs.readFileSync(path.join(ROOT, "assets/environments", ENV, "env.json"), "utf8"));
  const [ex, ey, ez] = E.eye.pos, S = SPOTS[ENV], p = (E.eye.pitch * Math.PI) / 180;
  const pos = [ex + S.cam.dx, ey + S.cam.dy, ez + S.cam.dz];
  const look = [pos[0], pos[1] - Math.sin(p) * 10 + S.cam.lookY, pos[2] - Math.cos(p) * 10];
  const c = clip(), END = 1.0;
  const sb = {
    id: `at-plate-${ENV}`, title: `Atlantis plate bench ${ENV}`, frame: "wide", far: 1500,
    fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, motion: "natural",
    set: { type: "env", env: ENV, shade: "soft", aperture: 0, focus: false, life: "auto" },
    music: false, sound: { sfx: 0, ambience: 0 }, creative: { length: [0, 20], notes: false },
    cast: [{ id: "spud", character: "potatobrawl/spud", at: S.at, face: S.face, expr: "kind", seed: 1.3 }],
    props: [host("spud", 0)], allowClip: lampClip(["spud"], END),
    beats: c.beats([["hold", 0, { pos, look, fov: S.cam.fov }]], END), duration: END,
    notes: "Generated by make-at-plates.mjs (bench).",
  };
  fs.writeFileSync(path.join(OUT, `at-plate-${ENV}.json`), JSON.stringify(sb, null, 1) + "\n");
  console.log("wrote", `at-plate-${ENV}.json`);
}

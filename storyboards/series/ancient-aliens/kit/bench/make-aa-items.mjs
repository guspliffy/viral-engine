const head = (gx, az, h, el = 0, y = 0.72) => frame([gx, y, 0], { az, h, fov: 24, el });

function bench(id, title, cast, props, SHOTS, set) {
  const c = clip();
  let T = 0;
  const shots = [];
  SHOTS.forEach(([name, setf, cam, label], i) => { T = r3(0.1 + i * 1.0); setf(c, T); shots.push([name, T, cam]); c.cap(T, T + 0.9, label, 240, false, { kinetic: false }); });
  const END = r3(0.1 + SHOTS.length + 0.1);
  console.log(id, "stills:", shots.map(([, t]) => r3(t + 0.55)).join(","));
  console.log(id, "names:", shots.map(([n]) => n).join(","));
  write(import.meta.url, {
    id, title, idea: "Props bench for the Ancient Aliens kit T6 (headlamp, strawhat, spiritlevel, camel, reedboat, nilewater), not a clip",
    fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
    set, music: false, sound: { auto: false },
    hook: { show: [cast[0].id], hint: 0, what: "engine test" },
    cast, props, captions: c.captions, beats: c.beats(shots, END),
    notes: "Generated by storyboards/series/ancient-aliens/kit/bench/make-aa-items.mjs (props bench, no reviews).",
  });
}

// Bench for the FINISHED Great Pyramid of 2560 BC (gold capstone, drawn casing, the court around it), built only from ../aa-kit.mjs.
//   node storyboards/series/ancient-aliens/kit/bench/make-aa-finished.mjs
//   node engine/render.mjs storyboards/series/ancient-aliens/kit/bench/aa-finished.json --stills <times> --out <dir>
import { clip, write, r3 } from "../../../../lib/clip.mjs";
import { S, SET, SET_NIGHT, VIEW, TOP, cam, far, giza2560, liftShip } from "../aa-kit.mjs";

const O = (i) => [i * 1000, 0], P = { a: O(0), b: O(1), c: O(2), d: O(3), e: O(4) };
const view = (o, v) => [o[0] + v.pos[0], o[1] + v.pos[2]];
const V = {
  a: { pos: [-62, 82, 150], look: [8, 6, -12], fov: 34 },    // block A's shot 11, start
  b: { pos: [30, 78, 160], look: [8, 6, -12], fov: 34 },     // block A's shot 11, end
  c: VIEW.finishedHigh,                                      // the kit's spot for the whole complex: start of an orbit
  d: VIEW.finishedHighEnd,                                   // ... and its end
  e: VIEW.pastWide,
};
const NIGHT = process.argv.includes("--night");
const props = Object.keys(V).flatMap((k) => [
  ...far(`f${k}`, view(P[k], V[k]), NIGHT ? { time: "night", stars: 3000, moon: [70, 30], seed: 2 } : { seed: 8 }),
  ...giza2560(`g${k}`, P[k], { state: "finished", ...(NIGHT && { night: 0.72, sunAz: 70 }) }),
  ...liftShip(`s${k}`, [P[k][0] - 44, P[k][1] - 30], { top: TOP(S, 1), hover: 16, beam: 0, lit: 0.4, block: null, shipK: 2.5 }),
]);
const c = clip();
for (const k of Object.keys(V)) c.prop(0, `s${k}-ship`, { beam: 0, wobble: 0 }, 0);
const shots = Object.keys(V).map((k, i) => [k, r3(0.1 + i), cam(P[k], V[k])]);
const END = r3(0.1 + shots.length + 0.1);
console.log("stills:", shots.map(([, t]) => r3(t + 0.55)).join(","));
write(import.meta.url, {
  id: NIGHT ? "aa-finished-night" : "aa-finished", title: "Ancient Aliens kit: the finished pyramid", idea: "Bench for the finished Great Pyramid and its court, not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, physics: false, set: NIGHT ? SET_NIGHT : SET, music: false, sound: { auto: false },
  cast: [], props, captions: c.captions, beats: c.beats(shots, END),
  notes: "Generated by storyboards/series/ancient-aliens/kit/bench/make-aa-finished.mjs (kit bench, no reviews).",
});

import { clip, write, r3, frame } from "../../../../lib/clip.mjs";

const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const sunKey = (az, el, d = 10) => { const a = (az * Math.PI) / 180, e = (el * Math.PI) / 180; return [r3(Math.sin(a) * Math.cos(e) * d), r3(Math.sin(e) * d), r3(Math.cos(a) * Math.cos(e) * d)]; };
const SPUD = (id, x, z, face) => ({ id, character: "potatobrawl/spud", at: [x, z], face, expr: "kind", follow: 0.2, seed: 2.1 });
const cam = (p, l, f) => ({ pos: p, look: l, fov: f });

function bench(id, title, cast, props, SHOTS, set, frameKind, seeds = () => {}) {
  const c = clip();
  let T = 0;
  const shots = [];
  seeds(c);
  SHOTS.forEach(([name, setf, cm, label], i) => { T = r3(0.1 + i * 1.0); setf(c, T); shots.push([name, T, cm]); void label; });
  const END = r3(0.1 + SHOTS.length + 0.1);
  console.log(id, "stills:", shots.map(([, t]) => r3(t + 0.55)).join(","));
  console.log(id, "names:", shots.map(([n]) => n).join(","));
  write(import.meta.url, {
    id, title, idea: "Props bench for EP04 past places part 1 (memphiscourt, palm, apisbier, nilebarge, nilebanks), not a clip",
    fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false, ...(frameKind === "wide" ? { frame: "wide" } : {}),
    set, music: false, sound: { auto: false },
    hook: { show: [cast[0].id], hint: 0, what: "engine test" },
    cast, props, captions: c.captions, beats: c.beats(shots, END),
    allowClip: cast.map((a) => ({ who: a.id, with: "bier", from: 0, to: END, reason: "bench: scale figure beside the bier" })).slice(0, 0),
    notes: "Generated by storyboards/series/ancient-aliens/04-serapeum/bench/make-eg-past.mjs (props bench, no reviews).",
  });
}


import { clip, write, r3 } from "../../../../lib/clip.mjs";

const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const sunKey = (az, el, d = 10) => { const a = (az * Math.PI) / 180, e = (el * Math.PI) / 180; return [r3(Math.sin(a) * Math.cos(e) * d), r3(Math.sin(e) * d), r3(Math.cos(a) * Math.cos(e) * d)]; };
const SPUD = (id, x, z, face) => ({ id, character: "potatobrawl/spud", at: [x, z], face, expr: "kind", follow: 0.2, seed: 2.1 });
const cam = (p, l, f) => ({ pos: p, look: l, fov: f });
const box = (id, z) => ({ id, kind: "granitebox", x: 0, y: 0.19, z, rot: 90, material: "black" });
const sunSet = { type: "plain", color: "#88bbe3", floor: "none", lighting: { v: 2, measure: false, ao: 0, key: sunKey(-38, 48), light: "#fff1d3", shadow: "#8f88b8", exposure: 1.0 } };

function group(id, title, props, cast, shots) {
  const c = clip(), list = [];
  shots.forEach(([name, cm], i) => list.push([name, r3(0.1 + i), cm]));
  const END = r3(0.1 + shots.length + 0.1);
  console.log(id, "stills:", list.map(([, t]) => r3(t + 0.55)).join(","));
  console.log(id, "names:", list.map(([n]) => n).join(","));
  write(import.meta.url, {
    id, title, idea: "Props bench for EP04 Saqqara (saqqara, sledge, egypthaul, waterjar, wetsand, djoser, lever, dustcloud, pounder), not a clip",
    fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false, frame: "wide",
    set: sunSet, music: false, sound: { auto: false }, hook: { show: [cast[0]?.id ?? "x"], hint: 0, what: "engine test" },
    cast, props, captions: c.captions, beats: c.beats(list, END), allowClip: [],
    notes: "Generated by storyboards/series/ancient-aliens/04-serapeum/bench/make-eg-saqqara.mjs (props bench, no reviews): " + title,
  });
}


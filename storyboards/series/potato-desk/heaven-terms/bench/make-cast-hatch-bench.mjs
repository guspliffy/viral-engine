// World frame (station B = the origin), as heaven-steps' sky bench: the hatch at (-0.65, 0, 1.30), hell's floor, the sky drum. One shot per beat (1.1 s each; the
// still is 0.4 s in; each fall value is SET one second before its beat with dur 0.01, so the beat sees the settled pose):
//   top      (-0.65, 3.4, 3.4) -> (-0.65, -0.2, 1.3) fov 34: 55 degrees down into the shaft, fall 0 | 0.5 | 1

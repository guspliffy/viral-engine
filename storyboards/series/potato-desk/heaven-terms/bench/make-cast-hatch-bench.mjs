import { clip, write } from "../../../../lib/clip.mjs";

const c = clip();
const cam = (pos, look, fov = 26) => ({ pos, look, fov });
const DROP = cam([0.55, 3.60, 4.70], [-0.50, 0, 0.95], 34), TOP = cam([-0.65, 3.4, 3.4], [-0.65, -0.2, 1.3], 34), STEEP = cam([-0.65, 4.2, 2.3], [-0.65, -0.6, 1.3], 34), SIDE = cam([-1.9, 1.3, 3.3], [-0.65, -0.3, 1.3], 30);
const props = [
  { id: "sky", kind: "stairsky", x: 0, y: 0, z: 0 },
  { id: "floor", kind: "hellfloor", x: 0, y: 0, z: 0 },
  { id: "hatch", kind: "hellhatch", x: -0.65, y: 0, z: 1.30 },
  { id: "chair", kind: "deckchair", x: 0.50, y: 0, z: 0.95, rot: -25 },
];
// the state each beat should see (set 1 s before its beat starts)
const BEATS = [["t0", TOP, 0, 1], ["t05", TOP, 0.5, 1], ["t1", TOP, 1, 1], ["st1", STEEP, 1, 1], ["st1glow", STEEP, 1, 1.4], ["s05", SIDE, 0.5, 1], ["s1", SIDE, 1, 1], ["d1", DROP, 1, 1]];
BEATS.forEach(([, , fall, glow], i) => { if (i > 0) c.prop(i * 1.1 - 0.05, "hatch", { fall, glow }, 0.01); });
const sb = {
  id: "cast-hatch-bench", title: "Heaven terms: hellhatch fall bench", idea: "Bench for hellhatch's `fall` key (fall 0, 0.5, 1), not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, motion: "natural", far: 160,
  set: { type: "plain", color: "#9fd0f0", floor: "none", para: 0, bloom: "emissive", lighting: 2, cel: { at: 0.25 }, ink: true, satsuei: true },
  music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine bench" },
  cast: [],
  props, captions: c.captions,
  beats: c.beats(BEATS.map(([n, cm], i) => [n, i * 1.1, cm]), BEATS.length * 1.1),
  notes: "Generated by storyboards/series/potato-desk/heaven-terms/bench/make-cast-hatch-bench.mjs (engine bench, no cast).",
};
write(import.meta.url, sb);
console.log("stills at: " + BEATS.map((_, i) => (i * 1.1 + 0.4).toFixed(1)).join(","));

// Heaven's terms bench, task A (25 Nov 2026): `termsscroll` of engine/page/props-heaventerms.js on the real stairway kinds placed as in heaven-steps
// (stairs, sky, zone clouds, terrace, gate, podium, gate rays, hell floor, hatch, deck chair), the gold mat on tread 99 and the stamp on the podium.
// Not a clip, no cast. Four cameras of heaven-terms/DESIGN.md section 0 (shots 1, 3, 19, 21) x four unroll values (0, 0.02, 0.3, 1) = 16 beats of 1.1 s;
// the still of beat i is at 1.1 i + 0.4. State changes are dur-0 `prop` steps at the start of the beat.
//   node storyboards/series/potato-desk/heaven-terms/bench/make-terms-bench.mjs
//   node engine/render.mjs <this dir>/terms-bench.json --draft --safe --out <out dir> --stills 0.4,1.5,2.6,...   (the times the generator prints)
//   node qa/contact.mjs <the stills in time order> --cols 4 --out <this dir>/terms-sheet.png
// A second file, terms-check.json, is the lane check: nine close looks from above and in front at landings 90 .. 10 and the floor, unroll 1 (sheet terms-check-sheet.png).
// GHOST NUMBERS: the stair's own gold riser numbers did not draw in this tree on 25 Nov (heaven-steps' own stairs-bench re-renders without them), so the bench places
// `risernum` copies at their places (props-heavenstairs.js NUMS: x per riser, 0.11 under the tread top, 0.0085 in front of the riser) to judge the lanes. NUMS=0 leaves them out.
import { clip, write } from "../../../../lib/clip.mjs";

const c = clip();
const ST = { T: [0, 22.00, -55.30], E: [0, 17.60, -43.90], B: [0, 0, 0] };
const cam = (s, pos, look, fov) => ({ pos: pos.map((v, i) => v + ST[s][i]), look: look.map((v, i) => v + ST[s][i]), fov });
const SHOTS = [
  ["s1", cam("T", [0.20, 0.50, 8.60], [0.42, 0.62, 0], 26)],
  ["s3", cam("T", [1.00, 6.00, -5.00], [-0.04, -7.40, 14.90], 46)],
  ["s19", cam("E", [0.45, -0.40, 4.20], [-0.45, 0.80, -0.45], 44)],
  ["s21", cam("B", [0.35, 1.25, 6.60], [0, 0.55, 0.80], 30)],
];
const U = [0, 0.02, 0.3, 1];
const w3 = (s, x, y, z) => ({ x: +(x + ST[s][0]).toFixed(3), y: +(y + ST[s][1]).toFixed(3), z: +(z + ST[s][2]).toFixed(3) });
const props = [
  { id: "stairs", kind: "heavenstairs", x: 0, y: 0, z: 0 },
  { id: "sky", kind: "stairsky", x: 0, y: 0, z: 0 },
  { id: "clouds", kind: "zoneclouds", x: 0, y: 0, z: 0 },
  { id: "terrace", kind: "heaventerrace", ...w3("T", 0, 0, 0) },
  { id: "gate", kind: "pearlgate", ...w3("T", -0.20, 0, -2.30), open: 0 },
  { id: "podium", kind: "cloudpodium", ...w3("T", 1.05, 0, -0.80) },
  { id: "rays", kind: "gaterays", ...w3("T", -0.20, 2.2, -6.0) },
  { id: "hell", kind: "hellfloor", x: 0, y: 0, z: 0 },
  { id: "hatch", kind: "hellhatch", x: -0.65, y: 0, z: 1.30, open: 0, glow: 1 },
  { id: "chair", kind: "deckchair", x: 0.50, y: 0, z: 0.95, rot: -25, color: "#c8362f", stripe: "#f2ebe0" },
  { id: "scroll", kind: "termsscroll", x: 0, y: 0, z: 0 },
  { id: "stamp", kind: "goldstamp", ...w3("T", 0.78, 0.42, -0.98) },
  { id: "mat", kind: "goldmat", ...w3("T", -0.10, -0.22, 0.25) },
  { id: "one", kind: "risernum", x: 0, y: 0.11, z: 0.501 },
];
const NUMS = [[10, 0], [20, 0], [30, 1.3], [40, 0], [50, -1.3], [60, 0], [70, 1.3], [80, 0], [90, -0.70], [91, -0.70], [98, 0.10], [99, 0.10], [100, 0.10], [61, 1.20], [62, 1.20], [2, 0]];
const zR = (n) => -0.5 * (n - 2) - 0.7 * Math.floor((n - 1) / 10);
if (process.env.NUMS !== "0") for (const [n, x] of NUMS) props.push({ id: `num${n}`, kind: "risernum", text: String(n), x, y: +(0.22 * n - 0.11).toFixed(3), z: +(zR(n) + 0.0085).toFixed(4) });
const beats = [], names = [];
SHOTS.forEach(([n, cm], si) => U.forEach((u, ui) => {
  const t = (si * U.length + ui) * 1.1;
  c.prop(t, "scroll", { unroll: u, count: u >= 0.3 ? 1 : 0 }, 0);
  beats.push([`${n}_u${u}`, t, cm]); names.push((t + 0.4).toFixed(1));
}));
const end = 16 * 1.1 + 0.1;
const sb = {
  id: "terms-bench", title: "Heaven's terms: scroll bench", idea: "Engine look bench for termsscroll (task A), not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, motion: "natural",
  set: { type: "plain", color: "#9fd0f0", floor: "none", para: 0, bloom: "emissive", cel: { at: 0.25 }, ink: true },
  music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine bench" },
  cast: [],
  props, captions: c.captions,
  beats: c.beats(beats, end),
  notes: "Generated by storyboards/series/potato-desk/heaven-terms/bench/make-terms-bench.mjs (engine bench, no cast).",
};
write(import.meta.url, sb);
console.log("stills at: " + names.join(","));

// ---- the lane check: unroll 1, a look at each landing from the lens side above it
const LAND = [90, 80, 70, 60, 50, 40, 30, 20, 10];
const laneMid = { 90: -0.4, 80: -0.4, 70: 0.4, 60: 0.4, 50: -0.4, 40: -0.4, 30: 0.4, 20: 0.4, 10: -0.2 };
const c2 = clip();
const cams = LAND.map((L) => ["L" + L, { pos: [laneMid[L] + 0.3, 0.22 * L + 2.1, zR(L) + 2.6], look: [laneMid[L], 0.22 * L - 0.1, zR(L) - 0.3], fov: 40 }]);
const nums2 = [];
cams.forEach(([n, cm], i) => { c2.prop(i * 1.1, "scroll", { unroll: 1 }, 0); nums2.push(n); });
const sb2 = { ...sb, id: "terms-check", title: "Heaven's terms: lane check", beats: c2.beats(cams.map(([n, cm], i) => [n, i * 1.1, cm]), 9 * 1.1 + 0.1), captions: c2.captions, notes: "Generated by make-terms-bench.mjs (lane check)." };
write(import.meta.url, sb2);
console.log("check stills at: " + LAND.map((_, i) => (i * 1.1 + 0.4).toFixed(1)).join(","));

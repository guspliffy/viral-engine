// Stormlake bench (You wake up mid EP02 sinking car, task T1): the "stormlake" set (engine/page/set-stormlake.js) at the
// six proof cameras of DESIGN.md 1.6, in the clip template's look, NO cast: stand-ins only (the car a 1.1 x 1.6 x 3.3 m
// stoneblock, the potatoes 0.65 m boulders), each shown only in its own shot.
//   0.0  panel 01 POV in the falling car (0.3, 8, -7), pitched 30 down, yawed 12 toward -x, fov 55 (no stand-ins)
//   2.5  panel 03 impact (7, 1.4, 14) -> (0, 4.5, -2), fov 55; car box nose-down at the surface, spec hole round it
//   19.0 panel 10 (4.5, -2, 1.2) -> (0.4, -1.6, 0), fov 50; car box base y -2.2, pitch 25
//   24.0 panel 11 (5.5, -4, 2) -> (0, -2.8, 0), fov 65; car box base y -5.0, pitch 40, three swimmers above it, shafts at (2.5, 0)
//   27.0 surfacing (9, 0.35, 8) -> (2, 0.2, 1), fov 45; three heads riding STORMLAKE.waveAt
//   30.0 panel 12 (37.5, 0.9, -5) -> (33.5, 0.45, -6.5), fov 50; three on the SHORE patch
//   26.95 (extra) the foam wipe, wipe 1
//   node storyboards/series/you-wake-up-mid/02-sinking-car/bench/make-stormlake-bench.mjs           -> stormlake-bench.json
//   node storyboards/series/you-wake-up-mid/02-sinking-car/bench/make-stormlake-bench.mjs --ref <f> -> the same bench on
//        the "snowslope" set (render-time reference only; written to <f>, not kept here)
//   node engine/render.mjs <json> --stills 0,2.5,19,24,27,30 --draft --safe --silent
//   node qa/contact.mjs out/stormlake-bench-*.png --out out/stormlake-bench-sheet.png [--width 1080 | 360]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { STORMLAKE } from "../../../../../engine/page/set-stormlake.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const LOOK = { aperture: 0, focus: false, bloom: "emissive", lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true };
const HOLE = [0, 0.3, 0, 1.6, 0.52];
const SET = {
  type: "stormlake", lip: true, under: "auto",
  shafts: [[0, [1, 0]], [23.5, [1, 0]], [23.5, [2.5, 0]]],
  hole: [[0, null], [2, HOLE], [3, HOLE], [3, null]],
  wipe: [[26.9, 0], [26.9, 1], [26.97, 1], [26.97, 0]],
  ...LOOK,
};

// the POV: pitched 30 down, yawed 12 toward -x
const pov = [0.3, 8, -7], dir = [-Math.sin(12 * Math.PI / 180) * Math.cos(Math.PI / 6), -0.5, Math.cos(12 * Math.PI / 180) * Math.cos(Math.PI / 6)];
const SHOTS = [
  { at: 0, still: 0, pos: pov, look: pov.map((v, i) => +(v + dir[i] * 10).toFixed(3)), fov: 55 },
  { at: 2, still: 2.5, pos: [7, 1.4, 14], look: [0, 4.5, -2], fov: 55 },
  { at: 18.5, still: 19, pos: [4.5, -2.0, 1.2], look: [0.4, -1.6, 0], fov: 50 },
  { at: 23.5, still: 24, pos: [5.5, -4.0, 2.0], look: [0, -2.8, 0], fov: 65 },
  { at: 26.5, still: 27, pos: [9, 0.35, 8], look: [2, 0.2, 1], fov: 45 },
  { at: 29.5, still: 30, pos: [37.5, 0.9, -5], look: [33.5, 0.45, -6.5], fov: 50 },
];
const P = 0.65, head = (x, z, t) => +(STORMLAKE.waveAt(x, z, t) - P / 2).toFixed(3);
// [shot index, stand-ins]
const STANDS = [
  [1, [{ kind: "stoneblock", w: 1.1, h: 1.6, d: 3.3, x: 0, y: -0.5, z: 0.3, tip: 28 }]],
  [2, [{ kind: "stoneblock", w: 1.1, h: 1.6, d: 3.3, x: 0, y: -2.2, z: 0, tip: 25 }]],
  [3, [{ kind: "stoneblock", w: 1.1, h: 1.6, d: 3.3, x: 0, y: -5.0, z: 0, tip: 40 },
    { kind: "boulder", x: 1.3, y: -2.4, z: 0.6 }, { kind: "boulder", x: 0.6, y: -2.0, z: -0.5 }, { kind: "boulder", x: 1.9, y: -2.9, z: -0.2 }]],
  [4, [[2.6, 1.8], [1.7, 0.6], [3.2, 0.3]].map(([x, z]) => ({ kind: "boulder", x, y: head(x, z, 27), z }))],
  [5, [[34.4, -7.2], [34.6, -6.0], [34.4, -4.8]].map(([x, z]) => ({ kind: "boulder", x, y: +STORMLAKE.heightAt(x, z).toFixed(3), z }))],
];
const props = [], actions = [];
for (const [si, list] of STANDS) list.forEach((p, k) => {
  const id = `s${si}-${k}`, size = p.kind === "boulder" ? { w: P, h: P, d: P } : {};
  props.push({ id, ...size, ...p, scale: 0 });
  actions.push({ do: "prop", id, at: SHOTS[si].at, dur: 0, set: { scale: 1 } });
  if (SHOTS[si + 1]) actions.push({ do: "prop", id, at: SHOTS[si + 1].at, dur: 0, set: { scale: 0 } });
});

const sb = {
  id: "stormlake-bench", title: "Stormlake bench: the storm lake world above and under the water (stand-ins, no cast)", fps: 30, look: "anime-pro", castLook: "sheet",
  profile: "short", loop: false, duration: 31, cleanStart: true, set: SET, music: false, sound: { sfx: 0, ambience: 0, speech: false },
  creative: { length: [1, 31], notes: false }, cast: [], props, actions, captions: [],
  shots: SHOTS.map(({ at, pos, look, fov }) => ({ at, pos, look, fov })),
  notes: "Test bench, not a clip. Generated by storyboards/series/you-wake-up-mid/02-sinking-car/bench/make-stormlake-bench.mjs (task T1).",
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const ri = process.argv.indexOf("--ref");
  if (ri > 0) {
    const f = process.argv[ri + 1];
    fs.writeFileSync(f, JSON.stringify({ ...sb, id: "stormlake-ref", set: { type: "snowslope", dark: 0, ...LOOK } }, null, 1) + "\n");
    console.log(f);
  } else {
    const f = path.join(here, `${sb.id}.json`);
    fs.writeFileSync(f, JSON.stringify(sb, null, 1) + "\n");
    console.log(path.relative(process.cwd(), f));
  }
  console.log(`stills: ${SHOTS.map((s) => s.still).join(",")} (+26.95 the wipe); SHORE y ${STORMLAKE.heightAt(34.5, -6).toFixed(2)}`);
}

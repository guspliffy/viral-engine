// Bench for the tow truck and the coat heap (engine/page/props-tow.js, task T5; happiness 01 redo, DESIGN.md sections 4 and 8a). Not a clip.
// One plain-set storyboard, stills only. Everything stands at a fixed place; the cameras move:
//   the train   truck at x -2.4 facing -x (rot -90) with the coupe hanging on its hook (TOW.pose), train middle at the origin
//   heap bench  x 40: the heap alone, then with a cushion and a sill stand-in (stone blocks) and the spill out; x 60: the real coupe
//               with the heap at the seat and panel 15's lens (T6's `door` is not built yet: the spill lies through the shut door)
//   node storyboards/series/happiness/01-money-redo/bench/tow/make-tow-bench.mjs
//   node engine/render.mjs <that json> --stills beats --draft --safe --out <dir>
//   node qa/contact.mjs <dir>/*.png --out bench/tow/contact.png
import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { TOW, COAT_AT } from "../../../../../../engine/page/props-tow.js";

const c = clip();
const { truck, coupe } = TOW.pose(-2.4, 0, 0, -90);
const XH = 40, XC = 60;
const L = (pos, look, fov) => ({ pos, look, fov });
const props = [
  { id: "truck", kind: "towtruck", ...truck, lights: 1 },
  { id: "tcoupe", kind: "coupe", ...coupe, load: 0 },
  { id: "heapA", kind: "coatheap", x: XH, y: 0.46, z: 0, door: 0 },
  { id: "cushion", kind: "stoneblock", x: XH + 26, y: 0, z: 0, w: 0.66, h: 0.46, d: 0.9 },
  { id: "heapB", kind: "coatheap", x: XH + 26, y: 0.46, z: 0, door: 1 },
  { id: "sill", kind: "stoneblock", x: XH + 26.77, y: 0, z: 0, w: 0.3, h: 0.19, d: 1.1 },
  { id: "coupeH", kind: "coupe", x: XC, y: 0, z: 0, rot: 0, load: 0 },
  { id: "heapC", kind: "coatheap", x: XC + COAT_AT[0], y: COAT_AT[1], z: COAT_AT[2], door: 1 },
];
c.prop(0, "truck", { lights: 1, clock: 0.1, len: 0, bend: 0 }, 0);
for (const id of ["heapA", "heapB", "heapC"]) c.prop(0, id, { door: id === "heapA" ? 0 : 1 }, 0);
const SHOTS = [
  ["train_side", L([0, 1.5, 30], [0, 1.3, 0], 40), "the train side-on, truck left (front -x), the coupe hanging tail-up from the hook"],
  ["train_p16", L([22.5, 1.2, 8.4], [0, 1.5, 0.3], 44), "panel 16's lens, moved to the bench (coupe nearest the camera)"],
  ["truck_side", L([-2.4, 1.6, 21], [-2.4, 1.5, 0], 30), "the truck side-on, lamp A lit", { truck: { clock: 0.1 } }],
  ["truck_front", L([-14, 3.0, 12], [-2.4, 1.3, 0], 30), "the truck from the front 3/4, lamp B lit", { truck: { clock: 0.3 } }],
  ["hook_side", L([0.5, 1.2, 8], [0.5, 1.2, 0], 22), "the hook and the coupe's tail lip, side-on"],
  ["hook_34", L([3.0, 2.3, 3.4], [0.5, 1.25, -0.1], 22), "the hook from above and behind the truck"],
  ["crane_top", L([-2.4, 4.8, 6.5], [-1.0, 2.4, 0], 34), "the boom from above"],
  ["heap_close", L([XH + 0.2, 1.05, 1.25], [XH, 0.62, 0], 30), "the heap alone (door 0): mound, collar roll, folded sleeve, the chain's S"],
  ["heap_spill", L([XH + 26.9, 1.05, 2.5], [XH + 26.5, 0.3, 0], 36), "the spill over the cushion edge and the sill (stand-in blocks), 0.30 on the road"],
  ["p15", L([XC + 1.7, 1.7, -4.2], [XC + 2.2, 0.6, 1.5], 50), "panel 15's lens: sleeve + chain on the road (coupe has no door yet)"],
];
const times = [];
const beats = SHOTS.map(([name, cam, , sets], i) => { const t = i * 1.4; times.push(r3(t + 0.55)); if (sets) for (const [id, s] of Object.entries(sets)) c.prop(t, id, s, 0.01); return [name, t, cam]; });
console.log("stills:", times.join(","));
console.log(SHOTS.map(([n], i) => `${i + 1}:${n}`).join("  "));
write(import.meta.url, {
  id: "tow-bench", title: "Tow truck and coat heap bench", idea: "Props bench for engine/page/props-tow.js (happiness 01 redo), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false,
  set: { type: "plain", color: "#7d8996", floor: "#56606b" }, music: false, sound: { auto: false },
  hook: { show: ["spud"], hint: 0, what: "engine test" },
  cast: [{ id: "spud", character: "potatobrawl/spud", at: [60, 66], face: 0, expr: "sad", follow: 0.2, seed: 2.2 }],
  props, allowClip: [], captions: [], beats: c.beats(beats, r3(SHOTS.length * 1.4)),
  notes: "Generated by bench/tow/make-tow-bench.mjs (props bench, no reviews). Stills: " + SHOTS.map(([n], i) => `${i + 1}:${n}`).join(" "),
});

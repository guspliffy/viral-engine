// Bench for engine/page/set-boutique.js (happiness 01 money redo, task T2; DESIGN.md section 2). Not a clip: stills only.
// Panel 07 as the DESIGN stages it: Spud (spud-rich) at BOUTIQUE.SPUD facing the glass with a hand up, Chip at CHIP pointing at the door, two assistants
// (tot stand-ins, no gifts) at the back, and the TWIN: a second spud-rich in the mirror's box (BOUTIQUE.twin) with the arms swapped. Stand-ins only: the
// director stages the real clip (Chip's hands at the cuff, the gift holds).
//   node storyboards/series/happiness/01-money-redo/bench/boutique/make-boutique-bench.mjs      -> boutique-bench.json + the still times
//   flock /tmp/ve-render.lock node engine/render.mjs <json> --stills beats --draft --safe --silent --out <dir>
//   node qa/contact.mjs <dir>/*.png --out <sheet.png> [--width 360]
import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { BOUTIQUE as B } from "../../../../../../engine/page/set-boutique.js";

const L = (pos, look, fov = 40) => ({ pos, look, fov });
const BEAT = 1.4, P07 = B.CAM.p07, tw = B.twin(B.SPUD, B.SPUD_FACE);
const LOOK = { aperture: 0, focus: false, lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true };
// the beats: [name, camera, twin (1 open box, 0 sheen)]
const BEATS = [
  ["p07_twin", L(P07.pos, P07.look, P07.fov), 1],
  ["p07_sheen", L(P07.pos, P07.look, P07.fov), 0],
  ["glass_twin", L([0.2, 1.5, 2.0], [1.55, 0.9, -0.6], 36), 1, "park"],
  ["glass_sheen", L([0.2, 1.5, 2.0], [1.55, 0.9, -0.6], 36), 0, "park"],
  ["glass_side_twin", L([-0.6, 1.1, 1.7], [1.55, 0.9, -0.7], 36), 1, "park"],
  ["wide_back", L([0.2, 1.5, 6.2], [0, 1.3, -1.2], 48), 1],
  ["box_from_side", L([3.1, 1.4, 1.6], [1.9, 0.9, -1.3], 50), 1, "park"],
  ["door_and_patch", L([2.0, 1.3, 2.6], [-3.25, 1.0, 0.7], 55), 1],
  ["chandelier", L([0.5, 1.0, 2.6], [-0.3, 2.3, -0.9], 55), 1],
  ["rails_A", L([-1.9, 1.3, 1.6], [-1.9, 1.0, -2.3], 50), 1],
  ["p07_wide", L(P07.pos, P07.look, 60), 1],
];

const c = clip();
const SPOT = { spud: [60, 66], chip: [64, 66], as1: [68, 66], as2: [72, 66] }, HOME = { spud: [B.SPUD[0], B.SPUD[2]], chip: [B.CHIP[0], B.CHIP[2]], as1: [B.ASSISTANTS[0][0], B.ASSISTANTS[0][2]], as2: [B.ASSISTANTS[1][0], B.ASSISTANTS[1][2]] };
const actor = (id, character, at, face, expr = "kind", seed = 2.6) => ({ id, character, at, face, expr, follow: 0, seed });
const times = [], shots = [];
const twinKeys = [[0, BEATS[0][2]]];
BEATS.forEach(([name, cam, twin, park], i) => {
  const t = i * BEAT;
  if (park) for (const id of ["spud", "chip", "as1", "as2"]) { c.A(t, id, "move", { to: SPOT[id], dur: 0.01, steps: 0, ease: "linear" }); c.A(t + BEAT - 0.05, id, "move", { to: HOME[id], dur: 0.01, steps: 0, ease: "linear" }); }   // an empty room for this still: the cast waits at SPOT
  shots.push([name, t, cam]); times.push(r3(t + 0.55));
  if (i) twinKeys.push([r3(t - 0.01), BEATS[i - 1][2]], [r3(t), twin]);
});
// Spud waves Chip off (right hand), the twin shows it on the other side; Chip points at the door
c.arm(0, "spud", "R", "wave", 0.01); c.arm(0, "twin", "L", "wave", 0.01);
c.arm(0, "chip", "R", "point", 0.01);   // a stand-in: the director aims it at the door (BOUTIQUE.DOOR_POINT)
const END = r3(BEATS.length * BEAT);
write(import.meta.url, {
  id: "boutique-bench", title: "Boutique bench (panel 07, twin on and off, the room)", idea: "Bench for engine/page/set-boutique.js (happiness 01 money redo), not a clip", fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet",
  motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false,
  set: { type: "boutique", twin: twinKeys, diag: true, ...LOOK }, music: false, sound: { auto: false },
  hook: { show: ["spud"], hint: 0, what: "engine test" },
  cast: [
    actor("spud", "potatobrawl/spud-rich", [B.SPUD[0], B.SPUD[2]], B.SPUD_FACE, "smug", 2.2),
    actor("twin", "potatobrawl/spud-rich", tw.at, tw.face, "smug", 2.2),
    actor("chip", "potatobrawl/chip", [B.CHIP[0], B.CHIP[2]], -90, "eager", 3.1),
    actor("as1", "potatobrawl/tot", [B.ASSISTANTS[0][0], B.ASSISTANTS[0][2]], B.ASSIST_FACE, "serene", 4.1),
    actor("as2", "potatobrawl/tot", [B.ASSISTANTS[1][0], B.ASSISTANTS[1][2]], B.ASSIST_FACE, "serene", 4.7),
  ],
  props: [], allowClip: [], captions: [], beats: c.beats(shots, END),
  notes: `Generated by bench/boutique/make-boutique-bench.mjs (set bench, no reviews). Stills: ${BEATS.map(([n], i) => `${i + 1}:${n}`).join(" ")}`,
});
console.log("stills at", times.join(","));
console.log(`SPUD ${B.SPUD} face ${B.SPUD_FACE}; TWIN ${tw.at} face ${tw.face}`);

// Each still is one story time; the keys hold their value for 0.2 s either side of it (eased steps between stills, as on cuts).
//   node storyboards/series/happiness/01-money-redo/bench/coast2/make-coast2-bench.mjs      -> coast2-bench.json + the still times
//   flock /tmp/ve-render.lock node engine/render.mjs <json> --stills <times> --draft --safe --silent

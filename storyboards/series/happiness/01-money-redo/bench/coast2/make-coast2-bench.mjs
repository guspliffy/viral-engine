import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { COAST } from "../../../../../../engine/page/set-coast.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const LOOK = { aperture: 0, focus: false, bloom: "emissive", lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true };
const r3 = (v) => +v.toFixed(3);
const C = COAST.CAM;
const c09 = { pos: C.c09.pos, look: C.c09.look, fov: C.c09.fov }, c09push = { pos: C.c09push.pos, look: C.c09push.look, fov: C.c09push.fov };
const lens09 = { pos: [1.0, 0.2, 11.5], look: [1.1, 0.6, 0], fov: 50 };   // DESIGN 9.4 panel 09
// panel 15: lens in the car frame (+1.7, 1.7, -4.2) -> (+2.2, 0.6, +1.5); the car's frame (x right, z forward) at rot 90 (nose +x) maps to world (lz, y, -lx)
const [cx, cy, cz] = COAST.CARSTOP2, w15 = (lx, ly, lz) => [r3(cx + lz), r3(cy + ly), r3(cz - lx)];
const lens15 = { pos: w15(1.7, 1.7, -4.2), look: w15(2.2, 0.6, 1.5), fov: 50 };
const wide = { pos: [12, -3.0, 9], look: [20, -8.7, 17], fov: 50 };   // the rail gap (x 15-25) and CARSTOP2 from the knoll's side
// the stills: [story time, name, camera, late, sink]
const STILLS = [
  [1, "c09-late1", c09, 1, 0], [3, "c09-late05", c09, 0.5, 0], [5, "c09-sink0", c09, 0, 0], [7, "c09-sink1", c09, 0, 1],
  [9, "c09-sink145", c09, 0, 1.45], [11, "c09-sink2", c09, 0, 2], [12, "c09push-sink2", c09push, 0, 2],
  [13, "p09-lens-late1", lens09, 1, 0], [14, "p09-lens-late05", lens09, 0.5, 0], [15, "p15-lens-sink08", lens15, 0, 0.8], [16, "wide-gap-sink08", wide, 0, 0.8],
  [17, "c09-sink18", c09, 0, 1.8],
];
const keys = (i) => { const k = [[0, 0]]; for (const s of STILLS) k.push([r3(s[0] - 0.2), s[i]], [r3(s[0] + 0.2), s[i]]); return k; };
const SET = { type: "coast", break: 1, late: keys(3), sink: keys(4), press: [[0, 0, 0.45], [0.72, 0.05, 0.34]], shadows: [[0, 0, 0.30, 0.85], [0.72, 0.05, 0.24, 0.50]], railGap: [15, 25], ...LOOK };

const sb = {
  id: "coast2-bench", title: "Coast bench 2: late afternoon, dusk + first star, press, railGap, CARSTOP2 (stand-in Spud and Chip)", fps: 30, look: "anime-pro", castLook: "sheet",
  profile: "short", loop: false, duration: 19, cleanStart: true, set: SET, music: false, sound: { sfx: 0, ambience: 0, speech: false },
  creative: { length: [1, 19], notes: false },
  cast: [
    { id: "spud", character: "potatobrawl/spud", at: [0, 0], face: 180, expr: "kind", follow: 0, seed: 29 },
    { id: "chip", character: "potatobrawl/chip", at: [1.2, 0.05], face: 180, expr: "kind", follow: 0, seed: 31 },
  ], props: [], actions: [], captions: [],
  shots: STILLS.map(([at, , c]) => ({ at: r3(at - 0.5), pos: c.pos, look: c.look, fov: c.fov })),
  notes: "Test bench, not a clip. Generated by storyboards/series/happiness/01-money-redo/bench/coast2/make-coast2-bench.mjs (task T7).",
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const f = path.join(here, `${sb.id}.json`);
  fs.writeFileSync(f, JSON.stringify(sb, null, 1) + "\n");
  console.log(path.relative(process.cwd(), f));
  console.log(`CARSTOP2 ${COAST.CARSTOP2.join(", ")}; lens15 ${lens15.pos.join(",")} -> ${lens15.look.join(",")}`);
  console.log(`stills: ${STILLS.map((s) => s[0]).join(",")}  (${STILLS.map((s) => `${s[0]} ${s[1]}`).join("; ")})`);
}

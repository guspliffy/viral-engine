import { clip, write, r3 } from "../../../../../lib/clip.mjs";

const SPOT = [60, 66];   // where an unused actor waits
const L = (pos, look, fov = 40) => ({ pos, look, fov });
const BEAT = 1.4;
const scene = (id, { set, props, cast, setup }, beats) => {
  const c = clip();
  setup?.(c);
  const shots = [], times = [];
  beats.forEach(([name, cam, shows, extra], i) => {
    const t = i * BEAT;
    for (const p of props) {
      const on = p.id in shows;
      c.prop(t, p.id, on ? { scale: p.scale ?? 1, ...shows[p.id] } : { scale: 0.001 }, 0.01, "linear");
    }
    extra?.(c, t);
    shots.push([name, t, cam]); times.push(r3(t + 0.55));
  });
  const END = r3(beats.length * BEAT);
  write(import.meta.url, {
    id, title: `Spree props bench (${id})`, idea: "Props bench for engine/page/props-spree.js (happiness 01 money redo), not a clip", fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet",
    motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false,
    set, music: false, sound: { auto: false },
    hook: { show: [cast[0].id], hint: 0, what: "engine test" },
    cast, props: props.map((p) => ({ ...p, scale: 0.001 })), allowClip: [], captions: [], beats: c.beats(shots, END),
    notes: `Generated by bench/spree/make-spree-bench.mjs (props bench, no reviews). Stills: ${beats.map(([n], i) => `${i + 1}:${n}`).join(" ")}`,
  });
  console.log(`${id} stills at`, times.join(","));
  console.log(beats.map(([n], i) => `${i + 1}:${n}`).join("  "));
};
const actor = (id, character, at, face, expr = "kind", seed = 2.6) => ({ id, character, at, face, expr, follow: 0.2, seed });


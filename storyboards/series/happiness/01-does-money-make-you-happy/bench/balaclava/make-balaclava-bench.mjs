// Balaclava bench (happiness 01, producer's note on draft 1: "the mask isn't attached to the head and glitches from frame
// to frame"). Spud wears the balaclava (prop "mask", wear "spud", the clip's spec) through the moves that squash his body:
// stand 0-1, a hop at 1.0, squash 0.1 at 2.0, a run of 2 m at 3.0-4.4, a crouch 4.8-5.9, a 180 turn over 4 s from 6.2.
//   node storyboards/series/happiness/01-does-money-make-you-happy/bench/balaclava/make-balaclava-bench.mjs        -> balaclava-bench.json + stills line
//   flock /tmp/claude-0/render.lock node engine/render.mjs <json> --stills <times> --draft --silent
//   node qa/contact.mjs out/balaclava-bench-draft-t*.png --out <dir>/strip.png --cols 8 --width 300
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const r3 = (x) => Math.round(x * 1000) / 1000;
const A = (at, what, o = {}) => ({ who: "spud", do: what, at, ...o });
const sb = {
  id: "balaclava-bench", title: "Balaclava bench: Spud in the balaclava through hop, squash, run, crouch, turn", fps: 30, frame: "wide",
  look: "anime-pro", castLook: "sheet", profile: "short", loop: false, duration: 10.6, cleanStart: true,
  motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 },
  set: { type: "env", env: "golden-city-crossing", aperture: 0, focus: false, lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true },
  music: false, sound: { sfx: 0, ambience: 0, speech: false }, creative: { length: [1, 11], notes: false },
  cast: [{ id: "spud", character: "potatobrawl/spud", at: [-1, 0], face: 0, expr: "kind", follow: 0, seed: 1.3 }],
  props: [{ id: "mask", kind: "balaclava", wear: "spud", x: 0, y: 0, z: 0 }],
  actions: [
    A(1.0, "hop", { height: 0.18, dur: 0.5 }),
    A(2.0, "squash", { amount: 0.1, dur: 0.5 }),
    A(3.0, "run", { pts: [[0, -1, 0], [1.4, 1, 0]], dur: 1.4, rate: [[0, 5], [1.4, 5]], stride: 1.7 }),
    A(4.8, "crouch", { to: 1, dur: 0.4 }),
    A(5.9, "crouch", { to: 0, dur: 0.4 }),
    A(6.2, "turn", { to: 270, dur: 4 }),
  ],
  captions: [],
  shots: [{ at: 0, pos: [0, 0.85, 3.6], look: [0, 0.62, 0], fov: 40 }],
  notes: "Test bench, not a clip. Generated by bench/balaclava/make-balaclava-bench.mjs.",
};
const T = [];
for (const [a, b, s] of [[0.3, 0.3, 1], [0.9, 1.6, 15], [1.95, 2.55, 15], [3.0, 4.4, 15], [4.8, 5.9, 5], [6.2, 10.2, 2.5]]) for (let t = a; t <= b + 1e-6; t += 1 / s) T.push(r3(t));
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const f = path.join(here, `${sb.id}.json`);
  fs.writeFileSync(f, JSON.stringify(sb, null, 1) + "\n");
  console.log(path.relative(process.cwd(), f));
  console.log(`stills (${T.length}): ${T.join(",")}`);
}

// Bench for DESIGN 11.4 (coffeecart) and 11.6 (notestorm + the moneybag key `full`), engine/page/props-happy.js and props-heist.js. Stills only.
//   props2-cart.json   the cart on env golden-city-crossing, the design's marks (11.4) with stand-in Spud and seller; cameras 2a, 2b and close-ups
//   props2-storm.json  the storm on the coast set (swap room, sunset keys as the clip) from camera 09 and the close of 11.6, the sack emptying
//   node storyboards/series/happiness/01-does-money-make-you-happy/bench/props2/make-props2-bench.mjs
//   flock /tmp/claude-0/render.lock node engine/render.mjs <json> --stills <times printed> --draft --silent --out <dir>
//   node qa/contact.mjs <dir>/*.png --out storyboards/series/happiness/01-does-money-make-you-happy/bench/props2/<name>.png
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip, write, r3 } from "../../../../../lib/clip.mjs";
import { COAST } from "../../../../../../engine/page/set-coast.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const LOOK = { aperture: 0, focus: false, lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true, bloom: "emissive" };
const COMMON = { fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, music: false, sound: { auto: false }, motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false, allowClip: [], captions: [] };
const L = (pos, look, fov) => ({ pos, look, fov });

// ----------------------------------------------------------------------------------------------------------------- the cart (11.4)
{
  const c = clip(), CART = [-1.25, 0, 1.0], SELLER = [-1.95, 1.0], BUY = [-0.52, 1.0];
  const beats = [   // name, camera
    ["2a", L([-1.2, 1.0, 6.1], [-1.2, 0.75, 1.0], 46)], ["2b", L([0.3, 2.2, 6.6], [0.9, 0.5, -0.3], 44)],
    ["front", L([-1.25, 1.3, 3.6], [-1.25, 1.2, 1.0], 36)], ["menu", L([-1.25, 1.25, 2.3], [-1.25, 1.22, 1.55], 30)],
    ["top", L([-0.2, 3.0, 3.0], [-1.25, 0.6, 1.0], 42)], ["side", L([1.4, 0.9, 1.4], [-1.25, 0.75, 1.0], 44)],
    ["counter", L([-1.0, 1.0, 2.5], [-1.25, 0.55, 1.0], 34)],
  ];
  const END = beats.length * 1.4, shots = [], times = [];
  beats.forEach(([n, cam], i) => { const t = i * 1.4; shots.push([n, t, cam]); times.push(r3(t + 0.6)); });
  const props = [
    { id: "pave", kind: "pavement", w: 14, d: 6, x: 0, z: 2.0 }, { id: "kerb", kind: "kerb", x0: -7, x1: 7, z: -1.0 },
    { id: "limo", kind: "limo", open: null, x: 2.0, z: -2.35, rot: 90 },
    { id: "cart", kind: "coffeecart", x: CART[0], y: CART[1], z: CART[2] },
    { id: "cup", kind: "cocoacup", x: CART[0] - 0.08, y: 0.46, z: CART[2] + 0.18, steam: 1 },
  ];
  write(import.meta.url, {
    ...COMMON, id: "props2-cart", title: "Props2 bench: coffeecart", idea: "Props bench (happiness 01 DESIGN 11.4), not a clip", castLook: "sheet",
    set: { type: "env", env: "golden-city-crossing", envCheck: false, ...LOOK }, hook: { show: ["spud"], hint: 0, what: "engine test" },
    cast: [{ id: "spud", character: "potatobrawl/spud", at: BUY, face: -65, expr: "sad", follow: 0.2, seed: 2.2 }, { id: "sel", character: "potatobrawl/chip", at: SELLER, face: 65, expr: "kind", follow: 0.2, seed: 4.4 }],
    props, beats: c.beats(shots, END), duration: END, notes: `Generated by bench/props2/make-props2-bench.mjs. Stills: ${beats.map(([n], i) => `${i + 1}:${n}`).join(" ")}`,
  });
  console.log("props2-cart stills at", times.join(","), "  ", beats.map(([n], i) => `${i + 1}:${n}`).join(" "));
}

// ----------------------------------------------------------------------------------------------------------------- the storm (11.6)
{
  const c = clip(), CP = [0, 0, -600], cw = (p) => [r3(p[0] + CP[0]), r3(p[1] + CP[1]), r3(p[2] + CP[2])], T0 = 3.0, END = T0 + 9.6;   // the break is over at 3.0 s
  const CAM = COAST.CAM, CLOSE = { pos: [0.55, 0.62, -3.4], look: [0.32, 0.55, 0], fov: 40 }, push = (k) => ({ pos: [CAM.c09.pos[0], CAM.c09.pos[1], r3(CAM.c09.pos[2] - 0.6 * k)], look: CAM.c09.look, fov: 40 });
  const at = (p) => ({ pos: cw(p.pos), look: cw(p.look), fov: p.fov });
  const shots = [["c09", 0, at(CAM.c09)], ["close", T0 + 3.3, at(CLOSE)], ["hold", T0 + 6.5, { ...at(CAM.c09), to: { ...at(push(1)) }, dur: r3(END - T0 - 6.5), ease: "linear" }]];
  const SEAT = cw(COAST.SEAT);
  c.A(0, "rich", "move", { to: [SEAT[0], SEAT[2]], y: SEAT[1], dur: 0.01, steps: 0, ease: "linear", sync: true }); c.A(0, "rich", "turn", { to: 180, dur: 0.01, ease: "linear", sync: true });
  c.A(0, "rich", "sit", { rot: 180, dur: 0.01, height: 0, hands: "lap" });
  c.A(r3(T0 + 3.0), "rich", "look", { to: [0.25, 0.15], dur: 0.4, blink: false });
  c.prop(0, "bag", { full: 1, tilt: 55 }, 0.01); c.prop(T0, "bag", { tilt: 88 }, 0.8, "inOut");   // prime `full`, then the sack rolls flat over 0-0.8
  c.prop(r3(T0 + 0.8), "bag", { full: 0 }, 3.6, "inOut");
  const room = { type: "coast", pos: CP, breakAt: 0, breakDur: 3.0, sink: [[0, 0], [r3(T0 + 5.6), 0], [r3(T0 + 8.6), 1]], slit: [[0, 1]], rain: [[0, 0]], grass: 1 };
  const props = [
    { id: "bag", kind: "moneybag", mark: false, x: cw(COAST.BAG)[0], y: 0, z: cw(COAST.BAG)[2], rot: 0, open: true, tilt: 55 },
    { id: "storm", kind: "notestorm", t0: T0, n: 700, seed: 1, x: CP[0], y: CP[1], z: CP[2] },
  ];
  const tau = [0.05, 0.2, 0.5, 0.8, 1.2, 1.6, 2.0, 2.5, 3.0, 3.4, 3.8, 4.2, 4.6, 5.0, 6.0, 7.0, 9.0];
  const stills = tau.map((s) => r3(T0 + s)), strip = []; for (let s = 0; s <= 3.0001; s += 0.1) strip.push(r3(T0 + s));
  write(import.meta.url, {
    ...COMMON, id: "props2-storm", title: "Props2 bench: notestorm on the coast", idea: "Props bench (happiness 01 DESIGN 11.6), not a clip", duration: END,
    set: { type: "env", env: "golden-city-crossing", envCheck: false, swap: [{ at: 0, room }], ...LOOK }, hook: { show: ["rich"], hint: 0, what: "engine test" },
    cast: [{ id: "rich", character: "potatobrawl/spud-rich", at: [SEAT[0], SEAT[2]], face: 180, expr: "sad", follow: 0, seed: 2.2 }],
    props, beats: c.beats(shots, END), notes: "Generated by bench/props2/make-props2-bench.mjs. Stills: tau (s after t0 = 3.0) " + tau.join(","),
  });
  console.log("props2-storm stills at", stills.join(","));
  fs.writeFileSync(path.join(here, "storm-times.txt"), `stills ${stills.join(",")}\nstrip ${strip.join(",")}\n`);
}

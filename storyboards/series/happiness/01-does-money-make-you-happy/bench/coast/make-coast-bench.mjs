// Coast bench (happiness 01, task T5): the "coast" set (engine/page/set-coast.js) from DESIGN.md 6.6's cameras, the clip
// template's look, one stand-in Spud (the plain cast potato, standing, facing -z) at SEAT for scale and the cast's light.
// Story time: the break starts at 2.0 s and takes 3.0 s (breakAt 2, breakDur 3): u = 0.15 at 2.45, 0.4 at 3.2, 0.66 at
// 3.98, 0.85 at 4.55, 1.0 at 5.0. The sink runs 9 -> 15 s. The slit shows for panel 08 (0 - 0.8 s).
//   node storyboards/series/happiness/01-does-money-make-you-happy/bench/coast/make-coast-bench.mjs          -> coast-bench.json
//   node storyboards/series/happiness/01-does-money-make-you-happy/bench/coast/make-coast-bench.mjs --strip  -> prints the 10 fps strip times
//   flock /tmp/claude-0/render.lock node engine/render.mjs <json> --stills <times> --draft --safe --silent
//   node qa/contact.mjs out/coast-bench-*.png --out <sheet.png> [--width 360]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { COAST, heightAt } from "../../../../../../engine/page/set-coast.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const LOOK = { aperture: 0, focus: false, bloom: "emissive", lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true };
const SET = { type: "coast", breakAt: 2, breakDur: 3, sinkAt: 9, sinkDur: 6, slit: [[0, 1], [0.8, 1], [1.0, 0]], ...LOOK };
// DESIGN 6.6 starts. The 08 cameras sit below the knoll's ground in the design's numbers (y -2.5 / -2.6 at x -6..4.5, ground there
// -0.7..-0.9): lifted here to the lowest y (0.25 m steps) from which the coupe's stop CARSTOP is in line of sight over the ground
// (0.5 m clear), looking at the same target. The director refits them (qa/camfit.mjs); the heights used are printed.
const clear = (p, q) => { for (let i = 1; i < 80; i++) { const t = i / 80, x = p[0] + (q[0] - p[0]) * t, y = p[1] + (q[1] - p[1]) * t, z = p[2] + (q[2] - p[2]) * t; if (y < heightAt(x, z) + 0.5) return false; } return true; };
const lift = (c) => { const g = heightAt(c.pos[0], c.pos[2]) + 1.4, tgt = [26, -8.6, 16.2]; let y = Math.max(c.pos[1], g); while (!clear([c.pos[0], y, c.pos[2]], tgt) && y < g + 14) y += 0.25; return { ...c, pos: [c.pos[0], +y.toFixed(2), c.pos[2]] }; };
const C = COAST.CAM;
const SHOTS = [
  { at: 0, ...lift(C.c08wide) }, { at: 0.6, ...lift(C.c08climb) }, { at: 1.0, ...C.c09 },
  { at: 6.0, ...C.c10 }, { at: 9.0, ...C.c09 },
];
// the last hold: camera 09 pushing 0.6 m forward over 4 s (11 -> 15 s) as keys
const push = (t) => { const k = Math.min(1, Math.max(0, (t - 11) / 4)); return +(C.c09.pos[2] - 0.6 * k).toFixed(3); };
for (const t of [11, 11.5, 12, 12.5, 13, 13.5, 14, 14.5, 15]) SHOTS.push({ at: t, pos: [C.c09.pos[0], C.c09.pos[1], push(t)], look: C.c09.look, fov: 40 });
const STILLS = [0.3, 0.9, 1.5, 2.45, 3.2, 3.98, 4.55, 5.0, 7.0, 15.5];
const STRIP = []; for (let t = 2.0; t <= 5.0001; t += 0.1) STRIP.push(+t.toFixed(2));

const sb = {
  id: "coast-bench", title: "Coast bench: coast road, cliff top, sea, rain dusk to sunset (stand-in Spud)", fps: 30, look: "anime-pro", castLook: "sheet",
  profile: "short", loop: false, duration: 16, cleanStart: true, set: SET, music: false, sound: { sfx: 0, ambience: 0, speech: false },
  creative: { length: [1, 16], notes: false },
  cast: [{ id: "spud", character: "potatobrawl/spud", at: [0, 0], face: 180, expr: "kind", follow: 0, seed: 29 }], props: [], actions: [], captions: [],
  shots: SHOTS.map(({ at, pos, look, fov }) => ({ at, pos, look, fov })),
  notes: "Test bench, not a clip. Generated by storyboards/series/happiness/01-does-money-make-you-happy/bench/coast/make-coast-bench.mjs (task T5).",
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`08 cameras lifted to y ${SHOTS[0].pos[1]} (wide), ${SHOTS[1].pos[1]} (climb)`);
  const f = path.join(here, `${sb.id}.json`);
  fs.writeFileSync(f, JSON.stringify(sb, null, 1) + "\n");
  console.log(path.relative(process.cwd(), f));
  console.log(`stills: ${STILLS.join(",")}`);
  if (process.argv.includes("--strip")) console.log(`strip: ${STRIP.join(",")}`);
}

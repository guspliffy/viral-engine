const RIG = { hand: 2, eyes: 2, hold: 2 }, MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const FAR = 40;
const mk = (id, state, set, spots, shots) => {
  const c = clip();
  const cast = Object.entries(spots).map(([k, v]) => ({ id: k, character: v.ch, at: [FAR, 0], y: 0, face: 0, expr: "kind", follow: 0.2, seed: v.seed || 1 }));
  shots.forEach(([name, t, cam, kind, who], i) => {
    for (const k of Object.keys(spots)) {
      const w = who[k]; const to = w ? [w[0], w[1]] : [FAR, 0];
      c.A(t, k, "move", { to, ...(w && w[2] ? { y: w[2] } : { y: 0 }), dur: 0.01 }); if (w) c.A(t, k, "turn", { to: w[3] ?? 0, dur: 0.01 });
    }
  });
  const beats = c.beats(shots.map(([n, t, cam, kind]) => [n, t, cam, kind]), shots.length);
  write(import.meta.url, {
    id, title: id, idea: "Set bench for Happiness 03 (set scoreroom), not a clip",
    fps: 30, frame: "wide", look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
    set, music: false, sound: { auto: false }, hook: { show: [Object.keys(spots)[0]], hint: 0, what: "engine test" },
    cast, props: [], captions: c.captions, beats, notes: "Generated by make-rm-bench.mjs (set bench, no reviews).",
  });
};

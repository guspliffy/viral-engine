  const shots = [];
  const sleepAt = (t) => { c.A(t, "mash", "ride", { prop: "bedm", off: [-0.20, SLEEPY, 0.54], yaw: -12, dur: 0 }); c.A(t, "mash", "pitch", { to: -60, dur: 0 }); c.A(t, "mash", "lean", { to: 0, dur: 0 }); c.A(t, "mash", "face", { lid: 1, dur: 0.01 }); for (const s of [RIGHT, LEFT]) c.arm(t, "mash", s, { o: [-0.02, 0.30, -0.12] }, 0); };
  const sideAt = (t) => { c.A(t, "mash", "ride", { prop: "bedm", off: [-0.38, 0.50, 0.54], yaw: -90, dur: 0 }); c.A(t, "mash", "pitch", { to: 0, dur: 0 }); c.A(t, "mash", "lean", { to: 60, dur: 0 }); };

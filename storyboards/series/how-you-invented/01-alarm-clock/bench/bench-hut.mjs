// ---- 3. the draft tail: door bang, tuck 1 to 0, wet 0 to 1, woke 0 to 1
function tail() {
  const c = clip();
  c.prop(0, "hut", { hole: 0, door: 0.6, doorlight: 1, shadow: 0, dawn: 0 }, 0); c.prop(0, "win", { x: recentre(LENS.C04b)[0], y: recentre(LENS.C04b)[1], dawn: 0, sun: 0, woke: 0 }, 0); c.prop(0, "lane", { dawn: 0, sun: 0, woke: 0 }, 0);
  for (const id of ["bedm", "beds"]) c.prop(0, id, { tuck: 1, wet: 0 }, 0);
  c.prop(0.1, "hut", { door: 1.06 }, 0.1); c.prop(0.2, "hut", { door: 0 }, 0.12, "in");                     // the bang
  c.prop(0.6, "win", { woke: 1 }, 1.2, "linear"); c.prop(0.6, "lane", { woke: 1 }, 1.2, "linear");           // seven windows
  c.prop(1.0, "bedm", { wet: 1 }, 0.3, "linear"); c.prop(1.0, "beds", { wet: 1 }, 0.3, "linear");
  c.prop(1.8, "bedm", { tuck: 0 }, 0.1, "linear"); c.prop(1.8, "beds", { tuck: 0 }, 0.1, "linear");           // 3 frames
  c.prop(2.2, "hut", { doorlight: 0 }, 0.5, "linear");
  const beats = c.beats([["tail", 0, LENS.C04b, "tail"]], 3.2);
  write(ISO, base("bench-hut-tail", "Alarm hut bench: draft tail", [], PROPS, beats));
}

    S("SLEEP side-on, no blanket (tuck 0.1 hides tuck mesh)", 1, SIDEV, null);
    S("SIDE side-on (tuck 0)", 2, SIDEV, (u) => { sideAt(u); c.prop(u, "bedm", { tuck: 0, bolster: 0 }, 0); });
    S("UP side-on tuck 0", 3, SIDEF, (u) => { upAt(u); c.prop(u, "bedm", { tuck: 0, bolster: 1 }, 0); });
    S("Spud sit side-on", 4, { pos: [-5.5, 1.0, 0.45], look: [-1.15, 0.7, 0.45], fov: 30 }, (u) => { sleepAt(u); c.prop(u, "bedm", { tuck: 1 }, 0); });
    S("SLEEP front (from the foot), low", 5, { pos: [1.1, 0.9, 3.2], look: [1.1, 0.8, -0.84], fov: 40 }, null);
    S("SLEEP from above", 6, { pos: [1.1, 4.2, -0.80], look: [1.1, 0.5, -0.85], fov: 40 }, null);
    const beats = c.beats(shots, shots.length);

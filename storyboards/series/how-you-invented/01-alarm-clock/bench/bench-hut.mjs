    shots.forEach(([, , , label], i) => console.log(`  ${r3(i + 0.6).toFixed(2)}s  ${label}`));
    write(ISO, base(id, "Alarm hut bench: side proofs", cast.slice(0, 2), [...PROPS.filter((p) => p.id === "bedm" || p.id === "beds")], beats, { frame: "wide", allowClip: [{ who: "mash", with: "bedm", from: 0, to: shots.length, reason: "in bed" }, { who: "spud", with: "beds", from: 0, to: shots.length, reason: "in bed" }] }));

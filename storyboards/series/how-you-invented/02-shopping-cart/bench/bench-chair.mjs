// ------------------------------------------------------------------------------------------------ 2. riders (flat ground)
const RB = [0, 0.10, -0.42];   // behind the rail
// a glove on the rail's RL / RR (+-0.17, 0.475, -0.20) for Spud (body 0.88 high over 0.14 legs, arm root +-0.38) standing at RB: out = 0.17 - 0.38, up = (0.475 - 0.10 - 0.14) / 0.88, fwd = -0.20 + 0.42
const RAIL = { o: [-0.21, 0.267, 0.22] };
const FLIP = (f) => {   // panel 10: off [0,0.10,-0.42] over [0,0.95,-0.05] to [0,0.40,0.03], pitch 0 to 180 over f 0..1 (the middle at f 0.5)
  const a = RB, m = [0, 0.95, -0.05], b = [0, 0.40, 0.03], [p, q, u] = f < 0.5 ? [a, m, f / 0.5] : [m, b, (f - 0.5) / 0.5];
  return { off: p.map((v, i) => r3(v + (q[i] - v) * u)), pitch: 180 * f };
};
function spudRail(t, c, o = {}) {
  c.A(t, "spud", "ride", { prop: "cart", off: o.off ?? RB, yaw: 0, dur: 0 });
  c.A(t, "spud", "pitch", { to: o.pitch ?? 0, dur: 0 });
  c.A(t, "spud", "lean", { to: o.lean ?? 0, dur: 0 });
  for (const side of ["R", "L"]) c.arm(t, "spud", side, RAIL, 0);
}
function mashBasket(t, c, o = {}) {
  c.A(t, "mash", "ride", { prop: "cart", off: o.off ?? [0, 0.32, 0.02], yaw: 180, sit: true, dur: 0 });
}

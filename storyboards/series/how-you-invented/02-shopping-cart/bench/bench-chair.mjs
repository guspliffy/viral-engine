// ------------------------------------------------------------------------------------------------ 5. the draft tail (sequential)
function tail() {
  const c = clip(), END = 3.0, V = 1.0, TURN = 0.377;
  seed(c); c.prop(0, "cart", { fill: 1 }, 0);
  // rolls +z at 1 m/s from z -1.0: spin = distance / 0.377; brakes at 1.5 s (block on tread), cart stops dead in 2 frames, jolt 1, then Spud flips
  c.prop(0, "cart", { z: -1.0 }, 0);
  c.prop(0, "cart", { z: 0.5, spin: 1.5 / TURN }, 1.5, "linear");
  c.prop(1.5, "cart", { brake: 1 }, 0.066, "linear");
  c.prop(1.5, "cart", { jolt: 1 }, 0.5, "linear");
  c.A(0, "spud", "ride", { prop: "cart", off: RB, yaw: 0, dur: 0 });
  for (const s of ["R", "L"]) c.arm(0, "spud", s, RAIL, 0);
  c.A(1.55, "spud", "ride", { prop: "cart", off: [0, 0.95, -0.05], yaw: 0, dur: 0.16, ease: "linear" });
  c.A(1.71, "spud", "ride", { prop: "cart", off: [0, 0.40, 0.03], yaw: 0, dur: 0.16, ease: "settle" });
  c.A(1.55, "spud", "pitch", { to: 180, dur: 0.32, ease: "linear" });
  const lens = frame([0, 0.6, 0], { az: 90, el: 4, h: 2.4, fov: 30 });
  const beats = c.beats([["tail", 0, { ...lens, pos: [lens.pos[0], lens.pos[1], 0.0], look: [0, 0.6, 0] }, "tail"]], END);
  write(ISO, base("bench-chair-tail", "Chair cart bench: draft tail (roll, brake, jolt, flip)", [SPUD(-1.0, -1.0)], [{ ...CART, z: -1.0 }], beats, {
    allowClip: [{ who: "spud", with: "cart", from: 0, to: END, reason: "Spud rides behind the rail and flips into the basket" }],
  }));
}
tail();

// shots: [label, lens, fn(up) that sets the state at up = start - 0.02]; stills at i + 0.6
function run(id, title, cast, props, shots, extra = {}, init = null) {
  const c = clip();
  init?.(c);
  const list = [];
  shots.forEach(([label, lens, fn], i) => { list.push([`s${i + 1}`, i, lens, label]); fn?.(Math.max(0, i - 0.02), c); });
  const beats = c.beats(list, shots.length);
  console.log(`${id} stills: ${shots.map((_, i) => r3(i + 0.6)).join(",")}`);
  shots.forEach(([label], i) => console.log(`  ${r3(i + 0.6).toFixed(2)}s  ${label}`));
  write(ISO, base(id, title, cast, props, beats, extra));
  return c;
}


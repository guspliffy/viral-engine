// and the slip at camera 15's two sizes (290 px wide at the start of the shot, 460 px after the push, on a 1080 px wide frame). One still a second, each from its own camera. Not a clip.
//   node storyboards/series/kid-vs-dad/04-waiter-jokes/bench/bench-waiter.mjs        -> bench-waiter.json (beside this file)
//   node engine/render.mjs <that json> --stills 0.5,1.5,... --draft --safe          (the times are printed)
//   node qa/contact.mjs out/bench-waiter-*.png --out <sheet.png>
// Grip proof of the bill on the dad (panel 15), the phone hold with `flat: false` (the generic proof bench turns a tip of -60 or less into the phone-on-its-back take):
//   node storyboards/series/kid-vs-dad/04-waiter-jokes/bench/bench-waiter.mjs --grips    -> bench-grip-tipbill.json, bench-grip-tipbill-side.json (+ the two still commands)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SET = { type: "plain", color: "#2a3346", floor: "#3a3f4a", light: "golden", para: 0, aperture: 0, focus: false, lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true };
const X = { menu: -2, tray: 0, plate: 1.2, bill: 2.4, bill2: 3.4 };
// vertical fov that shows `px` pixels of a 0.125 m slip across a 1080 px frame, from distance d
const fovFor = (px, d) => Math.round((2 * Math.atan((0.125 * 1080 / px / (9 / 16)) / 2 / d) * 180) / Math.PI * 10) / 10;
const D = 1.5, SLIP_Y = 0.125;
const STILLS = [
  { name: "menu from the lens (outside: cover, gold line, spine band)", shot: { pos: [X.menu, 0.42, 1.5], look: [X.menu, 0.15, 0], fov: 30 } },
  { name: "menu from the reader (inside: cream, rules)", shot: { pos: [X.menu, 0.45, -1.5], look: [X.menu, 0.15, 0], fov: 30 } },
  { name: "menu 3/4 from above, front-left", shot: { pos: [X.menu - 0.8, 0.75, 1.1], look: [X.menu, 0.15, 0], fov: 30 } },
  { name: "menu from above (the V)", shot: { pos: [X.menu, 1.4, 0.35], look: [X.menu, 0.1, -0.05], fov: 30 } },
  { name: "tray with two glasses, 3/4 from above", shot: { pos: [X.tray + 0.45, 0.55, 0.85], look: [X.tray, 0.05, 0], fov: 30 } },
  { name: "tray from the side (rim 0.014 over the base)", shot: { pos: [X.tray + 1.0, 0.1, 0.2], look: [X.tray, 0.05, 0], fov: 22 } },
  { name: "plate from above, 3/4", shot: { pos: [X.plate + 0.1, 0.7, 0.45], look: [X.plate, 0.01, 0], fov: 22 } },
  { name: "plate from the side", shot: { pos: [X.plate + 0.7, 0.02, 0.2], look: [X.plate, 0.01, 0], fov: 14 } },
  { name: "bill from the lens, close", shot: { pos: [X.bill, SLIP_Y, 0.6], look: [X.bill, SLIP_Y, 0], fov: 26 } },
  { name: `slip at camera 15 start (290 px wide), fov ${fovFor(290, D)}`, shot: { pos: [X.bill, SLIP_Y, D], look: [X.bill, SLIP_Y, 0], fov: fovFor(290, D) } },
  { name: `slip at camera 15 end (460 px wide), fov ${fovFor(460, D)}`, shot: { pos: [X.bill, SLIP_Y, D], look: [X.bill, SLIP_Y, 0], fov: fovFor(460, D) } },
  { name: "bill from behind (tray back, wood)", shot: { pos: [X.bill + 0.5, 0.2, -0.7], look: [X.bill, 0.12, 0], fov: 26 } },
  { name: "bill, 3/4 off the lens, tipped back 70 (slip to the lens)", shot: { pos: [X.bill2 - 0.55, 0.45, 1.0], look: [X.bill2, 0.1, 0], fov: 26 } },
];
const props = [
  { id: "menu", kind: "tallmenu", x: X.menu, y: 0, z: 0 },
  { id: "tray", kind: "servetray", x: X.tray, y: 0, z: 0 },
  { id: "gl1", kind: "waterglass", x: X.tray - 0.08, y: 0.008, z: 0.02, fill: 0.8 },
  { id: "gl2", kind: "waterglass", x: X.tray + 0.07, y: 0.008, z: -0.03, fill: 0.8 },
  { id: "plate", kind: "mealplate", x: X.plate, y: 0, z: 0 },
  { id: "bill", kind: "tipbill", x: X.bill, y: 0, z: 0, rot: 180 },
  { id: "bill2", kind: "tipbill", x: X.bill2, y: 0, z: 0, rot: 180, tip: 70 },
];
const sb = {
  id: "bench-waiter", title: "Waiter props bench: tallmenu, servetray, mealplate, tipbill (Kid vs Dad 04 T3)", fps: 30, look: "anime-pro", castLook: "sheet",
  profile: "short", loop: false, duration: STILLS.length, cleanStart: true, set: SET, music: false, sound: { sfx: 0, ambience: 0, speech: false },
  creative: { length: [1, 30], notes: false }, cast: [], props, actions: [], captions: [],
  shots: STILLS.map((s, i) => ({ at: i, ...s.shot })),
  notes: "Test bench, not a clip. Generated by storyboards/series/kid-vs-dad/04-waiter-jokes/bench/bench-waiter.mjs (T3).",
};
if (process.argv.includes("--grips") && process.argv[1] === fileURLToPath(import.meta.url)) {
  const { clip, write } = await import("../../../../lib/clip.mjs"), grips = await import("../../../../lib/grips.mjs");
  const TABLE_H = 0.36, DAD = [0, -0.25], END = 3.0, HELD = [0.3, 0.47, 0.42];   // the dad stands at z -0.25: the bill middle 0.55 out (the bottom edge 0.67), bottom edge at y 0.47, top edge 0.555 (DESIGN section 6; his belly ends at 0.41)
  const TIP = +(process.env.TIP ?? 70);   // tip +70 (NOT -70: a negative tip leans the top away from the holder and turns the slip, on the -z face, DOWN): the top edge toward him, the slip up and toward the lens
  const cams = { "": { pos: [0.9, 1.0, 3.1], look: [0.15, 0.65, 0.2], fov: 32 }, "-side": { pos: [2.6, 0.5, 0.25], look: [0, 0.5, 0.25], fov: 26 } };
  for (const [view, CAM] of Object.entries(cams)) {
    const c = clip(), { A } = c, spot = [0.15, TABLE_H, 0.35];
    const spec = { id: "it", kind: "tipbill", ...grips.placeFor("tipbill", spot, 0) };
    const h = grips.phone(c, "dad", spec, { side: "R", height: 0.40, flat: false });
    A(0, "dad", "noblink");
    let t = h.take(0.3);
    t = h.carry(t + 0.05, HELD, 0.45, "inOut", { tip: TIP });
    const holdAt = Math.round((t + 0.2) * 100) / 100;
    t = h.carry(t + 0.1, [HELD[0] + 0.02, HELD[1] + 0.01, HELD[2]], 0.5);
    t = h.put(t + 0.15, spot);
    c.cap(0, END, `Bill in the dad's right hand, tipped back ${TIP} degrees${view ? ", side" : ""}`, 1500, false, { kinetic: false });
    write(import.meta.url, {
      id: `bench-grip-tipbill${view}`, title: "Bill hold proof", idea: "Grip proof, not a clip", fps: 30, look: "anime-pro", profile: "short", loop: false,
      set: { type: "apartment", seed: 5 }, music: false, sound: { auto: false }, hook: { show: ["dad", "it"], hint: 0, what: "engine test" },
      cast: [{ id: "dad", character: "potatobrawl/dad", at: DAD, face: 0, expr: "kind", follow: 0.2, seed: 2.6 }],
      props: [{ id: "table", kind: "coffeetable", x: 0, z: 0.5, h: TABLE_H, w: 1.3, d: 0.5 }, spec],
      captions: c.captions, beats: c.beats([["hold", 0, CAM]], END),
      notes: "Generated by bench-waiter.mjs --grips (grip proof, no reviews).",
    });
    console.log(`node engine/render.mjs storyboards/series/kid-vs-dad/04-waiter-jokes/bench/bench-grip-tipbill${view}.json --stills ${holdAt} --draft`);
  }
  console.log("node qa/contact.mjs out/bench-grip-tipbill*-t*.png --out out/bench-grip-tipbill.png");
  process.exit(0);
}

// Bench for the gtv "cartoon" picture (engine/page/props-gravroom.js, DESIGN.md section 2 and 4). Not a clip.
// Set gravroom, cameras D and A from facts/02-gravity/bench/make-room-bench.mjs. 13 stills, 1 s apart, each 0.6 s into its beat:
//   T1  D alps control (the unchanged picture, a second gtv prop with no `picture`)     T2-T5  D cartoon scenes 0-3
//   T6  D card .5 (scene 1 crossfading to the card)   T7  D card 1   T8  D on 0 (dark glass and its sheen)
//   T9-T12  wide A, Tato (spud-kid) on the sofa turned to the TV, scenes 0-3 (the colour on him, the sofa and the wall)
//   T13 wide A at card 1 (the room dim and still)
//   node storyboards/series/kid-vs-dad/03-square-eyes/bench/bench-tv.mjs
//   node qa/preflight.mjs storyboards/series/kid-vs-dad/03-square-eyes/bench/kvd03-tv-bench.json
//   node engine/render.mjs storyboards/series/kid-vs-dad/03-square-eyes/bench/kvd03-tv-bench.json --stills beats --draft --safe
//   node qa/contact.mjs out/kvd03-tv-bench-*.png --out <sheet.png>
// Seeding (props3d propState starts `on` at 0 and `card` is not a known key): both are keyed at t 0 before any tween.
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const CAM = {
  A: { pos: [0.05, 1.52, 3.18], look: [0.03, 1.52, -2.65], fov: 51 },
  D: { pos: [-0.84, 1.33, 0.39], look: [-1.52, 1.06, -0.96], fov: 59 },
};
const SPUD = [0.46, -1.47], SEAT = 0.45;
// [camera, { alps, scene, card, on }, label]
const SHOTS = [
  ["D", { alps: true }, "T1 D alps control"],
  ["D", { scene: 0 }, "T2 D scene 0 chase"],
  ["D", { scene: 1 }, "T3 D scene 1 face"],
  ["D", { scene: 2 }, "T4 D scene 2 boom"],
  ["D", { scene: 3 }, "T5 D scene 3 night"],
  ["D", { scene: 1, card: 0.5 }, "T6 D card .5"],
  ["D", { scene: 1, card: 1 }, "T7 D card 1"],
  ["D", { scene: 0, on: 0 }, "T8 D on 0"],
  ["A", { scene: 0 }, "T9 A Tato, scene 0"],
  ["A", { scene: 1 }, "T10 A Tato, scene 1"],
  ["A", { scene: 2 }, "T11 A Tato, scene 2"],
  ["A", { scene: 3 }, "T12 A Tato, scene 3"],
  ["A", { scene: 0, card: 1 }, "T13 A Tato, card 1"],
];
const END = SHOTS.length;
const props = [
  { id: "rug", kind: "grug", x: 0.18, y: 0, z: 0.11, rot: 0 },
  { id: "sofa", kind: "gsofa", x: 0.20, y: 0, z: -1.61, rot: 0 },
  { id: "tv", kind: "gtv", x: -1.52, y: 0, z: -0.99, rot: 34, picture: "cartoon", scene: -1, light: 0.55, castLight: 4 },
  { id: "tva", kind: "gtv", x: -1.52, y: 0, z: -0.99, rot: 34, scale: 0 },
  { id: "lamp", kind: "glamp", x: 1.45, y: 0, z: -2.12, rot: 0 },
  { id: "plant", kind: "gplant", x: 1.80, y: 0, z: -1.60, rot: 0 },
  { id: "haze", kind: "ghaze", x: 0, y: 0, z: 0, rot: 0, haze: 0 },   // as the gravity bench has it, so T1 can be compared with its still
];
const cast = [{ id: "tato", character: "potatobrawl/spud-kid", at: SPUD, face: 0, expr: "kind", follow: 0, seed: 2.9 }];
c.A(0, "tato", "sit", { rot: -70, height: SEAT, dur: 0, hands: "keep" });
c.prop(0, "haze", { haze: 0 }, 0, "linear");
c.prop(0, "tv", { on: 1, card: 0, glow: 1, scene: 0 }, 0, "linear");
SHOTS.forEach(([, p], i) => {
  const t = r3(i + 0.01);
  c.prop(t, "tv", { scale: p.alps ? 0 : 1, on: p.on ?? 1, card: p.card ?? 0, scene: p.scene ?? 0 }, 0, "linear");
  c.prop(t, "tva", { scale: p.alps ? 1 : 0 }, 0, "linear");
});
const beats = c.beats(SHOTS.map(([cam, , label], i) => [`t${i + 1}`, i, CAM[cam], label]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "kvd03-tv-bench", title: "Kid vs Dad 03 TV bench", idea: "Props bench for the gtv cartoon picture (gravroom set), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: false }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast, props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/kid-vs-dad/03-square-eyes/bench/bench-tv.mjs (props bench, no reviews).",
});

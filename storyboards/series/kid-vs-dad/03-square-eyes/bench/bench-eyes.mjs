// Square-eyes bench (Kid vs Dad 03, builder A "eyes"; DESIGN.md section 4: engine/page/squareeyes.js). Not a clip.
// Set `plain` (day), look anime-pro, castLook sheet, rig eyes 2, like the clip. One beat a second, a still 0.6 s into each:
//   E1  Tato eyes, frame 0.45 m wide, no keys (the rig)      E2  square 0.02 (must look the same as E1)
//   E3  square 0.5   E4  square 1   E5  square 1 lids 0.5   E6  square 1 lids 1
//   E7  square 1 look [0.9, 0.4]   E8  look [-0.9, -0.4]   E9  square 1 shocked   E10  square 1 deadpan
//   E11 square 0.02 sqCorner 1   E12 sqCorner 0.5
//   E13 Dad phone eyes (square 1, sqTall 1, sqPhone 1), frame 0.6 m wide   E14 lids 0.5   E15 sqPhone 0
//   E16 medium line-up, frame 3.3 m wide (2.6 cut Mash and the reporter off): Mash square 1, Tato 0.5, Dad phone, reporter untouched   E17 the same, camera 35 degrees round
//   E18 the line-up on a dimmer room: NOT BUILT here (the plain set has no `set.lights`; the gravroom bench takes it)
//   E19a Mash's two blinks (frame 0.40 m wide), E19b Tato's H3 flicker (frame 0.45 m wide): 2 s each, stills at 15 fps
// Beats E1-E17 are stills at i + 0.6 (sheets: bench-eyes-A = E1-E12, B = E13-E17, C = E19a + E19b).
//   node storyboards/series/kid-vs-dad/03-square-eyes/bench/bench-eyes.mjs   -> bench-eyes.json (beside this file); prints the stills
//   node engine/render.mjs <that json> --stills <the printed list> --draft --safe ; node qa/contact.mjs out/bench-eyes-*.png --out <sheet.png>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const r3 = (v) => Math.round(v * 1000) / 1000;
const SET = { type: "plain", color: "#dfe6ee", floor: "#cfd8e2", aperture: 0, focus: false, lighting: 2, hatch: { boil: 0.25 }, cel: { at: 0.25 }, ink: true, satsuei: true };

// the cast in a row (x, z); `eye` = the middle of the two eyes in the world, read from the bench layout (out/bench-eyes-anime-pro.layout.json, actors[].eyes)
const CAST = {
  mash: { character: "potatobrawl/mash", at: [-1.15, 0], eye: [-1.169, 0.81, 0.23], seed: 3.7 },
  tato: { character: "potatobrawl/spud-kid", at: [-0.4, 0], eye: [-0.418, 0.434, 0.201], seed: 4.1 },
  dad: { character: "potatobrawl/wedge", at: [0.65, 0], eye: [0.67, 0.679, 0.324], seed: 2.9 },
  rep: { character: "potatobrawl/reporter", at: [1.5, -0.5], eye: [1.508, 0.57, -0.184], seed: 131.3 },
};
const W_PER_D = (fov) => 2 * Math.tan((fov / 2) * Math.PI / 180) * (9 / 16);   // frame width = d x this (1080x1920 portrait, vertical fov)
const close = (who, width, fov = 30) => { const [x, y, z] = CAST[who].eye, d = width / W_PER_D(fov); return { pos: [x, y, r3(z + d)], look: [x, y, z], fov }; };
const MID = (deg) => { const fov = 40, d = 3.3 / W_PER_D(fov), cx = 0.2, a = (deg * Math.PI) / 180; return { pos: [r3(cx + d * Math.sin(a)), 1.1, r3(d * Math.cos(a))], look: [cx, 0.62, -0.1], fov }; };

const KEYS = { square: 0, sqCorner: 0, sqTall: 0, sqPhone: 0 };
const PHONE = { square: 1, sqTall: 1, sqPhone: 1 };
const base = (id, title, duration, shots, actions) => ({
  id, title, fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, duration, cleanStart: true,
  motion: { feet: 2, overlap: true, timing: true, solve: true }, rig: { hand: 2, eyes: 2, hold: 2 }, physics: false, animeTiming: true, far: 200,
  set: SET, music: false, sound: { sfx: 0, ambience: 0, speech: false }, creative: { length: [1, 60], notes: false },
  cast: Object.entries(CAST).map(([id, c]) => ({ id, character: c.character, at: c.at, face: 0, expr: "kind", follow: 0, seed: c.seed })),
  actions, captions: [], shots,
  notes: "Test bench, not a clip. Generated by storyboards/series/kid-vs-dad/03-square-eyes/bench/bench-eyes.mjs (square eyes, builder A).",
});

// one beat's state for an actor: every face key absolute, so no beat leaks into the next
const S = (at, who, { keys = {}, lids = [0.04, 0.04], expr = "kind", look = [0, 0], set } = {}) => [
  { who, at, do: "face", ...KEYS, ...keys, lidL: lids[0], lidR: lids[1], dur: 0 },
  { who, at, do: "expr", expr, ...(set ? { set } : {}), dur: 0 },
  { who, at, do: "look", to: look, dur: 0, blink: false },
];

const BEATS = [
  // [name, who, state, camera]
  ["E1 Tato rig eyes (no keys)", "tato", {}, close("tato", 0.45)],
  ["E2 square 0.02", "tato", { keys: { square: 0.02 } }, close("tato", 0.45)],
  ["E3 square 0.5", "tato", { keys: { square: 0.5 } }, close("tato", 0.45)],
  ["E4 square 1", "tato", { keys: { square: 1 } }, close("tato", 0.45)],
  ["E5 square 1, lids 0.5", "tato", { keys: { square: 1 }, lids: [0.5, 0.5] }, close("tato", 0.45)],
  ["E6 square 1, lids 1", "tato", { keys: { square: 1 }, lids: [1, 1] }, close("tato", 0.45)],
  ["E7 square 1, look [0.9, 0.4]", "tato", { keys: { square: 1 }, look: [0.9, 0.4] }, close("tato", 0.45)],
  ["E8 square 1, look [-0.9, -0.4]", "tato", { keys: { square: 1 }, look: [-0.9, -0.4] }, close("tato", 0.45)],
  ["E9 square 1, shocked", "tato", { keys: { square: 1 }, expr: "shocked" }, close("tato", 0.45)],
  ["E10 square 1, deadpan", "tato", { keys: { square: 1 }, expr: "deadpan" }, close("tato", 0.45)],
  ["E11 square 0.02, sqCorner 1", "tato", { keys: { square: 0.02, sqCorner: 1 } }, close("tato", 0.45)],
  ["E12 square 0.02, sqCorner 0.5", "tato", { keys: { square: 0.02, sqCorner: 0.5 } }, close("tato", 0.45)],
  ["E13 Dad phone eyes", "dad", { keys: PHONE }, close("dad", 0.6)],
  ["E14 Dad phone eyes, lids 0.5", "dad", { keys: PHONE, lids: [0.5, 0.5] }, close("dad", 0.6)],
  ["E15 Dad tall square, sqPhone 0", "dad", { keys: { square: 1, sqTall: 1 } }, close("dad", 0.6)],
];
const LINEUP = [["mash", { keys: { square: 1 } }], ["tato", { keys: { square: 0.5 } }], ["dad", { keys: PHONE }]];

const actions = CAST_IDS().map((id) => ({ who: id, at: 0, do: "noblink" }));
function CAST_IDS() { return Object.keys(CAST); }
const shots = [], stills = [], names = [];
BEATS.forEach(([name, who, st, cam], i) => { actions.push(...S(i, who, st)); shots.push({ at: i, ...cam }); stills.push(r3(i + 0.6)); names.push(name); });
{
  const i = BEATS.length;   // E16, E17: the line-up, then from 35 degrees to the side
  for (const [who, st] of LINEUP) actions.push(...S(i, who, st));
  shots.push({ at: i, ...MID(0) }, { at: i + 1, ...MID(35) });
  stills.push(r3(i + 0.6), r3(i + 1.6)); names.push("E16 line-up", "E17 line-up, camera 35 deg round");
}
let t0 = BEATS.length + 2;   // E19a: Mash's two blinks
const MASH_STATE = { keys: { square: 1 }, set: { eye: 1.12, browY: 0.02, tilt: 0.05, curve: 0.2, open: 0, pupil: 0.85 } };
actions.push(...S(t0, "mash", MASH_STATE), { who: "mash", at: r3(t0 + 0.3), do: "blink", dur: 0.27 }, { who: "mash", at: r3(t0 + 0.85), do: "blink", dur: 0.27 });
shots.push({ at: t0, ...close("mash", 0.4) });
for (const f of [6, 8, 10, 12, 14, 16, 18, 22, 28, 30]) { stills.push(r3(t0 + f / 30)); names.push(`E19a Mash blinks, frame ${f}`); }
const t1 = t0 + 2;   // E19b: Tato's H3 flicker, frame numbers from the cut
actions.push(...S(t1, "tato", { keys: { square: 0.02 } }));
const fr = (f) => r3(t1 + f / 30), snap = (f0, f1, v) => ({ who: "tato", at: fr(f0), do: "face", sqCorner: v, dur: r3((f1 - f0) / 30) });
actions.push(snap(8, 10, 1), snap(15, 17, 0), snap(24, 26, 1), snap(36, 38, 0));
for (const f of [16, 37]) actions.push({ who: "tato", at: fr(f), do: "face", lidL: 0.24, dur: 0 }, { who: "tato", at: fr(f + 4), do: "face", lidL: 0.04, dur: 0 });   // his eye twitches after each snap
shots.push({ at: t1, ...close("tato", 0.45) });
for (const f of [7, 9, 10, 12, 15, 16, 17, 18, 25, 27, 30, 37, 38, 40]) { stills.push(fr(f)); names.push(`E19b Tato flicker, frame ${f}`); }

const sb = base("bench-eyes", "Square-eyes bench (Kid vs Dad 03, builder A)", t1 + 2, shots, actions);
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const f = path.join(here, `${sb.id}.json`);
  fs.writeFileSync(f, JSON.stringify(sb, null, 1) + "\n");
  console.log(path.relative(process.cwd(), f));
  console.log(`stills: ${stills.join(",")}`);
  stills.forEach((t, i) => console.log(`  ${t}  ${names[i]}`));
}

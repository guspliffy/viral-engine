// Country vs Country 01 cast bench (T3): the retiree (characters/potatobrawl/retiree.json, costume.watch "L") beside Spud 1.2 m apart,
// front and 3/4; Mash in the plain green bagger apron (props-winter.js `apron`: color, bib, straps). Not a clip.
//   ret-front / ret-34   retiree (left of frame) + Spud, 1.2 m apart, both at rest
//   ret-watch            close-up of the retiree's left wrist, forearm raised in front of the chest (arm pose "hold")
//   mash-front / mash-34 Mash in the apron
//   mash-close           the bib and the straps under the headphones
//   node .../bench/make-bench-cast.mjs && node engine/render.mjs .../bench/cast-bench.json --stills <times printed> --draft --safe --out <dir>
// The cap is the separate worn prop `tweedcap` (another builder): none here (the registered `flatcap` is the soft black one of props-spree.js).
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip(), { A } = c;
const RIG = { hand: 2, eyes: 2, hold: 2 };
const MOTION = { feet: 2, overlap: true, timing: true, solve: true };
const actor = (id, character, gx, face, expr = "kind", seed = 2.6) => ({ id, character, at: [gx, 0], face, expr, follow: 0.2, seed });
const cast = [], SHOTS = [], T = {};
let gx = -49, k = 0;
const GAP = 1.2;
for (const [name, face] of [["front", 0], ["34", 36]]) {
  const id = `ret-${name}`; T[id] = k++;
  cast.push(actor(`retiree-${name}`, "potatobrawl/retiree", gx - GAP / 2, face, "deadpan"), actor(`spud-${name}`, "potatobrawl/spud", gx + GAP / 2, -face, "kind"));
  SHOTS.push([id, { pos: [gx, 0.7, 7.2], look: [gx, 0.45, 0], fov: 34 }]); gx += 7;
}
// the watch: the retiree's left arm raised in front of his chest
T.watch = k++; cast.push(actor("retiree-watch", "potatobrawl/retiree", gx, 20, "deadpan"));
SHOTS.push(["watch", { pos: [gx + 0.75, 0.6, 1.8], look: [gx + 0.5, 0.5, 0.2], fov: 22 }]);
c.arm(0, "retiree-watch", "L", "hold", 0.01); gx += 7;
for (const [name, face, ox] of [["front", 0, 0], ["34", 30, 1.0]]) {
  const id = `mash-${name}`; T[id] = k++; cast.push(actor(id, "potatobrawl/mash", gx, face, "kind"));
  SHOTS.push([id, { pos: [gx + ox, 0.95, 5.4], look: [gx, 0.68, 0], fov: 34 }]); gx += 7;
}
T.close = k++; SHOTS.push(["close", { pos: [gx - 7 + 0.5, 0.85, 2.6], look: [gx - 7, 0.72, 0], fov: 28 }]);   // Mash 3/4 again, close
const END = k;
const props = [], ALLOW = [];
for (const id of ["mash-front", "mash-34"]) {
  props.push({ id: `apron-${id}`, kind: "apron", wear: id, x: 0, y: 0, z: 0, y0: 0.46, y1: 0.20, rx: 0.29, rz: 0.27, arc: 140, color: "#3f8a3a", bib: { top: 0.60, w: 0.24 }, straps: true });
  ALLOW.push({ who: id, with: `apron-${id}`, from: 0, to: END, reason: "worn by Mash" });
}
for (const w of cast.map((a) => a.id)) A(0, w, "noblink");
const times = SHOTS.map(([n]) => r3(T[n] + 0.55));
console.log("stills:", times.join(","));
write(import.meta.url, {
  id: "cast-bench", title: "Country vs Country 01 cast bench", idea: "the retiree beside Spud, Mash in the green apron, not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", motion: MOTION, rig: RIG, physics: false,
  set: { type: "plain", color: "#5b6376", floor: "#3f4655" }, music: false, sound: { auto: false },
  hook: { show: ["retiree-front"], hint: 0, what: "engine test" },
  cast, props, allowClip: ALLOW, captions: c.captions, beats: c.beats(SHOTS.map(([n, cam]) => [n, T[n], cam]), END),
  notes: "Generated by storyboards/series/country-vs-country/01-checkout/bench/make-bench-cast.mjs (cast bench, no reviews).",
});

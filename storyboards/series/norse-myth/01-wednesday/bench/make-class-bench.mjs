import { clip, write } from "../../../../lib/clip.mjs";

const c = clip();
const ONLY = process.argv.slice(2);
const shots = [];
const cam = (x, y, z, lx, ly, lz, fov) => ({ pos: [x, y, z], look: [lx, ly, lz], fov });
const beat = (name, t0, camera, acts = () => {}) => { if (ONLY.length && !ONLY.includes(name)) return; acts(t0); shots.push([name, t0, camera]); };
const K = (t, set) => c.prop(t, "room", set, 0);

const RB = 20;   // the second room (no pupils) at x 20: the shelf, drawings and clock counted without anybody in front
beat("room", 52, cam(0, 1.3, 6.5, 0, 1.2, -1.6, 52));
beat("shelfL", 53, cam(RB - 0.55, 0.62, 3.4, RB - 0.55, 0.62, -2.0, 36));

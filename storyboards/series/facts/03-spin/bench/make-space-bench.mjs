// Bench for space (engine/page/props-spinspace.js, task T5 of fact what-if 03 "Earth spins faster"): sstars, searth, sdisc in world SP at [80000,0,0]
// from the DESIGN H6 / J cameras (fov 40, looking straight down -z at Earth's centre, shifted so Earth sits where the sheets put it). Not a clip.
// Eight stills, 1 s apart, 0.6 s into each beat; each beat jumps the one param `t` (clip seconds):
//   P15 at 60.5 63 65.5     P16 at 67 70 73.0     P17 at 74 77
//   node storyboards/series/facts/03-spin/bench/make-space-bench.mjs
//   node engine/render.mjs storyboards/series/facts/03-spin/bench/space-bench.json --stills 0.6,1.6,2.6,3.6,4.6,5.6,6.6,7.6 --draft --safe
//   node qa/contact.mjs out/space-bench-*.png --out <tmp>/space-sheet.png   (then saved as bench/space-sheet.jpg)
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const O = [80000, 0, 0], FOV = 40, TAN = Math.tan((FOV / 2) * Math.PI / 180);
const ppu = (D) => 1920 / (2 * D * TAN);                              // screen px per world unit at distance D (1080 x 1920 frame)
// camera so that Earth's centre (the origin) appears at px (ex, ey), D from it; the camera looks straight down -z
const cam = (ex, ey, D) => { const k = ppu(D), x = (540 - ex) / k, y = (ey - 960) / k; return { pos: [O[0] + x, O[1] + y, O[2] + D].map(r3), look: [O[0] + x, O[1] + y, O[2]].map(r3), fov: FOV }; };
const CAM = { P15: cam(520, 880, 761), P16: cam(540, 800, 690), P17: cam(560, 760, 1165) };
const SHOTS = [["P15", 60.5], ["P15", 63], ["P15", 65.5], ["P16", 67], ["P16", 70], ["P16", 73.0], ["P17", 74], ["P17", 77]];
// Spud (H6): where his centre is on the screen at the Earth-centre depth (z 0), and his height in world units
const spud = (name, D, ex, ey, sx, sy, hpx) => { const k = ppu(D), cm = cam(ex, ey, D); const p = [(sx - 540) / k + (cm.pos[0] - O[0]), -(sy - 960) / k + (cm.pos[1] - O[1]), 0]; return { name, pos: p.map(r3), unitsTall: r3(hpx / k) }; };
console.log("cams:", JSON.stringify(CAM));
console.log("spud:", JSON.stringify([spud("P15 back", 761, 520, 880, 760, 1500, 330), spud("P16 back", 690, 540, 800, 700, 1560, 380), spud("P17 front", 1165, 560, 760, 600, 1520, 420)]));
const props = [
  { id: "stars", kind: "sstars", x: 0, y: 0, z: 0, rot: 0 },
  { id: "earth", kind: "searth", x: 0, y: 0, z: 0, rot: 0, t: 60 },
  { id: "disc", kind: "sdisc", x: 0, y: 0, z: 0, rot: 0, t: 60 },
];
c.prop(0, "earth", { t: 60 }, 0, "linear"); c.prop(0, "disc", { t: 60 }, 0, "linear");
SHOTS.forEach(([, t], i) => { c.prop(i + 0.01, "earth", { t }, 0, "linear"); c.prop(i + 0.01, "disc", { t }, 0, "linear"); });
const END = SHOTS.length;
const beats = c.beats(SHOTS.map(([k, t], i) => [`s${i + 1}`, i, CAM[k], `${k} t ${t}`]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "space-bench", title: "Spin space bench", idea: "Props bench for fact what-if 03 spin (sstars, searth, sdisc), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: true }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/03-spin/bench/make-space-bench.mjs (props bench, no reviews).",
});

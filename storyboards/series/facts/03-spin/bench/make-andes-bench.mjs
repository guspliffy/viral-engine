// Bench for Quito, the Andes valleys and the rising sea (engine/page/props-spinandes.js, task T3 of fact what-if 03 "Earth spins faster"):
// sandes + ssea from the DESIGN J cameras P1 (window view, t 0 and 1.0), P2 (2.2, 4.5), P3 (5.0, 8.5), a P9-like street view (31), and shigh from P14 (55, 59.5).
// Not a clip: no room, no sky, no street, no Spud. Nine stills, 1 s apart, each 0.6 s into its beat (t jumps 0.01 s after the beat starts).
//   node storyboards/series/facts/03-spin/bench/make-andes-bench.mjs
//   flock /tmp/claude-0/spin-render.lock node engine/render.mjs storyboards/series/facts/03-spin/bench/andes-bench.json --stills 0.6,1.6,2.6,3.6,4.6,5.6,6.6,7.6,8.6 --draft --safe
//   node qa/contact.mjs out/andes-bench-*.png --out storyboards/series/facts/03-spin/bench/andes-sheet.png   (then save as andes-sheet.jpg)
import { clip, write, r3 } from "../../../../lib/clip.mjs";
import { alt, spin } from "../../../../../engine/page/spin-tracks.js";

const c = clip();
const END = 9.0, HI = [40000, 0, 0];
const lerp = (a, b, k) => a + (b - a) * k;
const hiCam = (t) => {   // DESIGN G: camera height over the surface and pitch from `alt`, a point under it at HI + (0, 2400, 0)
  const a = alt(t), h = a < 0.5 ? lerp(1100, 1450, a / 0.5) : lerp(1450, 1784, (a - 0.5) / 0.5), p = (a < 0.5 ? lerp(43.7, 48.4, a / 0.5) : lerp(48.4, 52, (a - 0.5) / 0.5)) * Math.PI / 180;
  const pos = [HI[0], 2400 + h, HI[2]];
  return { pos: pos.map(r3), look: [pos[0], pos[1] - 1000 * Math.sin(p), pos[2] - 1000 * Math.cos(p)].map(r3), fov: 50, near: 4 };
};
const CAM = {
  P1: { pos: [0.55, 1.28, 0.6], look: [0.15, 0.1, -8], fov: 59, near: 0.04 },
  P2: { pos: [40, 62, 250], look: [-60, -170, -1500], fov: 50, near: 4 },
  P3a: { pos: [800, -60, -900], look: [800, -286, -1250], fov: 44, near: 4 },
  P3b: { pos: [800, -60, -900], look: [800, -286, -1250], fov: 36, near: 4 },
  P9: { pos: [-1.6, -9.9, -13.5], look: [2.2, -9.4, -20], fov: 55, near: 0.5 },
};
const SHOTS = [["P1", 0], ["P1", 1.0], ["P2", 2.2], ["P2", 4.5], ["P3a", 5.0], ["P3b", 8.5], ["P9", 31], ["P14", 55], ["P14", 59.5]];
const camOf = ([cam, tt]) => (cam === "P14" ? hiCam(tt) : CAM[cam]);
const props = [{ id: "sandes", kind: "sandes", x: 0, y: 0, z: 0, rot: 0, t: -1 }, { id: "ssea", kind: "ssea", x: 0, y: 0, z: 0, rot: 0, t: -1 }, { id: "shigh", kind: "shigh", x: 0, y: 0, z: 0, rot: 0, t: -1 }];
const set = (at, s) => { for (const id of ["sandes", "ssea", "shigh"]) c.prop(at, id, { t: s[1], ...(id === "sandes" && { centro: s[0] === "P2" ? 1 : 0 }) }, 0, "linear"); };
set(0, SHOTS[0]);
SHOTS.forEach((s, i) => set(i + 0.01, s));
const beats = c.beats(SHOTS.map((s, i) => [`a${i + 1}`, i, camOf(s), `${s[0]} t ${s[1]} (${spin(s[1]).toFixed(1)}x)`]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "andes-bench", title: "Spin Andes bench", idea: "Props bench for fact what-if 03 spin (sandes, ssea, shigh), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: true }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/03-spin/bench/make-andes-bench.mjs (props bench, no reviews).",
});

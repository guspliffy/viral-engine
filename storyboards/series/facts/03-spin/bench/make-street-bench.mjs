// Bench for the steep Quito street and its weather (engine/page/props-spinstreet.js, task T4): sstreet, sball, srain, sblobs on the
// bare room set (lights only), "far": 6000. Not a clip. Stills from DESIGN section J's cameras P9-P13, each at its own time:
//   P9 31.5   P10 38   P11 44.5   P12 48.5   P13 51.5 and 53.5
//   node storyboards/series/facts/03-spin/bench/make-street-bench.mjs
//   node engine/render.mjs storyboards/series/facts/03-spin/bench/street-bench.json --stills 31.5,38,44.5,48.5,51.5,53.5 --draft --safe
//   node qa/contact.mjs out/street-bench-*.png --out storyboards/series/facts/03-spin/bench/street-sheet.jpg
// Every prop takes the param t = clip seconds, tweened linearly from 0 to END (seeded at 0, as the gravity props).
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const END = 62;
// P13 is P12's camera tilting up 6 deg and rising .8 m over 50-55 s
const P12 = { pos: [2.0, -16.4, -53.0], look: [1.6, -18.6, -75.0], fov: 52 };
const p13 = (u) => {
  const dx = P12.look[0] - P12.pos[0], dy = P12.look[1] - P12.pos[1], dz = P12.look[2] - P12.pos[2], h = Math.hypot(dx, dz), pitch = Math.atan2(dy, h) + (6 * Math.PI / 180) * u;
  return { pos: [P12.pos[0], r3(P12.pos[1] + 0.8 * u), P12.pos[2]], look: [r3(P12.pos[0] + (dx / h) * 22), r3(P12.pos[1] + 0.8 * u + Math.tan(pitch) * 22), r3(P12.pos[2] + (dz / h) * 22)], fov: 52 };
};
const SHOTS = [
  ["p9", 0, { pos: [-1.6, -9.9, -13.5], look: [2.2, -9.4, -20], fov: 55 }, "P9 (31.5 s)"],
  ["p10", 36, { pos: [0.3, -12.2, -29], look: [0, -17.5, -70], fov: 55 }, "P10 (38 s)"],
  ["p11", 44, { pos: [-1.9, -16.4, -53.5], look: [2.4, -16.3, -58.5], fov: 50 }, "P11 (44.5 s)"],
  ["p12", 48, P12, "P12 (48.5 s)"],
  ["p13a", 50.5, p13(0.3), "P13 (51.5 s)"],
  ["p13b", 52.5, p13(0.7), "P13 (53.5 s)"],
];
const props = [
  { id: "street", kind: "sstreet", x: 0, y: 0, z: 0, rot: 0, splash: [[37.2, -0.2, 40.2]] },
  { id: "rain", kind: "srain", x: 0, y: 0, z: 0, rot: 0 },
  { id: "blobs", kind: "sblobs", x: 0, y: 0, z: 0, rot: 0 },
  { id: "ball", kind: "sball", x: 2.9, y: -9.45, z: -19.7, rot: 0, float: 36.7 },
];
for (const p of props) { c.prop(0, p.id, { t: 0 }, 0, "linear"); c.prop(0, p.id, { t: END }, END, "linear"); }
const beats = c.beats(SHOTS.map(([n, at, cam, label]) => [n, at, cam, label]), END);
write(import.meta.url, {
  id: "street-bench", title: "Spin street bench", idea: "Props bench for fact what-if 03 (sstreet, sball, srain, sblobs), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "spinroom", bare: true, light: "golden", key: [2.6, 3.6, 4.4] }, music: false, sound: { auto: false },
  hook: { show: ["street"], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/03-spin/bench/make-street-bench.mjs (props bench, no reviews).",
});

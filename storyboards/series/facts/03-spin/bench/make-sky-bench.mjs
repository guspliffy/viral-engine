// Bench for the sky of fact what-if 03 "Earth spins faster" (engine/page/props-spinsky.js, task T2): ssky, sclouds, sstorm on the bare
// gravroom set (lights and background only: an open view, no room, no terrain), from the director's cameras (DESIGN section J, all
// looking toward -z). Not a clip. 20 stills 1 s apart (0.6 s into each beat; each beat jumps the one param `t` = clip seconds):
//   1-3 P1 at t 0 / 1.0 / 1.57 (sunset in the hook)   4 P2 at 3.8 (sunrise)   5 P6 at 6.5 (night: stars, moon)   6 P6 at 13.0 (storm veil)
//   7 P6 at 15.34 (terminator mid-sky)  8 P6 at 15.5   9 P7 at 26.7   10 P9 at 33   11 P11 at 45   12 P12 at 48   13 P13 at 52
//   14 P5 at 13.0 WITH the storm   15-16 P11 at 43.2 / 43.4 (the clouds swap from sprites to the dome bake on the 43.3 cut)
//   18-19 P1 at 1.2 / 2.2 (sun low left, trail up right)   20 P5W at 13.0 with the storm, fov 95 (the whole disc, tilted)
//   17 P1 at 1.0 with spec.trail 2 (the sheet's P1 spreads its ghosts wider than DESIGN B2's 26 deg of wheel angle gives)
// plus the B7 comfort strips: 12 stills 1/3 s apart in two windows (t 44-47.67 at P12, t 19-22.67 at P7; the sky tweened linear):
//   node storyboards/series/facts/03-spin/bench/make-sky-bench.mjs
//   flock /tmp/claude-0/spin-render.lock node engine/render.mjs storyboards/series/facts/03-spin/bench/sky-bench.json --stills <printed list> --draft --safe
//   node qa/contact.mjs out/sky-bench-*.png --out <tmp>/sky-sheet.png   (the first 20 only; then saved as bench/sky-sheet.jpg, JPEG q80)
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const CAM = {
  P1: { pos: [0.55, 1.28, 0.6], look: [0.15, 0.1, -8], fov: 59 },
  P2: { pos: [40, 62, 250], look: [-60, -170, -1500], fov: 50 },
  P5: { pos: [0.5, 1.0, 0.05], look: [1.05, 1.1, -2.65], fov: 56 },
  P5W: { pos: [0.5, 1.0, 0.05], look: [1.05, 1.1, -2.65], fov: 95 },
  P6: { pos: [-0.35, 0.95, -0.55], look: [-0.05, 0.8, -2.4], fov: 54 },
  P7: { pos: [0.55, 0.8, 0.95], look: [-0.25, 1.05, -1.6], fov: 56 },
  P9: { pos: [-1.6, -9.9, -13.5], look: [2.2, -9.4, -20], fov: 55 },
  P11: { pos: [-1.9, -16.4, -53.5], look: [2.4, -16.3, -58.5], fov: 50 },
  P12: { pos: [2.0, -16.4, -53.0], look: [1.6, -16.2, -75], fov: 52 },
  P13: { pos: [2.0, -15.6, -53.0], look: [1.6, -16.0, -75], fov: 52 },
};
const SHOTS = [["P1", 0], ["P1", 1.0], ["P1", 1.57], ["P2", 3.8], ["P6", 6.5], ["P6", 13.0], ["P6", 15.34], ["P6", 15.5], ["P7", 26.7], ["P9", 33], ["P11", 45], ["P12", 48], ["P13", 52], ["P5", 13.0, true], ["P11", 43.2], ["P11", 43.4], ["P1", 1.0, false, 2], ["P1", 1.2], ["P1", 2.2], ["P5W", 13.0, true]];
const N = SHOTS.length, LUM = [["P12", 44, N], ["P7", 19, N + 4]];   // [camera, t at the start, beat start]
const END = N + 8;
const props = [
  { id: "sky", kind: "ssky", x: 0, y: 0, z: 0, rot: 0, t: 0, trail: 1 },
  { id: "clouds", kind: "sclouds", x: 0, y: 0, z: 0, rot: 0, t: 0 },
  { id: "storm", kind: "sstorm", x: 0, y: 0, z: 0, rot: 0, t: -1 },
];
const IDS = ["sky", "clouds", "storm"];
for (const id of IDS) c.prop(0, id, { t: id === "storm" ? -1 : 0, ...(id === "sky" && { trail: 1 }) }, 0, "linear");
SHOTS.forEach(([, t, storm, trail], i) => { for (const id of IDS) c.prop(i + 0.01, id, { t: id === "storm" && !storm ? -1 : t, ...(id === "sky" && { trail: trail ?? 1 }) }, 0, "linear"); });
for (const [, t0, b0] of LUM) {
  for (const id of ["sky", "clouds"]) { c.prop(b0 - 0.001, id, { t: t0 }, 0, "linear"); c.prop(b0, id, { t: t0 + 4 }, 4, "linear"); }
  c.prop(b0 - 0.001, "sky", { trail: 1 }, 0, "linear");
  c.prop(b0 - 0.001, "storm", { t: -1 }, 0, "linear");
}
const shots = [...SHOTS.map(([cam, t], i) => [`s${i + 1}`, i, CAM[cam], `${cam} t ${t}`]), ...LUM.map(([cam, t0, b0]) => [`lum${b0}`, b0, CAM[cam], `${cam} lum t ${t0}-${t0 + 4}`])];
const beats = c.beats(shots, END);
const stills = [...SHOTS.map((_, i) => r3(i + 0.6)), ...LUM.flatMap(([, , b0]) => Array.from({ length: 12 }, (_, k) => r3(b0 + k / 3)))];
console.log("stills:", stills.join(","));

write(import.meta.url, {
  id: "sky-bench", title: "Spin sky bench", idea: "Props bench for fact what-if 03 spin (ssky, sclouds, sstorm), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: true }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/03-spin/bench/make-sky-bench.mjs (props bench, no reviews).",
});

// Bench for the satellite entry, the strikes and the window cracks (engine/page/props-gravstrike.js, task T5 of the gravity v2 builds):
// gentry, gstrike, gglass on the gravroom set (not bare: the window frame and the cracks' glass are the set's), with gsky, gclouds,
// the ground (no intact buildings: the city is rubble by 33 g) and the sofa behind them, from DESIGN-v2 section E cameras P3 and P4. Not a clip. 12 stills, 1 s apart, 0.6 s into each beat;
// each beat jumps the one param `t` (clip seconds) to the time shown:
//   P3 at 33.2 33.8 34.6 35.4 35.9     P4 at 36.05 36.2 36.6 37.0 37.3 38.5 42
//   node storyboards/series/facts/02-gravity/bench/make-strike-bench.mjs
//   node engine/render.mjs storyboards/series/facts/02-gravity/bench/strike-bench.json --stills 0.6,1.6,2.6,3.6,4.6,5.6,6.6,7.6,8.6,9.6,10.6,11.6 --draft --safe
//   node qa/contact.mjs out/strike-bench-*.png --out storyboards/series/facts/02-gravity/bench/strike-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const CAM = {
  P3: { pos: [0.34, 1.18, 0.94], look: [0.55, 2.34, -8], fov: 63 },
  P4: { pos: [0.34, 1.30, -0.02], look: [-0.12, 0.95, -8], fov: 60 },
};
const SHOTS = [["P3", 33.2], ["P3", 33.8], ["P3", 34.6], ["P3", 35.4], ["P3", 35.9], ["P4", 36.05], ["P4", 36.2], ["P4", 36.6], ["P4", 37.0], ["P4", 37.3], ["P4", 38.5], ["P4", 42]];
const END = SHOTS.length;
const FROM = [0.05, 1.52, 3.18];
const props = [
  { id: "sky", kind: "gsky", x: 0, y: 0, z: 0, rot: 0, from: FROM },
  { id: "clouds", kind: "gclouds", x: 0, y: 0, z: 0, rot: 0, sink: 0, drift: 0 },
  { id: "street", kind: "gstreet", x: 0, y: 0, z: 0, rot: 0 },
  { id: "horizon", kind: "ghorizon", x: 0, y: 0, z: 0, rot: 0 },
  { id: "sofa", kind: "gsofa", x: 0.20, y: 0, z: -1.61, rot: 0, sink: 0, damage: 0 },
  { id: "entry", kind: "gentry", x: 0, y: 0, z: 0, rot: 0, t: -1, cam: CAM.P3 },
  { id: "strike", kind: "gstrike", x: 0, y: 0, z: 0, rot: 0, t: -1, from: CAM.P4.pos },
  { id: "glass", kind: "gglass", x: 0, y: 0, z: 0, rot: 0, t: -1 },
];
for (const id of ["entry", "strike", "glass"]) c.prop(0, id, { t: -1 }, 0, "linear");
c.prop(0, "sofa", { sink: 0, damage: 0 }, 0, "linear");
c.prop(0, "clouds", { sink: 0, drift: 0 }, 0, "linear");
SHOTS.forEach(([, t], i) => { for (const id of ["entry", "strike", "glass"]) c.prop(i + 0.01, id, { t }, 0, "linear"); });
const beats = c.beats(SHOTS.map(([cam, t], i) => [`${cam.toLowerCase()}_${i + 1}`, i, CAM[cam], `${cam} t ${t}`]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "strike-bench", title: "Gravity strike bench", idea: "Props bench for fact what-if 02 gravity v2 (gentry, gstrike, gglass), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: false }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/02-gravity/bench/make-strike-bench.mjs (props bench, no reviews).",
});

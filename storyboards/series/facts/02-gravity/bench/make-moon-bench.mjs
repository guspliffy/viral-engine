// Bench for the Moon's fall, the fire wall and the room hit (engine/page/props-gravmoon.js, task T7 of the gravity v2 builds):
// gmoonfall, gfirewall, groomhit, gflash, and the sofa's new brk, on the gravroom set (not bare: the shots look through the window),
// with gsky, ghorizon, gruin (the city the wave erases), the glass overlay, the lamp and the plant moved by the header's tween numbers,
// and a .8 x .25 x .5 m stone block standing in for Spud on the sofa. DESIGN-v2 section E cameras P7, P8, P9. Not a clip. 16 stills,
// 1 s apart, 0.6 s into each beat; each beat jumps the one param `t` (clip seconds) to the time shown:
//   P7 at 48.2 50 52 54 55.9     P8 at 56.1 56.4 57.5 58.6 59.2     P9 at 59.25 59.35 59.5 59.8 60.2 60.45
//   node storyboards/series/facts/02-gravity/bench/make-moon-bench.mjs
//   node engine/render.mjs storyboards/series/facts/02-gravity/bench/moon-bench.json --stills 0.6,1.6,2.6,3.6,4.6,5.6,6.6,7.6,8.6,9.6,10.6,11.6,12.6,13.6,14.6,15.6 --draft --safe
//   node qa/contact.mjs out/moon-bench-*.png --out <tmp>/moon-sheet.png   (then saved as bench/moon-sheet.jpg, JPEG q80)
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const TROOM = 59.287, END_HIT = 60.5;
const CAM = {
  P7: { pos: [0.34, 1.12, 0.94], look: [-0.09, 2.33, -8], fov: 65 },
  P8: { pos: [0.15, 1.91, -2.58], look: [-48, 130, -2500], fov: 53 },
  P9: { pos: [0.48, 1.39, 0.21], look: [0.37, 0.78, -2.30], fov: 71 },
};
const SHOTS = [["P7", 48.2], ["P7", 50], ["P7", 52], ["P7", 54], ["P7", 55.9], ["P8", 56.1], ["P8", 56.4], ["P8", 57.5], ["P8", 58.6], ["P8", 59.2], ["P9", 59.25], ["P9", 59.35], ["P9", 59.5], ["P9", 59.8], ["P9", 60.2], ["P9", 60.45]];
const END = SHOTS.length;
const props = [
  { id: "sky", kind: "gsky", x: 0, y: 0, z: 0, rot: 0, from: CAM.P7.pos },
  { id: "horizon", kind: "ghorizon", x: 0, y: 0, z: 0, rot: 0 },
  { id: "ruin", kind: "gruin", x: 0, y: 0, z: 0, rot: 0, t: -1 },
  { id: "moon", kind: "gmoonfall", x: 0, y: 0, z: 0, rot: 0, t: -1 },
  { id: "fire", kind: "gfirewall", x: 0, y: 0, z: 0, rot: 0, t: -1 },
  { id: "hit", kind: "groomhit", x: 0, y: 0, z: 0, rot: 0, t: -1 },
  { id: "flash", kind: "gflash", x: 0, y: 0, z: 0, rot: 0, t: -1, cam: CAM.P9 },
  { id: "glass", kind: "gglass", x: 0, y: 0, z: 0, rot: 0, t: -1 },
  { id: "sofa", kind: "gsofa", x: 0.20, y: 0, z: -1.61, rot: 0, sink: 0.12, damage: 0.3, brk: 0 },
  { id: "plant", kind: "gplant", x: -1.40, y: 0.09, z: -2.48, rot: 0 },
  { id: "lamp", kind: "glamp", x: 1.45, y: 0, z: -2.12, rot: 0, roll: 0 },
  { id: "spud", kind: "stoneblock", x: 0.46, y: 0.42, z: -1.5, rot: 0, w: 0.8, h: 0.25, d: 0.5 },
];
const TIMED = ["ruin", "moon", "fire", "hit", "flash", "glass"];
for (const id of TIMED) c.prop(0, id, { t: -1 }, 0, "linear");
c.prop(0, "sofa", { sink: 0.12, damage: 0.3, brk: 0 }, 0, "linear");
c.prop(0, "lamp", { x: 1.45, y: 0, z: -2.12, roll: 0 }, 0, "linear");
c.prop(0, "plant", { x: -1.40, y: 0.09, z: -2.48 }, 0, "linear");
const P = (a, b, t) => Math.min(1, Math.max(0, (t - a) / (b - a)));
const k3 = (a, b, k, u) => (u < 0.5 ? a + (b - a) * u * 2 : b + (k - b) * (u - 0.5) * 2);
SHOTS.forEach(([, t], i) => {
  const at = i + 0.01, h = P(TROOM, END_HIT, t);
  for (const id of TIMED) c.prop(at, id, { t }, 0, "linear");
  c.prop(at, "sofa", { brk: h }, 0, "linear");
  // the header's tween numbers: plant (+.22,+.20,+.64) -> (+.38,-.05,+1.45); lamp origin (+.94,+.91,+.70) -> (+1.26,+1.64,+1.60), roll 38 -> 82
  c.prop(at, "plant", { x: -1.40 + k3(0, 0.22, 0.38, h), y: 0.09 + k3(0, 0.20, -0.05, h), z: -2.48 + k3(0, 0.64, 1.45, h) }, 0, "linear");
  c.prop(at, "lamp", { x: 1.45 + k3(0, 0.94, 1.26, h), y: k3(0, 0.91, 1.64, h), z: -2.12 + k3(0, 0.70, 1.60, h), roll: k3(0, 38, 82, h) }, 0, "linear");
});
const beats = c.beats(SHOTS.map(([cam, t], i) => [`m${i + 1}`, i, CAM[cam], `${cam} t ${t}`]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "moon-bench", title: "Gravity Moon bench", idea: "Props bench for fact what-if 02 gravity v2 (gmoonfall, gfirewall, groomhit, gflash, gsofa brk), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: false }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/02-gravity/bench/make-moon-bench.mjs (props bench, no reviews).",
});

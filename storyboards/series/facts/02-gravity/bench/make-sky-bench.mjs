//   node qa/contact.mjs out/gravity-sky-bench-*.png --out storyboards/series/facts/02-gravity/bench/sky-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const END = 10.0;
const CAM = {
  A: { pos: [0.05, 1.52, 3.18], look: [0.03, 1.52, -2.65], fov: 51 },
  C8: { pos: [0.20, 1.42, 0.53], look: [0.12, 1.37, -2.65], fov: 67 },
  C10: { pos: [0.21, 1.23, 0.40], look: [0.16, 1.71, -2.65], fov: 68 },
  C13: { pos: [0.16, 1.24, 0.46], look: [0.05, 1.87, -2.65], fov: 69 },
  C14: { pos: [0.16, 1.24, 0.46], look: [0.10, 2.00, -2.65], fov: 72 },
};
// [camera, { moon, cracks, sink, t }, label]
const SHOTS = [
  ["A", {}, "A normal"],
  ["C8", { sink: 0.5 }, "C8 (panel 8) sink .5"],
  ["C8", { sink: 1 }, "C8 sink 1"],
  ["C10", { t: 0.9 }, "C10 (panel 10) sats t .9"],
  ["C10", { t: 1.6 }, "C10 sats t 1.6"],
  ["C10", { t: 2.5 }, "C10 sats t 2.5"],
  ["C13", { moon: 0.5 }, "C13 (panel 13) moon .5"],
  ["C14", { moon: 0.86 }, "C14 (panel 14) moon .86"],
  ["C14", { moon: 1, cracks: 0.5 }, "C14 moon 1 cracks .5"],
  ["C14", { moon: 1, cracks: 1 }, "C14 moon 1 cracks 1"],
];
const props = [
  { id: "sky", kind: "gsky", x: 0, y: 0, z: 0, rot: 0 },
  { id: "moon", kind: "gmoon", x: 0, y: 0, z: 0, rot: 0, moon: 0, cracks: 0 },
  { id: "sats", kind: "gsats", x: 0, y: 0, z: 0, rot: 0, t: -1 },
  { id: "clouds", kind: "gclouds", x: 0, y: 0, z: 0, rot: 0, sink: 0, drift: 0 },
];
c.prop(0, "moon", { moon: 0, cracks: 0 }, 0, "linear");
c.prop(0, "sats", { t: -1 }, 0, "linear");
c.prop(0, "clouds", { sink: 0, drift: 0 }, 0, "linear");
SHOTS.forEach(([, p], i) => {
  c.prop(i + 0.01, "moon", { moon: p.moon ?? 0, cracks: p.cracks ?? 0 }, 0, "linear");
  c.prop(i + 0.01, "sats", { t: p.t ?? -1 }, 0, "linear");
  c.prop(i + 0.01, "clouds", { sink: p.sink ?? 0, drift: 0 }, 0, "linear");
});
const beats = c.beats(SHOTS.map(([cam, , label], i) => [`s${i + 1}`, i, CAM[cam], label]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "gravity-sky-bench", title: "Gravity sky bench", idea: "Props bench for fact what-if 02 gravity (gsky, gmoon, gsats, gclouds), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: true }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/02-gravity/bench/make-sky-bench.mjs (props bench, no reviews).",
});

//   node qa/contact.mjs out/city-bench-*.png --out storyboards/series/facts/02-gravity/bench/city-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const END = 9.0;
const CAM = {
  A: { pos: [0.05, 1.52, 3.18], look: [0.03, 1.52, -2.65], fov: 51 },
  C: { pos: [0.28, 1.23, 0.33], look: [0.72, 1.62, -2.65], fov: 66 },
  D: { pos: [-30, -22, -8], look: [9.7, -38, -49.5], fov: 62 },
};
const SHOTS = [["A", 0], ["C", 0], ["C", 0.25], ["C", 0.5], ["C", 0.75], ["C", 1], ["A", 1], ["D", 0.5, 0.1], ["D", 1, 0.1]];

const props = [
  { id: "street", kind: "gstreet", x: 0, y: 0, z: 0, rot: 0 },
  { id: "tower", kind: "gtower", x: 0, y: 0, z: 0, rot: 0, fall: 0, dust: 1 },
  { id: "city", kind: "gcity", x: 0, y: 0, z: 0, rot: 0, seed: 26031 },
  { id: "horizon", kind: "ghorizon", x: 0, y: 0, z: 0, rot: 0 },
];
c.prop(0, "tower", { fall: 0, dust: 1 }, 0, "linear");
SHOTS.forEach(([, fall, dust = 1], i) => c.prop(i + 0.01, "tower", { fall, dust }, 0, "linear"));

const beats = c.beats(SHOTS.map(([cam, fall], i) => [`${cam.toLowerCase()}${i + 1}`, i, CAM[cam], `${cam}, fall ${fall}`]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "city-bench", title: "Gravity city bench", idea: "Props bench for fact what-if 02 (gstreet, gtower, gcity, ghorizon), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: true }, music: false, sound: { auto: false },
  hook: { show: ["tower"], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/02-gravity/bench/make-city-bench.mjs (props bench, no reviews).",
});

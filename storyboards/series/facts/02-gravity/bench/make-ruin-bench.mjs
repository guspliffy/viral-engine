// Bench for the collapsing city and the torn street (engine/page/props-gravruin.js, task T4 of fact what-if 02 gravity v2): gruin and
// grupture on the real gravroom set (the shots look through the window), "far": 6000, from the DESIGN E cameras. Not a clip. Nine
// stills, 1 s apart, each 0.6 s into its beat (the one time param t jumps 0.01 s after the beat starts):
//   P1 t 23.5 / 24.5 / 25.5 / 26.5 / 27.5   P2 t 28.2 / 30   P4 t 40   P8 t 59.2 (the v1 tower is hidden from 23 s, as in the clip)
//   node storyboards/series/facts/02-gravity/bench/make-ruin-bench.mjs
//   node engine/render.mjs storyboards/series/facts/02-gravity/bench/ruin-bench.json --stills 0.6,1.6,2.6,3.6,4.6,5.6,6.6,7.6,8.6 --draft --safe
//   node qa/contact.mjs out/ruin-bench-*.png --out <tmp>/ruin-sheet.png   (then saved as bench/ruin-sheet.jpg, JPEG q80)
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const END = 9.0;
const CAM = {
  P1: { pos: [0.34, 1.26, -0.02], look: [0.06, 0.95, -8], fov: 59 },
  P2: { pos: [0.20, 2.55, -2.57], look: [-5.5, -60, -38], fov: 47 },
  P4: { pos: [0.34, 1.30, -0.02], look: [-0.12, 0.95, -8], fov: 60 },
  P8: { pos: [0.15, 1.91, -2.58], look: [-48, 130, -2500], fov: 53 },
};
const SHOTS = [["P1", 23.5], ["P1", 24.5], ["P1", 25.5], ["P1", 26.5], ["P1", 27.5], ["P2", 28.2], ["P2", 30.0], ["P4", 40], ["P8", 59.2]];
const props = [
  { id: "sky", kind: "gsky", x: 0, y: 0, z: 0, rot: 0, from: CAM.P1.pos },
  { id: "horizon", kind: "ghorizon", x: 0, y: 0, z: 0, rot: 0 },
  { id: "tower", kind: "gtower", x: 0, y: 0, z: 0, rot: 0, fall: 0, dust: 1 },
  { id: "ruin", kind: "gruin", x: 0, y: 0, z: 0, rot: 0, seed: 26031 },
  { id: "rupt", kind: "grupture", x: 0, y: 0, z: 0, rot: 0 },
];
const towerFall = (t) => Math.min(1, Math.max(0, (t - 23.9) / 3));
for (const id of ["ruin", "rupt"]) c.prop(0, id, { t: -1 }, 0, "linear");
SHOTS.forEach(([, t], i) => {
  for (const id of ["ruin", "rupt"]) c.prop(i + 0.01, id, { t }, 0, "linear");
  c.prop(i + 0.01, "tower", { fall: towerFall(t), dust: 0.1, scale: t >= 23 ? 0 : 1 }, 0, "linear");
});
const beats = c.beats(SHOTS.map(([cam, t], i) => [`r${i + 1}`, i, CAM[cam], `${cam}, t ${t}`]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "ruin-bench", title: "Gravity ruin bench", idea: "Props bench for fact what-if 02 gravity v2 (gruin, grupture), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: false }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/02-gravity/bench/make-ruin-bench.mjs (props bench, no reviews).",
});

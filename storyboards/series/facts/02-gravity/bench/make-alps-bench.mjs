// Bench for the Alps crushing (engine/page/props-gravalps.js, task T6 of fact what-if 02 gravity v2): galps from the design's cameras
// P5 (t 43.0 43.8 44.6 45.4) and P6 (t 45.6 46.3 47.0 47.9). Not a clip. Eight stills, 1 s apart, each 0.6 s into its beat (t jumps 0.01 s after the beat starts).
//   node storyboards/series/facts/02-gravity/bench/make-alps-bench.mjs
//   node engine/render.mjs storyboards/series/facts/02-gravity/bench/alps-bench.json --stills 0.6,1.6,2.6,3.6,4.6,5.6,6.6,7.6 --draft --safe
//   node qa/contact.mjs out/alps-bench-*.png --out storyboards/series/facts/02-gravity/bench/alps-sheet.png   (then save as alps-sheet.jpg)
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const END = 8.0, O = [40000, 0, 0], S = 0.6;
const w = (p) => [O[0] + S * p[0], O[1] + S * p[1], O[2] + S * p[2]].map(r3);
const CAM = {
  P5: { pos: w([0, 2180, 1550]), look: w([0, 2230, -3010]), fov: 84 },
  P6: { pos: w([280, 2610, -580]), look: w([610, 3070, -2760]), fov: 57 },
};
const SHOTS = [["P5", 43.0], ["P5", 43.8], ["P5", 44.6], ["P5", 45.4], ["P6", 45.6], ["P6", 46.3], ["P6", 47.0], ["P6", 47.9]];
const props = [{ id: "alps", kind: "galps", x: 0, y: 0, z: 0, rot: 0, t: -1 }];
c.prop(0, "alps", { t: 43 }, 0, "linear");
SHOTS.forEach(([, tt], i) => c.prop(i + 0.01, "alps", { t: tt }, 0, "linear"));
const beats = c.beats(SHOTS.map(([cam, tt], i) => [`a${i + 1}`, i, CAM[cam], `${cam} t ${tt}`]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","), "cams:", JSON.stringify(CAM));

write(import.meta.url, {
  id: "alps-bench", title: "Gravity Alps bench", idea: "Props bench for fact what-if 02 gravity v2 (galps), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: true }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/02-gravity/bench/make-alps-bench.mjs (props bench, no reviews).",
});

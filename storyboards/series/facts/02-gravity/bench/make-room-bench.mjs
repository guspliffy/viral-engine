// Bench for the living room (engine/page/set-gravroom.js + engine/page/props-gravroom.js, task T1 of fact what-if 02 gravity):
// the set gravroom, gsofa, gtv, glamp, gplant, grug, gtunnel, ghaze, from the design's cameras A, D and B. Not a clip.
// Ten stills, 1 s apart, each taken 0.6 s into its beat:
//   1 A base   2 D base   3 B base   4 A sink .16 damage 1   5 B sink .16 damage 1   6-7 D crumble .5 / 1
//   8-9 B gtunnel r 238 / r 0   10 A haze 1
//   node storyboards/series/facts/02-gravity/bench/make-room-bench.mjs
//   node engine/render.mjs storyboards/series/facts/02-gravity/bench/gravity-room-bench.json --stills 0.6,1.6,2.6,3.6,4.6,5.6,6.6,7.6,8.6,9.6 --draft --safe
//   node qa/contact.mjs out/gravity-room-bench-*.png --out storyboards/series/facts/02-gravity/bench/room-sheet.png
import { clip, write, r3 } from "../../../../lib/clip.mjs";

const c = clip();
const END = 10.0;
const CAM = {
  A: { pos: [0.05, 1.52, 3.18], look: [0.03, 1.52, -2.65], fov: 51 },
  D: { pos: [-0.84, 1.33, 0.39], look: [-1.52, 1.06, -0.96], fov: 59 },
  B: { pos: [0.30, 1.10, 0.40], look: [0.44, 1.37, -1.60], fov: 50 },
};
// [camera, { sink, damage, crumble, r, haze }, label]
const SHOTS = [
  ["A", {}, "A base (sink 0, damage 0, crumble 0)"],
  ["D", {}, "D base"],
  ["B", {}, "B base"],
  ["A", { sink: 0.16, damage: 1 }, "A sink .16 damage 1"],
  ["B", { sink: 0.16, damage: 1 }, "B sink .16 damage 1"],
  ["D", { crumble: 0.5 }, "D crumble .5"],
  ["D", { crumble: 1 }, "D crumble 1"],
  ["B", { r: 238 }, "B tunnel r 238"],
  ["B", { r: 0 }, "B tunnel r 0"],
  ["A", { haze: 1 }, "A haze 1"],
];
const props = [
  { id: "rug", kind: "grug", x: 0.18, y: 0, z: 0.11, rot: 0 },
  { id: "sofa", kind: "gsofa", x: 0.20, y: 0, z: -1.61, rot: 0, sink: 0, damage: 0 },
  { id: "tv", kind: "gtv", x: -1.52, y: 0, z: -0.99, rot: 34, crumble: 0 },
  { id: "lamp", kind: "glamp", x: 1.45, y: 0, z: -2.12, rot: 0 },
  { id: "plant", kind: "gplant", x: 1.80, y: 0, z: -1.60, rot: 0 },
  { id: "tunnel", kind: "gtunnel", x: 0, y: 0, z: 0, rot: 0, cam: { ...CAM.B, aspect: 9 / 16 }, r: 2000 },
  { id: "haze", kind: "ghaze", x: 0, y: 0, z: 0, rot: 0, haze: 0 },
];
// seed every tweened key at time 0, then one jump per beat
c.prop(0, "sofa", { sink: 0, damage: 0 }, 0, "linear");
c.prop(0, "tv", { crumble: 0 }, 0, "linear");
c.prop(0, "tunnel", { r: 2000, feather: 84, cx: 545, cy: 1450 }, 0, "linear");
c.prop(0, "haze", { haze: 0 }, 0, "linear");
SHOTS.forEach(([, p], i) => {
  c.prop(i + 0.01, "sofa", { sink: p.sink ?? 0, damage: p.damage ?? 0 }, 0, "linear");
  c.prop(i + 0.01, "tv", { crumble: p.crumble ?? 0 }, 0, "linear");
  c.prop(i + 0.01, "tunnel", { r: p.r ?? 2000 }, 0, "linear");
  c.prop(i + 0.01, "haze", { haze: p.haze ?? 0 }, 0, "linear");
});
const beats = c.beats(SHOTS.map(([cam, , label], i) => [`r${i + 1}`, i, CAM[cam], label]), END);
console.log("stills:", SHOTS.map((_, i) => r3(i + 0.6)).join(","));

write(import.meta.url, {
  id: "gravity-room-bench", title: "Gravity room bench", idea: "Props bench for fact what-if 02 gravity (gravroom set, gsofa, gtv, glamp, gplant, grug, gtunnel, ghaze), not a clip",
  fps: 30, look: "anime-pro", profile: "short", loop: false, castLook: "sheet", physics: false, far: 6000,
  set: { type: "gravroom", bare: false }, music: false, sound: { auto: false },
  hook: { show: [], hint: 0, what: "engine test" },
  cast: [], props, captions: c.captions, beats,
  notes: "Generated by storyboards/series/facts/02-gravity/bench/make-room-bench.mjs (props bench, no reviews).",
});

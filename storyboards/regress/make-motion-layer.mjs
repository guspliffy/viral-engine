#!/usr/bin/env node
// Regression fixtures for the motion layer (thread H, quality plan items 8, 9, 12; engine/page/solve.js):
//   regress-layer-sink         a fist pressed into its own belly, no layer: limb-through-costume must fail
//   regress-layer-sink-solved  the same with "motion": { "solve": true }: the solver pushes it out, clean
//   regress-layer-hold-end     regress-pickup's mug grabbed and never released with every layer flag on (a hold to the end made the
//                              overlap stepper's weights NaN and crashed the page, 5 Nov): lays out, clean
// Built on regress-turn.json (make-regress.mjs) so set, camera and cast match the other fixtures.
//   node storyboards/regress/make-motion-layer.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DIR = path.dirname(fileURLToPath(import.meta.url));
const base = JSON.parse(fs.readFileSync(path.join(DIR, "regress-turn.json"), "utf8"));
const NOTE = "Generated by storyboards/regress/make-motion-layer.mjs (regression fixture, no reviews).";
const LAYER = { feet: 2, overlap: true, timing: true, solve: true };

function fixture(id, title, motion, beat, expect, extra = {}) {
  const sb = structuredClone(base);
  Object.assign(sb, { id, title, motion, expect, notes: NOTE, ...extra });
  sb.captions = [{ ...sb.captions[0], text: title.replace(/^Regression: /, "") }];
  sb.beats = [{ ...sb.beats[0], name: beat.name, do: [{ who: "rea", do: "noblink", at: 0 }, ...beat.do] }];
  fs.writeFileSync(path.join(DIR, `${id}.json`), JSON.stringify(sb, null, 1) + "\n");
  console.log("wrote", id);
}

// the right fist pressed a few centimetres into the side of the belly (under the solver's 6 cm cap)
const sink = { name: "sink", do: [
  { who: "rea", do: "arm", side: "R", pose: { o: [-0.05, 0.42, 0.06] }, dur: 0.4, ease: "inOut", at: 0.3 },
  { who: "rea", do: "grip", side: "R", shape: "fist", dur: 0.2, at: 0.3 },
  { who: "rea", do: "arm", side: "R", pose: "rest", dur: 0.4, ease: "inOut", at: 1.6 },
] };
fixture("regress-layer-sink", "Regression: fist into its own belly", { feet: 2 }, sink, { fail: ["limb-through-costume"] });
fixture("regress-layer-sink-solved", "Regression: fist into its belly, solved", { feet: 2, solve: true }, sink, { clean: ["limb-through-costume", "rig-jump"] });

// regress-pickup's mug, grabbed at 0.86 s and lifted to chest height (not to the face), never put down, with every layer on
const pick = JSON.parse(fs.readFileSync(path.join(DIR, "regress-pickup.json"), "utf8"));
{
  const sb = structuredClone(pick);
  sb.beats = sb.beats.map((b) => ({ ...b, do: b.do.filter((a) => b.at + (a.at ?? 0) < 1.45 && a.do !== "release") }));
  Object.assign(sb, { id: "regress-layer-hold-end", title: "Regression: hold to the end", motion: LAYER, notes: NOTE,
    expect: { clean: ["rig-jump", "prop-pop", "limb-through-costume"] } });
  fs.writeFileSync(path.join(DIR, `${sb.id}.json`), JSON.stringify(sb, null, 1) + "\n");
  console.log("wrote", sb.id);
}

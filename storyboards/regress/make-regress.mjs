// Contact and motion regression fixtures: short engine tests (no reviews, not clips) that the checks must judge the
// same way after every engine, rig or check change. Each has an "expect" block that qa/regress.mjs tests against the
// layout's contact and rig results (render.mjs --layout):
//   fail:  checks that must fail (a glitch staged on purpose, so a check that stops catching it shows up)
//   warn:  checks that must at least warn
//   clean: checks that must have no warning or failure (the good version of a move)
// and no other gate check may fail. The bad fixtures copy real glitches: the Zombie Too hug (4 Nov, bodies 86 % into
// each other inside an allowClip window) and a one-frame arm pop.
//   node storyboards/regress/make-regress.mjs && node qa/regress.mjs
import { clip, write, frame, r3 } from "../lib/clip.mjs";
import * as grips from "../lib/grips.mjs";

const base = (id, title, cast, props, c, shot, end, expect, more = {}) => {
  c.cap(0, end, title, 1500, false, { kinetic: false });
  write(import.meta.url, {
    id: `regress-${id}`, title: `Regression: ${title}`, idea: "Contact/motion regression fixture (qa/regress.mjs), not a clip",
    fps: 30, look: "anime-pro", castLook: "golden", profile: "short", loop: false, motion: "natural",
    set: { type: "livingroom", seed: 5, focus: false }, music: false, sound: { auto: false },
    hook: { show: cast.map((x) => x.id), hint: 0, what: "engine test" },
    cast, props, captions: c.captions, beats: c.beats([[id, 0, shot]], end), expect, ...more,
    notes: "Generated by storyboards/regress/make-regress.mjs (regression fixture, no reviews).",
  });
};
const CLEAN = ["rig-jump", "foot-slide", "prop-pop"];

// WALK + STOP: a natural walk across and a stop with weight; the feet stay planted between steps
{
  const c = clip(), { A } = c;
  A(0, "phx", "noblink");
  A(0.1, "phx", "look", { to: [0.8, 0], dur: 0.15, blink: false });
  A(0.2, "phx", "turn", { to: "right", dur: 0.35 });
  A(0.6, "phx", "move", { to: [0.6, 0.1], dur: 1.5, steps: 2 });
  A(2.2, "phx", "turn", { to: "camera", dur: 0.35 });
  base("walk-stop", "walk and stop", [{ id: "phx", character: "duo/phoenix", at: [-0.6, 0.1], face: "camera", expr: "kind", follow: 0.3, seed: 1.7, span: 0 }], [], c,
    { pos: [0, 0.75, 6.6], look: [0, 0.5, 0], fov: 40 }, 3.0, { clean: CLEAN });
}

// TURN: a full turn on the spot and back (the body turns, the feet step round, the hands follow the body)
{
  const c = clip(), { A } = c;
  A(0, "rea", "noblink");
  A(0.2, "rea", "turn", { to: 180, dur: 0.6 });
  A(1.3, "rea", "turn", { to: "camera", dur: 0.6 });
  base("turn", "turn round", [{ id: "rea", character: "notyet/reaper-noscythe", at: [0, 0], face: "camera", expr: "kind", follow: 0.2, seed: 3.3 }], [], c,
    { pos: [0, 0.8, 5], look: [0, 0.5, 0], fov: 40 }, 2.4, { clean: CLEAN });
}

// BLINK: a line said with the eyes steady (noblink, blink: false on the look), a placed blink after it
{
  const c = clip(), { A } = c;
  A(0, "wiz", "noblink");
  A(0.2, "wiz", "look", { to: [0.6, 0.1], dur: 0.2, blink: false });
  c.say(0.5, "wiz", "Hm.", 0.6);
  c.cap(0.5, 1.2, "HM.", 400, false, { kinetic: false });
  A(1.5, "wiz", "blink");
  A(1.8, "wiz", "look", { to: [0, 0], dur: 0.2, blink: false });
  base("blink", "line and blink", [{ id: "wiz", character: "lookdev/wizard-crisp", at: [0, 0], face: "camera", expr: "kind", follow: 0.2, seed: 2.6 }], [], c,
    frame([0, 0.6, 0], { h: 1.4, fov: 30 }), 2.4, { clean: CLEAN });
}

// PICK UP + PUT DOWN (one hand, the mug hold) and TWO-HAND CARRY (the box hold), at a table: the grip library benches,
// cut to the moves the checks must keep judging clean
const TABLE_H = 0.36, WIZ = [0, -0.25];
for (const [id, title, kind, spot, held, hold] of [
  ["pickup", "pick up and put down", { kind: "campmug", scale: 1.9 }, [-0.13, TABLE_H, 0.42], [-0.1, 0.46, 0.38], "mug"],
  ["carry", "two-hand carry", { kind: "parcel", scale: 0.8 }, [0, TABLE_H, 0.46], [0, 0.42, 0.44], "box"],
]) {
  const c = clip(), { A } = c;
  const spec = { id: "it", ...kind, ...grips.placeFor(kind.kind, spot, 0) };
  const h = grips[hold](c, "wiz", spec, { side: "R" });
  A(0, "wiz", "noblink");
  A(0, "wiz", "look", { to: [0.1, -0.8], dur: 0.01, blink: false });
  let t = h.take(0.3);
  t = h.carry(t + 0.05, held, 0.45);
  t = h.carry(t + 0.1, [held[0] + 0.05, held[1] + 0.03, held[2]], 0.5);
  t = h.put(t + 0.15, spot);
  const end = Math.max(3, Math.ceil((t + 0.2) * 10) / 10);
  base(id, title, [{ id: "wiz", character: "lookdev/wizard-crisp", at: WIZ, face: 0, expr: "kind", follow: 0.2, seed: 2.6 }],
    [{ id: "table", kind: "coffeetable", x: 0, z: 0.5, h: TABLE_H, w: 1.3, d: 0.5 }, spec], c,
    { pos: [-0.75, 1.05, 2.3], look: [-0.05, 0.55, 0.3], fov: 30 }, end, { clean: CLEAN });
}

// HUG: good (facing each other a body-width apart, each of Reaper's arms round Phoenix's side on its own side),
// merging (the first Zombie Too hug: the bodies walk into each other) and crossing (the fixed Zombie Too hug, Jonny
// 4 Nov: Reaper's right arm comes out of his chest and runs through Phoenix's belly to his far side). All inside an
// allowClip window with a reason: a window allows contact, not these
const ZOMBIE_ARMS = (c, R, P, H) => {
  c.arm(r3(H + 0.15), "rea", "R", { world: [r3(P[0] + 0.42), 0.46, r3(P[1] + 0.22)] }, 0.35, "inOut");
  c.arm(r3(H + 0.15), "rea", "L", { world: [r3(P[0] + 0.2), 0.62, r3(P[1] - 0.42)] }, 0.35, "inOut");
};
for (const [id, title, R, P, yaw, arms, expect] of [
  ["hug", "hug", [-0.45, 0], [0.45, 0], 90, (c, R, P, H) => {
    // facing +x, Reaper's right is toward the camera (+z): each glove on Phoenix's side on its own side
    c.arm(r3(H + 0.15), "rea", "R", { world: [r3(P[0] - 0.22), 0.45, 0.46] }, 0.35, "inOut");
    c.arm(r3(H + 0.15), "rea", "L", { world: [r3(P[0] - 0.22), 0.45, -0.46] }, 0.35, "inOut");
  }, { clean: ["character-overlap", "limb-through-costume", "rig-jump"] }],
  ["hug-merge", "hug that merges (must fail)", [-0.12, -0.04], [0.44, 0.12], 26, ZOMBIE_ARMS, { fail: ["character-overlap", "limb-through-costume"] }],
  ["hug-cross", "arm out of the chest (must fail)", [-0.36, -0.04], [0.55, 0.12], 26, ZOMBIE_ARMS, { fail: ["limb-through-costume", "character-overlap"] }],
]) {
  const c = clip(), { A } = c, HUG = 0.3;
  A(0, "rea", "noblink"); A(0, "phx", "noblink");
  A(HUG, "rea", "move", { to: R, dur: 0.45, steps: 2 });
  A(HUG, "phx", "move", { to: P, dur: 0.45, steps: 2 });
  A(HUG, "rea", "turn", { to: yaw, dur: 0.25 });
  A(HUG, "phx", "turn", { to: -yaw, dur: 0.25 });
  arms(c, R, P, HUG);
  A(r3(HUG + 0.4), "rea", "grip", { side: "both", shape: "relaxed", dur: 0.15 });
  base(id, title, [
    { id: "rea", character: "notyet/reaper-noscythe", at: [-0.9, 0], face: 60, expr: "sad", follow: 0.2, seed: 3.3 },
    { id: "phx", character: "duo/phoenix", at: [0.95, 0.1], face: -60, expr: "kind", follow: 0.25, seed: 1.7, span: 0 },
  ], [], c, frame([0.05, 0.68, 0.05], { az: -14, el: 2, h: 1.9, fov: 40 }), 2.0, expect, {
    allowClip: [
      { who: "rea", with: "phx", from: HUG + 0.1, to: 2.0, reason: "the hug: gloves round the sides, cheeks close" },
      { who: "phx", with: "rea", from: HUG + 0.1, to: 2.0, reason: "the hug" },
    ],
  });
}


// Core Five redesign tests (thread "Make videos with the Core Five characters", 5 Nov 2026): one short engine test per
// redesigned character (characters/core-five-2026/*.json, def.build "core"), so Jonny judges the build from a video,
// not stills: a tentative wave and a glance at the glove (the sheet's "NEW HERE" / "DID THAT RIGHT?"), a full turn, a
// few planted steps, a confident point ("MY SPECIALTY") and a push in to the face. Pure engine test: no reviews, no story.
//   node storyboards/core-five/make-core-tests.mjs   -> storyboards/core-five/test-<name>.json
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const CORE = { astronaut: "core-five-2026/astronaut" };

// the beats below are written on the clip's clock; a beat's items are timed from the beat's start
const rel = (beats) => beats.map((b) => ({ ...b, do: b.do.map((x) => ({ ...x, at: Math.round((x.at - b.at) * 1000) / 1000 })) }));

export function coreTest(name, character) {
  const W = "c", full = { pos: [0, 0.78, 4.7], look: [0, 0.7, 0], fov: 30 };
  const close = { pos: [0.3, 1.0, 2.85], look: [0.3, 0.9, 0.25], fov: 30 };
  const a = (at, o) => ({ who: W, at, ...o });
  const turns = [90, 180, 270, 360].map((to, i) => a(3.5 + i * 0.9, { do: "turn", to, dur: 0.75 }));
  return {
    id: `core-${name}-test`, title: `${name[0].toUpperCase() + name.slice(1)} (Core Five) engine test`,
    idea: "Engine test of the Core Five humanoid build, not a clip", fps: 30, look: "anime-pro", profile: "short", loop: false,
    castLook: "sheet-clean", motion: { feet: 2 }, rig: { hand: 2, eyes: 2 },
    set: { type: "plain", color: "#f1dcb0", floor: "#d6b27c", light: "golden", para: 0, aperture: 0, shade: "soft" },
    // the handoff's look: the clip template's (no "drawn" block: no paper grain, drawn on ones), with castLook "sheet-clean"
    // (clean two-tone cel, no hatching over the faces)
    music: false, sound: { guard: true, surface: "wood" },   // footsteps and the room only: an engine test, no music creative: { length: [4, 20], notes: false },
    hook: { show: [W], hint: 0, what: "engine test" },
    // a still wide shot while the body does the work, one push in to the face for the last beat, then a still close-up
    camera: [{ at: 0, ...full }, { at: 9.75, ...full }, { at: 10.45, ...close }, { at: 11.6, ...close }],
    cast: [{ id: W, character, at: [0, 0], face: 0, expr: "eager", follow: 0, seed: 1.3 }],
    beats: rel([
      { name: "new here", at: 0, len: 3.4, do: [
        a(0, { do: "look", to: [0, 0], dur: 0.1, blink: false }),
        // a tentative start: the hand comes up half way, a pause, then the wave
        a(0, { do: "arm", side: "R", pose: { o: [0.1, 0.92, 0.2] }, dur: 0.4 }),
        a(0, { do: "expr", expr: "eager", set: { tilt: 0.36, curve: 0.45 }, dur: 0.3 }),
        // the wave: the hand up beside the dome (never inside it) and three small side to side waggles
        a(0.7, { do: "arm", side: "R", pose: { o: [0.2, 1.3, 0.14] }, dur: 0.25 }),
        ...[0.95, 1.15, 1.35, 1.55].map((t, i) => a(t, { do: "arm", side: "R", pose: { o: [i % 2 ? 0.2 : 0.3, i % 2 ? 1.3 : 1.24, 0.14] }, dur: 0.2 })),
        a(0.8, { do: "expr", expr: "happy", dur: 0.3 }),
        // did that right? the hand comes down in front of the chest and the eyes check the glove, a shy proud smile
        a(1.75, { do: "arm", side: "R", pose: { o: [-0.02, 0.62, 0.3] }, dur: 0.45 }),
        a(1.7, { do: "look", to: [-0.35, -0.45], dur: 0.2 }),
        a(2.05, { do: "expr", expr: "kind", set: { tilt: 0.34, curve: 0.75, eye: 0.9 }, dur: 0.35 }),
        a(2.75, { do: "look", to: [0, 0], dur: 0.2 }),
        a(2.85, { do: "arm", side: "R", pose: "rest", dur: 0.45 }),
        a(2.9, { do: "expr", expr: "happy", dur: 0.3 }),
      ] },
      { name: "turn", at: 3.4, len: 3.8, do: turns },
      { name: "walk", at: 7.2, len: 2.0, do: [
        a(7.2, { do: "look", to: [0.8, 0], dur: 0.15, blink: false }),
        a(7.25, { do: "turn", to: "right", dur: 0.5 }),
        a(7.75, { do: "move", to: [0.32, 0.25], dur: 1.0, steps: 2 }),
        a(8.8, { do: "turn", to: "camera", dur: 0.5 }),
        a(8.9, { do: "look", to: [0, 0], dur: 0.15 }),
      ] },
      { name: "my specialty", at: 9.2, len: 2.4, do: [
        a(9.3, { do: "expr", expr: "focused", set: { tilt: -0.12, curve: 0.55, eye: 1.0 }, dur: 0.3 }),
        a(9.35, { do: "arm", side: "R", pose: "point", dur: 0.35 }),
        a(9.4, { do: "look", to: [-0.6, 0.05], dur: 0.15 }),
        a(10.4, { do: "look", to: [0, 0], dur: 0.15 }),
        a(10.45, { do: "arm", side: "R", pose: "rest", dur: 0.4 }),
        a(10.5, { do: "expr", expr: "delighted", dur: 0.3 }),
      ] },
    ]),
    notes: "Generated by storyboards/core-five/make-core-tests.mjs (engine test, no reviews).",
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [name, character] of Object.entries(CORE)) {
    const f = path.join(here, `test-${name}.json`);
    fs.writeFileSync(f, JSON.stringify(coreTest(name, character), null, 1) + "\n");
    console.log(f);
  }
}

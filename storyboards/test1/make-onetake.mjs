// Test 1 (two-week test plan, 30 Oct 2026): the one-take arm. Each clip's setup cuts in the first ~3 s become one
// continuous, wider shot of the same action; actions, captions, music and sound are untouched, and every shot from
// the first cut after 3 s on is the merged clip's. The finished MP4 keeps the merged master's frames and sound after
// that cut (storyboards/test1/splice.sh), so only the opening differs.
//   node storyboards/test1/make-onetake.mjs -> storyboards/test1/*-onetake.json
import { readFileSync, writeFileSync } from "node:fs";

const CLIPS = [
  {
    src: "../prank/never-prank-the-quiet-friend.json", id: "never-prank-the-quiet-friend-onetake",
    title: "Never Prank the Quiet Friend (one-take opening)",
    replace: ["01 the prank", "02 the foam", "03 the target", "04 the tickle"],
    // both faces, the feather and the foam on his palm in one frame from 0.0; a slow push until the cut at 3.1
    shot: { pos: [-0.45, 1.58, 6.5], look: [-0.04, 0.8, 0.42], fov: 30, to: { pos: [-0.4, 1.44, 5.7], look: [-0.03, 0.81, 0.45] }, dur: 3.1, ease: "inOut" },
  },
  {
    src: "../juice/vampire-vs-juice-box.json", id: "vampire-vs-juice-box-onetake",
    title: "Vampire vs Juice Box (one-take opening)",
    replace: ["01 wrong tool", "02 pressure", "03 immediate splash", "04 the silent solution"],
    // the bite, both jets and the Wizard's face in one two-shot from 0.0; a slow push until the cut at 3.0
    shot: { pos: [-0.22, 1.02, 6.0], look: [0.02, 0.62, 0.33], fov: 22, to: { pos: [-0.24, 1.0, 5.5], look: [0.02, 0.6, 0.33] }, dur: 3.0, ease: "inOut" },
    // ends before the SPLORT! pop at 1.24 s, which sits where the caption is
    caption: { from: 0, to: 1.2, text: "New vampire. Still learning.", pos: 230, pop: false, kinetic: false },
  },
];

const only = process.argv[2];
for (const c of CLIPS) {
  if (only && !c.id.startsWith(only)) continue;
  const sb = JSON.parse(readFileSync(new URL(c.src, import.meta.url)));
  const beats = c.replace.map(n => sb.beats.find(b => b.name === n));
  if (beats.some(b => !b)) throw new Error(`${c.id}: the merged clip's opening changed`);
  beats[0].shot = c.shot;
  for (const b of beats.slice(1)) b.shot = "keep";
  sb.id = c.id; sb.title = c.title;
  if (c.caption && !sb.captions?.length) sb.captions = [c.caption];
  sb.notes = `Generated by storyboards/test1/make-onetake.mjs from storyboards/${c.src.slice(3)} (Test 1, one-take arm).`;
  writeFileSync(new URL(`./${c.id}.json`, import.meta.url), JSON.stringify(sb, null, 1) + "\n");
  const end = beats.at(-1).at + beats.at(-1).len;
  console.log(`${c.id}: one take 0-${end.toFixed(2)} s`);
}

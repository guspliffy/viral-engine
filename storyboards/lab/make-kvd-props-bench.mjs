// ENGINE BENCH (22 Nov 2026, Kid vs Dad 01, task T5): the props `jokejar`, `snaredrum` and `drumsticks` (engine/page/props-kvd.js).
// Pure engine test, no creative review. Wide frame so four jars sit in a row.
//   node storyboards/lab/make-kvd-props-bench.mjs            -> storyboards/lab/kvd-props-bench.json
//   node storyboards/lab/make-kvd-props-bench.mjs --grip     -> kvd-grip-jar.json, kvd-grip-sticks.json (+ "-side"): the in-hand proofs
// Beat "jars" (0-1 s): the jar at fill 0, 0.5, 0.82 and 0.82 with plink 1 (a still at 0.5).
// Beat "kit" (1-2.2 s): the snare + stand + cymbal seen from the yard side over the closed fence (z -2.6), the kit 0.55 behind
// it (z -3.15), Spud on a crate (size 0.44) with the drumsticks in his LEFT fist (mug hold). strike / hit 0 at t 1.6; strike
// 0.35 (and hit 0.35) at t 1.97; beat "kitside" (2.2-3.0): the same from the holder's left, rest at 2.35, strike 0.35 at 2.57.
//   node engine/render.mjs storyboards/lab/kvd-props-bench.json --stills 0.5,1.6,1.97,2.35,2.57 --draft --safe
import { clip, write, r3 } from "../lib/clip.mjs";
import * as grips from "../lib/grips.mjs";

const GRIP = process.argv.includes("--grip");
const BASE = { fps: 30, look: "anime-pro", profile: "short", frame: "wide", loop: false, music: false, sound: { auto: false, signature: false, sfx: 0.6, ambience: 0.06 }, castLook: "sheet", cleanStart: true };
const X0 = 20;   // the kit scene stands 20 m to the side of the jars, so the first beat shows no fence
const KIT = { x: X0 + 0.3, z: -3.15 }, FENCE = { x: X0 + 0.3, z: -2.6 };

function bench() {
  const c = clip({ faces: "strong" }), { A } = c, END = 3.0;
  // the jars: fill 0, 0.5, 0.82, 0.82 + plink 1, on the grass at z 0
  const props = [0, 0.5, 0.82, 0.82].map((fill, i) => ({ id: `jar${i}`, kind: "jokejar", x: r3(-0.54 + i * 0.36), y: 0, z: 0, fill, ...(i === 3 && { plink: 1 }) }));
  // the kit
  props.push({ id: "fence", kind: "fence", x: FENCE.x, z: FENCE.z, width: 1.6 });
  props.push({ id: "kit", kind: "snaredrum", x: KIT.x, y: 0, z: KIT.z });
  props.push({ id: "cym", kind: "cymbal", x: r3(KIT.x + 0.26), y: 1.2, z: r3(KIT.z - 0.18), tip: 105, rot: 0 });
  props.push({ id: "crate", kind: "crate", size: 0.44, x: r3(KIT.x - 0.05), y: 0, z: r3(KIT.z - 0.62) });
  const fist = [r3(KIT.x + 0.2), 1.01, r3(KIT.z + 0.02)];
  const sticks = { id: "sticks", kind: "drumsticks", ...grips.placeFor("drumsticks", fist, 0) };
  props.push(sticks);
  const cast = [{ id: "spud", character: "potatobrawl/spud", at: [r3(KIT.x - 0.05), r3(KIT.z - 0.62)], y: 0.45, face: 0, expr: "kind", follow: 0.2, seed: 1.7 }];
  const h = grips.mug(c, "spud", sticks, { side: "L" });
  h.take(1.1);
  c.prop(0, "kit", { hit: 0 }, 0); c.prop(0, "sticks", { strike: 0 }, 0);
  // strike 0.35 (and hit 0.35) at 1.97 (yard side) and again at 2.57 (side view)
  for (const t0 of [1.9, 2.5]) { c.prop(r3(t0 - 0.0175), "kit", { hit: 1 }, 0.25, "linear"); c.prop(t0, "sticks", { strike: 1 }, 0.2, "linear"); c.prop(r3(t0 + 0.3), "kit", { hit: 0 }, 0); c.prop(r3(t0 + 0.3), "sticks", { strike: 0 }, 0); }
  c.prop(0, "cym", { ring: 0 }, 0);
  return { ...BASE, id: "kvd-props-bench", title: "Kid vs Dad 01 props bench", idea: "jokejar, snaredrum, drumsticks (engine bench)", seed: "kvd-props-bench",
    set: { type: "plain", color: "#bfd0d8", floor: "#8fae72" }, hook: { show: ["spud"], hint: 0, what: "props bench" },
    cast, props, captions: c.captions, visible: c.visible,
    beats: c.beats([["jars", 0, { pos: [0, 0.34, 2.3], look: [0, 0.12, 0], fov: 24 }], ["kit", 1.0, { pos: [X0 + 0.3, 1.2, 1.4], look: [X0 + 0.3, 0.98, -3.3], fov: 26 }], ["kitside", 2.2, { pos: [X0 + 2.6, 1.15, -2.7], look: [X0 + 0.3, 0.98, -3.2], fov: 24 }]], END),
    notes: "Generated by storyboards/lab/make-kvd-props-bench.mjs (engine bench, no creative review)." };
}
write(import.meta.url, bench());

// --grip: the in-hand proofs, as storyboards/lookdev/make-grip-tests.mjs --prop <kind> but with the cast and the hand a brief names
// (that tool is hard-wired to the right hand): Chip lifts the jar in both hands (box hold, gap 0.03); Spud closes his LEFT fist on the sticks (mug hold).
if (GRIP) {
  const TABLE_H = 0.36;
  const TESTS = [
    ["jar", "jokejar", "box", "chip", "potatobrawl/chip", "L", { gap: 0.03 }, [0, TABLE_H, 0.5], [0, 0.46, 0.42]],
    ["sticks", "drumsticks", "mug", "spud", "potatobrawl/spud", "L", { side: "L" }, [0.15, TABLE_H + 0.1, 0.55], [0.15, 0.7, 0.5]],
  ];
  const SIDE_CAM = { pos: [2.5, 0.75, 0.9], look: [0, 0.5, 0.36], fov: 26 };
  for (const [name, kind, hold, who, character, , opts, spot, held] of TESTS) for (const view of ["", "-side"]) {
    const c = clip(), { A } = c, spec = { id: "it", kind, ...grips.placeFor(kind, spot, 0) };
    const h = grips[hold](c, who, spec, opts);
    A(0, who, "noblink");
    let t = h.take(0.3);
    t = h.carry(t + 0.05, held, 0.45);
    const holdAt = r3(t + 0.1);
    t = h.carry(t + 0.1, [held[0] + 0.05, held[1] + 0.03, held[2]], 0.5);
    t = h.put(t + 0.15, spot);
    const end = Math.max(3.4, Math.ceil((t + 0.2) * 10) / 10);
    const CAM = view ? SIDE_CAM : name === "sticks" ? { pos: [0.5, 1.0, 2.6], look: [0.15, 0.62, 0.4], fov: 36 } : { pos: [-0.75, 1.05, 1.9], look: [0, 0.5, 0.4], fov: 26 };
    write(import.meta.url, { ...BASE, frame: undefined, id: `kvd-grip-${name}${view}`, title: `In-hand proof: ${kind}`, idea: "grip proof", set: { type: "apartment", seed: 5 }, hook: { show: [who, "it"], hint: 0, what: "engine test" },
      cast: [{ id: who, character, at: [0, -0.25], face: 0, expr: "kind", follow: 0.2, seed: 2.6 }],
      props: [{ id: "table", kind: "coffeetable", x: 0, z: 0.5, h: TABLE_H, w: 1.3, d: 0.5 }, spec], captions: c.captions, beats: c.beats([[hold, 0, CAM]], end),
      notes: `kvd-grip proof, still at ${holdAt}` });
    console.log(`node engine/render.mjs storyboards/lab/kvd-grip-${name}${view}.json --stills ${holdAt} --draft`);
  }
}

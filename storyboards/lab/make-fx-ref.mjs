// Effekseer reference reel (8 Nov 2026; engine test, not for posting): each of the seven Effekseer effects the engine
// names (engine/page/vfx.js VFX) played on its own round the Wizard, one at a time on a fixed camera, so each can be
// studied frame by frame and redrawn as a drawn cel (engine/page/fxcel.js, Jonny 8 Nov: "really copying how the effect
// seeker effects look but in handdrawn style"). Variant "cel" puts the drawn copies in the same slots.
//   node storyboards/lab/make-fx-ref.mjs        -> fx-ref-effekseer.json, fx-ref-cel.json
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SLOT = 3, T0 = 0.5;
// FX_ONLY=toon-hit,sparks: leave the other drawn copies out (while they are being built)
const ONLY = process.env.FX_ONLY ? process.env.FX_ONLY.split(",") : null;
// [effect, Effekseer item] per slot; the drawn copy takes the same item as a "cel" of that kind; both start at the slot's start
export const SLOTS = [
  ["toon-hit", { effect: "toon-hit", on: "wiz", offset: [0.35, 0.65, 0.35], scale: 0.32 }],
  ["toon-water", { effect: "toon-water", pos: [0.55, 0, 0.2], scale: 0.12 }],
  ["sparks", { effect: "sparks", pos: [0.3, 1.0, 0], scale: 0.3 }],
  ["light", { effect: "light", on: "wiz", offset: [0, 0, 0], scale: 0.3, dur: 2.4 }],
  ["aura", { effect: "aura", on: "wiz", offset: [0, 0, 0], scale: 0.3, dur: 2.4, follow: true }],
  ["barrier", { effect: "barrier", on: "wiz", offset: [0, 0, 0], scale: 0.2, dur: 2.4, follow: true }],
  ["tornado", { effect: "tornado", on: "wiz", offset: [0, 0, 0], scale: 0.3, dur: 2.4, follow: true }],
];
const dur = T0 + SLOTS.length * SLOT;
const shot = { pos: [0, 1.5, 8.5], look: [0, 1.1, 0], fov: 40 };
function board(variant) {
  const fx = SLOTS.map(([name, v], i) => variant === "effekseer" ? { do: "vfx", at: T0 + i * SLOT, ...v, reason: `reference: Effekseer ${name}` } : { do: "cel", at: T0 + i * SLOT, kind: v.effect, ...Object.fromEntries(Object.entries(v).filter(([k]) => !["effect", "follow", "fade"].includes(k))), reason: `drawn copy of Effekseer ${name}` }).filter((x) => !ONLY || x.do === "vfx" || ONLY.includes(x.kind));
  return {
    id: `fx-ref-${variant}`, title: `Effect reference: ${variant}`, idea: "engine test, not a clip (storyboards/lab/make-fx-ref.mjs)",
    fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, motion: "natural", duration: dur,
    set: { type: "plain", color: "#f3c99a", floor: "#6f6669", light: "golden", para: 0, bloom: "emissive", aperture: 0, focus: false,
      plate: { src: "assets/plates/street-terrace-evening.png", z: -4.5, center: [0.3, 7.55], height: 15, relief: 0.3 }, ink: true, satsuei: true },
    music: false, sound: { auto: false }, hook: { show: ["wiz"], hint: 0, what: "engine test" },
    cast: [{ id: "wiz", character: "lookdev/wizard-crisp", at: [-0.25, 0], face: "camera", expr: "kind", follow: 0.2, seed: 2.6 }],
    props: [],
    captions: SLOTS.map(([name], i) => ({ from: T0 + i * SLOT, to: T0 + (i + 1) * SLOT, text: name, pos: 330, pop: false, kinetic: false })),
    beats: [{ name: "ref", at: 0, len: dur, shot, do: [{ who: "wiz", do: "noblink", at: 0 }] }],
    fx,
    notes: "Generated by storyboards/lab/make-fx-ref.mjs (engine test, not for posting).",
  };
}
for (const v of ["effekseer", "cel"]) {
  const f = path.join(here, `fx-ref-${v}.json`);
  fs.writeFileSync(f, JSON.stringify(board(v), null, 1) + "\n");
  console.log("wrote", path.relative(process.cwd(), f));
}

// Ink lab (8 Nov 2026, X posts review upgrade 1; engine test, not for posting): the coffee run (never has money 02) with
// today's template look (castLook "sheet", lighting 2, cel shadows) and the same with set "ink" (line
// widths in real pixels, a drawn hierarchy, thinner far away); c adds set "satsuei" (the anime grade: halation,
// diffusion glow, lavender shadows, warm highlights). One change per step.
//   node storyboards/lab/make-ink-lab.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "../series/never-has-money/02-coffee-run/coffee-run.json");
const base = JSON.parse(fs.readFileSync(src, "utf8"));
const today = { ...base, set: { ...base.set, cel: { at: 0.25 } }, notes: "Generated by storyboards/lab/make-ink-lab.mjs (ink lab, engine test, not for posting)." };
const V = {
  a: { ...today, id: "ink-lab-a", title: "Ink lab: today's lines" },
  b: { ...today, id: "ink-lab-b", title: "Ink lab: set ink", set: { ...today.set, ink: true } },
  c: { ...today, id: "ink-lab-c", title: "Ink lab: set ink + satsuei", set: { ...today.set, ink: true, satsuei: true } },
};
for (const [k, sb] of Object.entries(V)) {
  const f = path.join(here, `ink-lab-${k}.json`);
  fs.writeFileSync(f, JSON.stringify(sb, null, 1) + "\n");
  console.log("wrote", path.relative(process.cwd(), f));
}

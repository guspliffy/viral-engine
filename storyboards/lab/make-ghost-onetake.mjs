// Quality lab 01, sample for the first test (research prompt v2, part D): Ghost Photo's opening as one continuous
// take instead of its three quick cuts (close on the glowing sheet 0.0, timer insert 0.6, trio 1.2, rise 2.0).
// The take starts on the same close-up and pulls back past the tripod's blinking lamp to the trio by 2.0 s;
// everything else is Ghost Photo as merged.
//   node storyboards/lab/make-ghost-onetake.mjs -> storyboards/lab/ql-ghost-onetake.json
import { readFileSync, writeFileSync } from "node:fs";
const sb = JSON.parse(readFileSync(new URL("../ghostphoto/ghost-photo.json", import.meta.url)));
const [clue, timer, trio] = sb.beats;
if (clue.name !== "clue" || timer.name !== "timer" || trio.name !== "trio") throw new Error("Ghost Photo's opening changed");
const dur = trio.at + trio.len;   // to the reveal's cut
clue.shot = { pos: [0.05, 1.24, 3.7], look: [0, 1.04, 0], fov: 44, to: { pos: [1.1, 1.22, 6.7], look: [0.12, 0.92, 0], fov: 50 }, dur, ease: "inOut" };
delete timer.shot; delete trio.shot;
sb.id = "ql-ghost-onetake"; sb.title = "Quality lab: Ghost Photo opening, one take";
sb.notes = "Generated by storyboards/lab/make-ghost-onetake.mjs from storyboards/ghostphoto/ghost-photo.json.";
writeFileSync(new URL("./ql-ghost-onetake.json", import.meta.url), JSON.stringify(sb, null, 1) + "\n");
console.log(`ql-ghost-onetake: one take 0-${dur.toFixed(2)} s`);

// Pebble voice lab 2 (Jonny 6 Nov 2026 09:49: "A cleaned is good, but could sound a bit more old or wise. Fable cleaned
// is nice too. A mix from Fable's speaking flow and the voice of A cleaned, maybe a bit older"). Two new lines each:
//   1 A cleaned (the reference he liked)                                        voices.json pebble-k1
//   2 Fable's flow, A's voice: the Fable cleaned read converted to A's voice (Chatterbox voice conversion, MIT; it
//     keeps the words, timing and melody of the source and takes the voice of a 10 s Kokoro A clip)
//   3 the same with an older A as the voice (Kokoro daniel 0.4 + santa 0.6, slower)
//   4 3 aged a little more: 7 % slower, a faint 5 Hz tremor, a softer top, no pitch shift
//   5 a plain Kokoro mix of both voices (fable 0.4, daniel 0.3, santa 0.3), longer pauses           pebble-k3
// The converted lines are made outside the engine (out/voice-lab/mix*-N.wav) and play as recorded lines.
//   node storyboards/pebble/make-pebble-voice-mix.mjs -> storyboards/pebble/pebble-voice-mix.json
import { clip, write } from "../lib/clip.mjs";
import * as peb from "./pebble-acting.mjs";

const W = "peb", LINES = ["Slow is not late. Slow is how you notice things.", "The river never hurries, and it still arrives."], GAPS = [6.0, 4.3];
const OPTIONS = [["1", "A cleaned", { voice: "pebble-k1" }], ["2", "Fable's flow, A's voice", { rec: "out/voice-lab/mixA-%.wav" }],
  ["3", "Fable's flow, older A", { rec: "out/voice-lab/mixO-%.wav" }], ["4", "3, a little older still", { rec: "out/voice-lab/mixOld-%.wav" }],
  ["5", "Kokoro mix of A + Fable", { voice: "pebble-k3" }]];
const c = clip({ faces: "strong" }), { A, see } = c, PER = GAPS[0] + GAPS[1] + 0.3, END = 0.3 + OPTIONS.length * PER;
const HOME = [0, -1.15];
const cast = [{ id: W, character: "pebble/pebble", at: HOME, face: 0, expr: "kind", follow: 0.4, seed: 1.3 }];
peb.restArms(c, 0, W, { dur: 0 });
A(0, W, "look", { to: [0, 0], dur: 0, blink: false });
peb.strawHeld(c, 0, W);   // the straw out of his mouth while he talks
OPTIONS.forEach(([n, name, how], i) => {
  const t0 = 0.3 + i * PER;
  c.cap(t0 - 0.2, t0 + PER - 0.25, `${n}: ${name}`, 230, false, { size: 58, kinetic: false });
  LINES.forEach((line, k) => {
    const o = how.rec ? { rec: how.rec.replace("%", String(k + 1)), age: "age-none" } : { voice: how.voice };
    peb.line(c, t0 + (k ? GAPS[0] : 0), W, line, k ? 3.4 : 5.2, { caption: false, ...o });
  });
  peb.calmSmile(c, t0 + PER - 0.6, W);
});
see(0, END, [`${W}.face`], "Pebble saying each voice option");
const MCU = { pos: [0.05, 1.3, 2.75], look: [0.02, 1.12, -1.1], fov: 33 };
const beats = c.beats([["voices", 0, MCU, "hook"]], END);
write(import.meta.url, {
  id: "pebble-voice-mix", title: "Pebble voice lab 2", idea: "Pebble says two new lines in five mixes of A cleaned and Fable (not a clip)", fps: 30, look: "anime-pro", profile: "short", loop: false,
  castLook: "sheet-clean", cleanStart: true, motion: { feet: 2 }, rig: { hand: 2, eyes: 2 },
  sound: { sfx: 0.6, ambience: 0.3, guard: true, surface: "dirt" }, creative: { length: [8, 60], notes: false }, hook: { show: [W], hint: 0, what: "voices" },
  set: { type: "env", env: "meadow-path", shade: "soft", aperture: 0, focus: false, lighting: 2 },
  music: false, cast, props: [], captions: c.captions, beats, visible: c.visible,
  notes: "Generated by storyboards/pebble/make-pebble-voice-mix.mjs (voice lab, no reviews).",
});

// Engine test for the heel-to-toe roll (timeline.js rollAt, "motion": { "feet": 3 }; Jonny 7 Nov 20:19: carry the
// human rig's walk lessons over to Pebble, "maybe he looks more natural then"). One bench written twice, today's
// planted gait (feet 2) and the roll (feet 3), nothing else different, for an old | new side by side at normal and half
// speed. Pebble walks across in profile and stops, turns and walks toward us, turns on the spot and walks away.
// Pure engine test (no reviews).
//   node storyboards/pebble/make-pebble-roll-test.mjs
//   node engine/render.mjs storyboards/pebble/roll/roll-bench-today.json   (and roll-bench-roll)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip } from "../lib/clip.mjs";
import * as peb from "./pebble-acting.mjs";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "roll");
fs.mkdirSync(OUT, { recursive: true });
const c = clip(), { A } = c, W = "peb", END = 12.0;
A(0, W, "turn", { to: "right", dur: 0 });
A(0, W, "noblink");
A(0, W, "look", { to: [0.3, 0], dur: 0, blink: false });
// 1. ACROSS in profile, left to right, and a stop
peb.walk(c, 0.3, W, [0.5, -0.3], 3.2, { steps: 2.3 });
// 2. TURN to us and walk up (the eyes lead each walk and turn)
A(3.95, W, "look", { to: [0, 0], dur: 0.3, blink: false });
A(4.1, W, "turn", { to: "camera", dur: 0.6 });
peb.walk(c, 4.8, W, [0.4, 1.0], 2.2, { steps: 2.3 });
// 3. TURN round on the spot and walk away up the room
A(7.45, W, "look", { to: [-0.4, 0.05], dur: 0.3, blink: false });
A(7.6, W, "turn", { to: 160, dur: 0.9, ease: "inOut" });
peb.walk(c, 8.6, W, [0.1, -0.6], 2.6, { steps: 2.3, rest: false });
const SHOT = { pos: [-0.1, 0.95, 10.5], look: [-0.1, 0.95, 0], fov: 30 };
const cast = [{ id: W, character: "pebble/pebble", at: [-1.0, -0.3], face: "right", expr: "kind", follow: 0.3, seed: 1.3, span: 0 }];
const base = {
  id: "roll-bench", title: "Heel-to-toe roll bench", idea: "Engine test: Pebble's feet, not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false,
  rig: { hand: 2, eyes: 2, hold: 2 }, physics: true,
  set: { type: "livingroom", seed: 5, focus: false, lighting: 2, hatch: { boil: 0.25 } },
  music: false, sound: { sfx: 0.6, ambience: 0.3, surface: "wood" },
  hook: { show: [W], hint: 0, what: "engine test" },
  cast, props: [], captions: [], beats: c.beats([["bench", 0, SHOT]], END), duration: END,
  notes: "Generated by storyboards/pebble/make-pebble-roll-test.mjs (engine test).",
};
const LABELS = [[0, 4.0, "WALK ACROSS + STOP"], [4.0, 7.5, "TURN + WALK TO US"], [7.5, END, "TURN ROUND + WALK AWAY"]];
const MOTION = { overlap: true, timing: true, solve: true };
for (const [v, feet, tag] of [["today", 2, "TODAY: FLAT FEET"], ["roll", 3, "NEW: HEEL TO TOE"]]) {
  const sb = { ...base, id: `roll-bench-${v}`, motion: { feet, ...MOTION, ...(feet === 2 ? { roll: false } : {}) } };
  sb.captions = [{ from: 0, to: END, text: tag, pos: 260, pop: false, kinetic: false }, ...LABELS.map(([from, to, text]) => ({ from, to, text, pos: 1450, pop: false, kinetic: false }))];
  fs.writeFileSync(path.join(OUT, `${sb.id}.json`), JSON.stringify(sb, null, 1) + "\n");
}
console.log(`wrote 2 storyboards to ${OUT}`);

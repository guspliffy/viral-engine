// Pebble own-voice audition (Jonny 6 Nov 2026: "speaking the voice myself and then we edit it to an older voice"; the
// synthetic voices sound metallic): Jonny's phone take of the line, cleaned, then three older versions of it
// (voices.json pebble-own-a/b/c), and option A on his second take. A label above Pebble names each one.
// The takes are not in the repo (out/voice-takes/, Jonny's own voice): copy them there before generating.
//   node storyboards/pebble/make-pebble-own-voice.mjs -> storyboards/pebble/pebble-own-voice.json
import { clip, write } from "../lib/clip.mjs";
import * as peb from "./pebble-acting.mjs";

const W = "peb", LINE = "No rush. The path will wait.", T1 = "out/voice-takes/pebble-no-rush-1.m4a", T2 = "out/voice-takes/pebble-no-rush-2.m4a";
const OPTIONS = [["1", "your take, cleaned", T1, "age-none"], ["2", "older A", T1, "pebble-own-a"], ["3", "older B", T1, "pebble-own-b"],
  ["4", "older C", T1, "pebble-own-c"], ["5", "older A, take 2", T2, "pebble-own-a"]];
const c = clip({ faces: "strong" }), { A, see } = c, GAP = 4.4, END = 0.3 + OPTIONS.length * GAP;
const HOME = [0, -1.15];
const cast = [{ id: W, character: "pebble/pebble", at: HOME, face: 0, expr: "kind", follow: 0.4, seed: 1.3 }];
peb.restArms(c, 0, W, { dur: 0 });
A(0, W, "look", { to: [0, 0], dur: 0, blink: false });
OPTIONS.forEach(([n, name, rec, age], i) => {
  const t = 0.3 + i * GAP;
  peb.line(c, t, W, LINE, 3.4, { rec, age, caption: false });
  c.cap(t - 0.2, t + GAP - 0.25, `${n}: ${name}`, 230, false, { size: 58, kinetic: false });
  if (i % 2) peb.contentBlink(c, t + 3.6, W, { hold: 0.3 }); else peb.calmSmile(c, t + 3.6, W);
});
see(0, END, [`${W}.face`], "Pebble saying each voice option");
const MCU = { pos: [0.05, 1.3, 2.75], look: [0.02, 1.12, -1.1], fov: 33 };
const beats = c.beats([["voices", 0, MCU, "hook"]], END);
write(import.meta.url, {
  id: "pebble-own-voice", title: "Pebble own-voice audition", idea: "Pebble says Jonny's recorded line, plain and aged (not a clip)", fps: 30, look: "anime-pro", profile: "short", loop: false,
  castLook: "sheet-clean", cleanStart: true, motion: { feet: 2 }, rig: { hand: 2, eyes: 2 },
  sound: { sfx: 0.6, ambience: 0.3, guard: true, surface: "dirt" }, creative: { length: [8, 25], notes: false }, hook: { show: [W], hint: 0, what: "voices" },
  set: { type: "env", env: "meadow-path", shade: "soft", aperture: 0, focus: false, lighting: 2 },
  music: false, cast, props: [], captions: c.captions, beats, visible: c.visible,
  notes: "Generated by storyboards/pebble/make-pebble-own-voice.mjs (voice audition, no reviews).",
});

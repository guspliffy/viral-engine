// Pebble turn-around check video (Jonny 6 Nov 2026, 21:12: "a short video of pebble turning around, to check the
// progress and what needs to be done"). Same neutral bench as make-pebble-turnaround.mjs, but moving:
//   1. a smooth 360° turntable (eased in, constant speed, eased out)
//   2. the pack's five views, each turned to and held (labels + the pack's view are overlaid after the render)
//   3. the face close, turning from one three-quarter to the other
//   4. next to a standard potato for size
//   node storyboards/pebble/make-pebble-turn-video.mjs -> storyboards/pebble/pebble-turn-video.json
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { REST } from "./pebble-acting.mjs";

const here = path.dirname(fileURLToPath(import.meta.url)), W = "peb", P = "pot";
const full = { pos: [0, 1.0, 6.2], look: [0, 0.92, 0], fov: 30 }, close = { pos: [0.2, 1.25, 4.4], look: [0.02, 1.12, 0], fov: 27 };
const duo = { pos: [0.62, 1.0, 8.8], look: [0.62, 0.85, 0], fov: 30 };
const a = (at, o, who = W) => ({ who, at, ...o });
// 1. the turntable: 72°/s; the cubic ease-in over 36° in 1.5 s ends at 72°/s, so the speed never jumps
const spin = [a(1.0, { do: "turn", to: 36, dur: 1.5, ease: "in" }),
  ...[108, 180, -108, -36].map((y, i) => a(2.5 + i, { do: "turn", to: y, dur: 1, ease: "linear" })),
  a(6.5, { do: "turn", to: 0, dur: 1.5, ease: "out" })];
// 2. the pack's views in its order: three-quarter (faces screen right), left profile, back, right profile, front
export const HOLDS = [[40, "three-quarter"], [-90, "left profile"], [180, "back"], [90, "right profile"], [0, "front"]];
const STEP = 2.2, T0 = 9.0;
const steps = HOLDS.map(([y], i) => a(T0 + i * STEP, { do: "turn", to: y, dur: 0.7 }));
// 3. the face close, 4. next to a potato
const C0 = T0 + HOLDS.length * STEP - 1.5, D0 = C0 + 3.2, END = D0 + 2.2;
const face = [a(C0 + 0.3, { do: "turn", to: 35, dur: 1.0 }), a(C0 + 1.7, { do: "turn", to: -35, dur: 1.2 }), a(D0, { do: "turn", to: 0, dur: 0 }),
  // the potato waits well off to the side (in profile the shell reaches his sword) and steps in on the cut
  a(D0 - 0.03, { do: "move", to: [1.55, 0], dur: 0.01, ease: "linear", steps: 0 }, P)];
const sb = {
  id: "pebble-turn-video", title: "Pebble turn-around", idea: "Lookdev check video of Pebble (not a clip)", fps: 30, look: "anime-pro", profile: "short", loop: false, duration: END,
  castLook: "sheet-clean", motion: { feet: 2 }, rig: { hand: 2, eyes: 2 },
  set: { type: "plain", color: "#efe6d6", floor: "#d8cbb4", para: 0, aperture: 0, lighting: 2 },
  music: false, sound: { guard: true, surface: "wood", speech: false }, creative: { length: [4, 30], notes: false },
  hook: { show: [W], hint: 0, what: "lookdev" },
  shots: [{ at: 0, ...full }, { at: C0, ...close }, { at: D0, ...duo }],   // hard cuts (a camera path would blend a frame)
  cast: [{ id: W, character: "pebble/pebble", at: [0, 0], face: 0, expr: "kind", follow: 0, seed: 1.1 },
    { id: P, character: "potatobrawl/samurai", at: [3.4, 0], face: 0, expr: "kind", follow: 0, seed: 2.1 }],
  beats: [{ name: "turns", at: 0, len: END, do: [a(0, { do: "look", to: [0, 0], dur: 0, blink: false }), a(0, { do: "noblink" }),
    a(0, { do: "turn", to: 0, dur: 0 }), ...["R", "L"].map((side) => a(0, { do: "arm", side, pose: REST[side], dur: 0 })), ...spin, ...steps, ...face] }],
  notes: "Generated by storyboards/pebble/make-pebble-turn-video.mjs (lookdev check video, no reviews). " +
    `Holds: ${HOLDS.map(([, n], i) => `${n} ${(T0 + i * STEP + 0.7).toFixed(1)}-${(T0 + (i + 1) * STEP).toFixed(1)}`).join(", ")}; face ${C0.toFixed(1)}; potato ${D0.toFixed(1)}.`,
};
fs.writeFileSync(path.join(here, "pebble-turn-video.json"), JSON.stringify(sb, null, 1) + "\n");
console.log(path.join(here, "pebble-turn-video.json"), sb.notes);

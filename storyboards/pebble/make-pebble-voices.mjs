// Pebble voice audition (Jonny 6 Nov 2026: "I would like to give him a voice", real words, never gibberish): Pebble in
// a close shot says the same line in each of the four calm voice recipes (engine/voice/voices.json pebble, pebble-b,
// pebble-c, pebble-d), a label naming the option above him. Jonny picks by ear; the pick becomes his "tts".
//   node storyboards/pebble/make-pebble-voices.mjs -> storyboards/pebble/pebble-voices.json
import { clip, write } from "../lib/clip.mjs";
import * as peb from "./pebble-acting.mjs";

const W = "peb", LINE = "No rush. The path will wait.";
const OPTIONS = [["A", "pebble"], ["B", "pebble-b"], ["C", "pebble-c"], ["D", "pebble-d"]];
const c = clip({ faces: "strong" }), { A, see } = c, GAP = 3.4, END = 0.3 + OPTIONS.length * GAP;
const cast = [{ id: W, character: "pebble/pebble", at: [0, 0.05], face: 0, expr: "kind", follow: 0.4, seed: 1.3 }];
peb.restArms(c, 0, W, { dur: 0 });
A(0, W, "look", { to: [0, 0], dur: 0, blink: false });
OPTIONS.forEach(([name, voice], i) => {
  const t = 0.3 + i * GAP;
  peb.line(c, t, W, LINE, 2.3, { voice, caption: false });
  c.cap(t - 0.2, t + GAP - 0.25, `Voice ${name}: ${LINE}`, 230, false, { size: 58, kinetic: false });
  if (i % 2) peb.contentBlink(c, t + 2.55, W, { hold: 0.3 }); else peb.calmSmile(c, t + 2.55, W);
});
see(0, END, [`${W}.face`], "Pebble saying each voice option");
const MCU = { pos: [0.05, 1.1, 2.6], look: [0.02, 0.86, 0.05], fov: 33 };
const beats = c.beats([["voices", 0, MCU, "hook"]], END);
write(import.meta.url, {
  id: "pebble-voices", title: "Pebble voice audition", idea: "Pebble says one line in four voices (not a clip)", fps: 30, look: "anime-pro", profile: "short", loop: false,
  castLook: "sheet", cleanStart: true, motion: { feet: 2 }, rig: { hand: 2, eyes: 2 },
  sound: { sfx: 0.6, ambience: 0.3, guard: true, surface: "dirt" }, creative: { length: [8, 20], notes: false }, hook: { show: [W], hint: 0, what: "voices" },
  set: { type: "env", env: "meadow-path", shade: "soft", aperture: 0, focus: false, lighting: 2, hatch: { boil: 0.25 } },
  music: false, cast, props: [], captions: c.captions, beats, visible: c.visible,
  notes: "Generated by storyboards/pebble/make-pebble-voices.mjs (voice audition, no reviews).",
});

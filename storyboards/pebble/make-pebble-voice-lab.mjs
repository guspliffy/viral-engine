// Pebble voice lab (Jonny 6 Nov 2026: the synthetic voices beat his own take but sound "super metallic"; try new
// sentences and storytelling voices, compare their soundline with what we want, then use it in our own style).
// Pebble says two new lines in each candidate, a label above him names it:
//   1 voice A as before (Kokoro blend, pitched down 1 semitone: the reference)
//   2 A cleaned (no pitch shift, a storyteller's phrase pauses, warm EQ)      voices.json pebble-k1
//   3 Fable cleaned (one unblended voice, same treatment)                     pebble-k2
//   4 Chatterbox with Pebble's timbre (a newer free model, MIT; reference: voice A cleaned)
//   5 Chatterbox's own built-in voice, slowed to his pace
// The Chatterbox lines are made outside the engine (tools/voice-lab, out/voice-lab/*.wav) and play as recorded lines.
//   node storyboards/pebble/make-pebble-voice-lab.mjs -> storyboards/pebble/pebble-voice-lab.json
import { clip, write } from "../lib/clip.mjs";
import * as peb from "./pebble-acting.mjs";

const W = "peb", LINES = ["The river never hurries, and it still arrives.", "Breathe first. Then decide."];
const OPTIONS = [["1", "voice A as before", { voice: "pebble" }], ["2", "A cleaned", { voice: "pebble-k1" }], ["3", "Fable cleaned", { voice: "pebble-k2" }],
  ["4", "new model, Pebble's sound", { rec: "out/voice-lab/cb-peb-%.wav", age: "age-none" }], ["5", "new model, own voice", { rec: "out/voice-lab/cb-def-%.wav", age: "age-slow" }]];
const c = clip({ faces: "strong" }), { A, see } = c, GAP = 3.9, PER = LINES.length * GAP + 0.4, END = 0.3 + OPTIONS.length * PER;
const HOME = [0, -1.15];
const cast = [{ id: W, character: "pebble/pebble", at: HOME, face: 0, expr: "kind", follow: 0.4, seed: 1.3 }];
peb.restArms(c, 0, W, { dur: 0 });
A(0, W, "look", { to: [0, 0], dur: 0, blink: false });
peb.strawHeld(c, 0, W);   // the straw out of his mouth while he talks
OPTIONS.forEach(([n, name, how], i) => {
  const t0 = 0.3 + i * PER;
  c.cap(t0 - 0.2, t0 + PER - 0.25, `${n}: ${name}`, 230, false, { size: 58, kinetic: false });
  LINES.forEach((line, k) => {
    const o = how.rec ? { rec: how.rec.replace("%", String(k + 1)), age: how.age } : { voice: how.voice };
    peb.line(c, t0 + k * GAP, W, line, 3.0, { caption: false, ...o });
  });
  peb.calmSmile(c, t0 + PER - 0.6, W);
});
see(0, END, [`${W}.face`], "Pebble saying each voice option");
const MCU = { pos: [0.05, 1.3, 2.75], look: [0.02, 1.12, -1.1], fov: 33 };
const beats = c.beats([["voices", 0, MCU, "hook"]], END);
write(import.meta.url, {
  id: "pebble-voice-lab", title: "Pebble voice lab", idea: "Pebble says two new lines in five candidate voices (not a clip)", fps: 30, look: "anime-pro", profile: "short", loop: false,
  castLook: "sheet-clean", cleanStart: true, motion: { feet: 2 }, rig: { hand: 2, eyes: 2 },
  sound: { sfx: 0.6, ambience: 0.3, guard: true, surface: "dirt" }, creative: { length: [8, 60], notes: false }, hook: { show: [W], hint: 0, what: "voices" },
  set: { type: "env", env: "meadow-path", shade: "soft", aperture: 0, focus: false, lighting: 2 },
  music: false, cast, props: [], captions: c.captions, beats, visible: c.visible,
  notes: "Generated by storyboards/pebble/make-pebble-voice-lab.mjs (voice lab, no reviews).",
});

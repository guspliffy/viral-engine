// Move library trial (quality plan item 16): one sneak written twice with the clip template's flags, nothing else
// different. HAND: a sneak acted with today's tools (crouch, tip forward, paws up, slow steps with pauses and looks
// round), as a clip would write it. MOCAP: the CMU "Mickey sneaking walk" (subject 120, take 09) played through
// storyboards/lib/moves. Same character, set, camera, distance and length. Pure engine test.
//   node tools/mocap/make-trial.mjs
//   node engine/render.mjs storyboards/lookdev/moves/sneak-trial-hand.json   (and sneak-trial-mocap)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clip } from "../../storyboards/lib/clip.mjs";
import { play, load } from "../../storyboards/lib/moves/index.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "storyboards/lookdev/moves");
fs.mkdirSync(OUT, { recursive: true });

const RANGE = [1.0, 10.6], END = 9.8, START = [-0.62, -0.18], HEADING = 72;
const CHAR = "duo/phoenix";
const SHOT = { pos: [0.0, 0.85, 7.4], look: [0.0, 0.5, 0], fov: 30 };
const base = (id, tag) => ({
  id, title: "Sneak trial", idea: "Engine test: move library trial (hand-made vs motion capture), not a clip",
  fps: 30, look: "anime-pro", castLook: "sheet", profile: "short", loop: false, cleanStart: true,
  motion: { feet: 2 }, rig: { hand: 2 },
  set: { type: "plain", color: "#efe2c8", floor: "#c9a27a", light: "golden", para: 0, bloom: "emissive",
    plate: { src: "assets/plates/livingroom-golden.png", z: -2.3, center: [0.3, 1.7], height: 6.4 }, aperture: 0 },
  music: false, sound: { sfx: 0.6, ambience: 0.3, guard: true },
  hook: { show: ["phx"], hint: 0, what: "engine test" },
  props: [], duration: END,
  captions: [{ from: 0, to: END, text: tag, pos: 260, pop: false, kinetic: false }],
  notes: "Generated by tools/mocap/make-trial.mjs (engine test).",
});
const cast = (extra = {}) => [{ id: "phx", character: CHAR, at: START, face: HEADING, expr: "kind", seed: 1.7, span: 0, ...extra }];

// MOCAP
{
  const c = clip();
  c.A(0, "phx", "noblink");
  const r = play(c, 0, "phx", "sneak", { from: START, heading: HEADING, char: CHAR, range: RANGE });
  // the face: sly, careful
  c.A(0, "phx", "expr", { expr: "smug", set: { curve: 0.15 }, dur: 0.01 });
  c.A(0, "phx", "face", { lid: 0.35, brow: 0.2, dur: 0.01 });
  const sb = { ...base("sneak-trial-mocap", "MOTION CAPTURE"), cast: cast(), beats: c.beats([["sneak", 0, SHOT]], END) };
  // the gait's own body motion (bob, sway, lean into the walk, the tip on a stop) would double what the capture has
  sb.motion = { feet: 2, feetTune: { body: 0, lean: 0, tip: 0 } };
  fs.writeFileSync(path.join(OUT, `${sb.id}.json`), JSON.stringify(sb, null, 1) + "\n");
  console.log("mocap ends at", r.last);
  var END_AT = r.last.slice(1);
}

// HAND: the same trip, acted by hand with today's tools
{
  const c = clip(), { A } = c;
  A(0, "phx", "noblink");
  A(0, "phx", "expr", { expr: "smug", set: { curve: 0.15 }, dur: 0.01 });
  A(0, "phx", "face", { lid: 0.35, brow: 0.2, dur: 0.01 });
  // paws up; the near (right) one lower so it never covers the face from this side
  const PAWS = { o: [-0.02, 0.62, 0.3] }, PAW_R = { o: [0.05, 0.42, 0.26] };
  // gets into the sneak: crouch, tip forward, paws up
  A(0.3, "phx", "crouch", { to: 0.7, dur: 0.5 });
  A(0.3, "phx", "pitch", { to: 14, dur: 0.5 });
  c.arm(0.3, "phx", "R", PAW_R, 0.45);
  c.arm(0.35, "phx", "L", PAWS, 0.45);
  // five slow steps with a look round between them
  const legs = 5, t0 = 1.0, t1 = 8.4, dx = (END_AT[0] - START[0]) / legs, dz = (END_AT[1] - START[1]) / legs;
  const per = (t1 - t0) / legs;
  for (let i = 0; i < legs; i++) {
    const s = t0 + i * per;
    A(s, "phx", "move", { to: [START[0] + dx * (i + 1), START[1] + dz * (i + 1)], dur: per * 0.62, steps: 1.6 });
    A(s, "phx", "look", { to: [0.1, -0.35], dur: 0.2, blink: false });
    A(s + per * 0.66, "phx", "look", { to: [i % 2 ? 0.7 : -0.7, 0.05], dur: 0.15, blink: false });
    A(s + per * 0.66, "phx", "still", { dur: per * 0.3, idle: 0.1 });
  }
  // stands up at the end
  A(8.6, "phx", "crouch", { to: 0, dur: 0.5 });
  A(8.6, "phx", "pitch", { to: 0, dur: 0.5 });
  c.arm(8.6, "phx", "R", "rest", 0.5);
  c.arm(8.6, "phx", "L", "rest", 0.5);
  A(8.6, "phx", "look", { to: [0, 0], dur: 0.25, blink: false });
  const sb = { ...base("sneak-trial-hand", "HAND-MADE (TODAY)"), cast: cast(), beats: c.beats([["sneak", 0, SHOT]], END) };
  fs.writeFileSync(path.join(OUT, `${sb.id}.json`), JSON.stringify(sb, null, 1) + "\n");
}
console.log(`wrote 2 storyboards to ${OUT} (move: ${load("sneak").source})`);
